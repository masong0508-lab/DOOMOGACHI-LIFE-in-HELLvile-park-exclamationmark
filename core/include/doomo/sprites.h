/* sprites.h - procedural sprites for demons, pickups, projectiles, props
 * and effects (owner: art). Generated at build time by artgen into
 * core/gen/art_data.c like the textures (const, ROM on GBA).
 * Cute vs brutal variants for every death/gore effect: GORE_CUTE turns
 * gibs into confetti, hearts and plush stuffing; GORE_BRUTAL is full Doom.
 */
#ifndef DOOMO_SPRITES_H
#define DOOMO_SPRITES_H

#include "types.h"

enum {
    SPR_NONE = 0,
    /* demons (frames: 0-1 walk, 2 attack, 3 pain, 4-7 death) */
    SPR_IMPLING, SPR_VAPE_WRAITH, SPR_PUFF_DEMON, SPR_HELLHOUND_PUP,
    SPR_BONE_JESTER, SPR_SLIME_BELCHER, SPR_GARGOYLE, SPR_CYBER_PIGGY,
    SPR_BRUTE, SPR_CLOUD_SPIDER, SPR_LORD_VAPULA,
    /* projectiles & effects */
    SPR_FIREBALL, SPR_VAPE_BOLT, SPR_BUBBLE, SPR_GLITTER_SHOT, SPR_PLASMA,
    SPR_ROCKET, SPR_HOLY_SPLASH, SPR_EXPLOSION, SPR_PUFF, SPR_BLOOD_SPRAY,
    SPR_GIBS, SPR_CONFETTI, SPR_HEARTS, SPR_STUFFING, SPR_SPARKLE,
    /* pickups */
    SPR_HEALTH_SMALL, SPR_HEALTH_BIG, SPR_ARMOR, SPR_AMMO_BULLETS,
    SPR_AMMO_SHELLS, SPR_AMMO_CELLS, SPR_AMMO_ROCKETS, SPR_KEY_RED,
    SPR_KEY_BLUE, SPR_SCRAP, SPR_SOUL_ORB, SPR_CANDY,
    /* props */
    SPR_TREE, SPR_FLOWER_BED, SPR_LAMP, SPR_BENCH, SPR_FOUNTAIN, SPR_BARREL,
    SPR_SKULL_PILE, SPR_CORPSE_CUTE, SPR_CORPSE_BRUTAL, SPR_TORCH,
    SPR_SIGN, SPR_MAILBOX, SPR_VAPE_PORTAL, SPR_EGG, SPR_PET,
    SPR_COUNT
};

#define SPR_MAX_FRAMES 8
/* frame is clamped to the sprite's frame count. */
const DoomoImage *sprite_image(int spr_id, int frame);
int  sprite_frames(int spr_id);
void sprites_init(void);

/* ---- extras (art, additive) ---------------------------------------------- */
/* Demon frame layout (SPR_IMPLING .. SPR_LORD_VAPULA). Death frames show
 * the demon recoiling, falling and lying still (X eyes); the gore effect
 * sprites (BLOOD_SPRAY/GIBS vs CONFETTI/HEARTS/STUFFING) are layered on
 * top according to the gore setting, so the frames suit both modes. */
enum { DFRAME_WALK0, DFRAME_WALK1, DFRAME_ATTACK, DFRAME_PAIN,
       DFRAME_DEATH0, DFRAME_DEATH1, DFRAME_DEATH2, DFRAME_DEATH3,
       DFRAME_COUNT };
/* Per-sprite hints for renderers / actors. Every image is centred on its
 * x axis. Ground sprites have their feet on the bottom row; SPRF_CENTERED
 * sprites (projectiles, effects) are symmetric about their centre, so draw
 * them with feet z = centre z - h/2 (in world units). */
enum {
    SPRF_FULLBRIGHT  = 1,   /* glows: draw with BB_FULLBRIGHT              */
    SPRF_FLOATS      = 2,   /* hovers / flies (no ground contact)          */
    SPRF_CENTERED    = 4,   /* image centre = object centre                */
    SPRF_TRANSLUCENT = 8,   /* ghostly vapour: BB_TRANSLUCENT if supported */
    SPRF_LOOP        = 16,  /* idle loop animation (play frames in a loop) */
    SPRF_ONESHOT     = 32   /* effect that plays once then disappears      */
};
int sprite_flags(int spr_id);
const char *sprite_name(int spr_id);         /* "impling", ... ("" if bad) */

/* ---- internal: generated by core/tools/artgen into core/gen/art_data.c -- */
typedef struct DoomoArtFrame {
    uint16_t w, h;
    const uint8_t *pix;
} DoomoArtFrame;
typedef struct DoomoArtSprite {
    uint16_t first;     /* index into doomo_art_frames                    */
    uint8_t  frames;
    uint8_t  flags;     /* SPRF_*                                         */
} DoomoArtSprite;
#define DOOMO_SPR_MAX_IMAGES 224
extern const DoomoArtFrame  doomo_art_frames[];
extern const uint16_t       doomo_art_frame_total;
extern const DoomoArtSprite doomo_art_spr[SPR_COUNT];
extern const char *const    doomo_art_spr_names[SPR_COUNT];

#endif
