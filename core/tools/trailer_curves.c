/* trailer_curves.c - host tool: the trailer's timing curves as a committed
 * golden for the comic-timing tests (owner: S1, docs/design/story/SPEC.md
 * sec.6.1, CT sec.3.2, Appendix B).
 *
 * The trailer (trailer/tk.c, read only) has one elastic curve and one ease:
 *   tk_bounce(t) = 1 - cos(6t) * e^(-4t) * (1 - 0.2t)    (tk.c:470)
 *   tk_ease(t)   = t*t*(3-2t)                            (tk.c:469)
 * Both are reproduced here verbatim, in the same float arithmetic (tk.c
 * itself drags in the trailer's renderer and palette, so it is not linked).
 * The runtime springs (tween.h TW_JELLY..TW_FOLLOW) are exact sampled damped
 * oscillators fitted to the trailer (CT sec.3.2); this tool derives their
 * Q14 coefficients and their exact 64 px step responses in double precision.
 *
 * Host only (floats and libm are fine here, never in core/src). Rebuild the
 * golden after changing a preset:
 *
 *   cc -std=c99 -O2 -o /tmp/trailer_curves core/tools/trailer_curves.c -lm
 *   /tmp/trailer_curves > core/tests/data/trailer_curves.h
 *
 * The output is deterministic (fixed format, no timestamps).
 */
#include <math.h>
#include <stdio.h>
#include <stdlib.h>

static float tk_clampf(float v, float lo, float hi) { return v < lo ? lo : v > hi ? hi : v; }
static float tk_ease(float t) { t = tk_clampf(t, 0, 1); return t * t * (3 - 2 * t); }
static float tk_bounce(float t)
{
    t = tk_clampf(t, 0, 1);
    return 1.0f - cosf(t * 6.0f) * expf(-4.0f * t) * (1.0f - t * 0.2f);
}

/* the presets of CT sec.3.2: period (frames), zeta; same order as tween.h */
static const struct { const char *name; double period, zeta; } presets[] = {
    { "TW_JELLY",  3.8, 0.41  },
    { "TW_SLAM4",  4.2, 0.555 },
    { "TW_SLAM7",  7.3, 0.555 },
    { "TW_SLAM8",  8.4, 0.555 },
    { "TW_BRAKE",  8.4, 0.45  },
    { "TW_BOING", 11.0, 0.71  },
    { "TW_WOBBLE", 8.0, 0.22  },
    { "TW_FOLLOW",24.0, 0.85  },
};
#define NPRE ((int)(sizeof presets / sizeof presets[0]))
#define STEPS 16

static long rnd(double v) { return (long)floor(v + 0.5); }

int main(void)
{
    int i, p, n;
    printf("/* trailer_curves.h - GENERATED by core/tools/trailer_curves.c (do not edit).\n"
           " * The trailer's tk_bounce / tk_ease (trailer/tk.c) and the exact step\n"
           " * responses of the tween.h spring presets (CT sec.3.2), for test_tween.c. */\n"
           "#ifndef DOOMO_TRAILER_CURVES_H\n#define DOOMO_TRAILER_CURVES_H\n\n");

    printf("/* tk_bounce(i / 64) in fix16 (65536 = 1.0), i = 0..64 */\n");
    printf("static const long TC_BOUNCE_FX[65] = {");
    for (i = 0; i <= 64; i++)
        printf("%s%s%ld", i ? "," : "", i % 9 == 0 ? "\n    " : " ", rnd(tk_bounce((float)i / 64.0f) * 65536.0));
    printf("\n};\n\n");

    printf("/* tk_ease(i / 16) in Q8.8, i = 0..16 */\n");
    printf("static const int TC_EASE_Q8[17] = {");
    for (i = 0; i <= 16; i++)
        printf("%s%ld", i ? ", " : " ", rnd(tk_ease((float)i / 16.0f) * 256.0));
    printf(" };\n\n");

    printf("/* Spring presets: Q14 coefficients of e[n+1] = a1*e[n] + a2*e[n-1], c = the\n"
           " * Q14 ratio e[-1]/e[0] of a release from rest (exact first frame, CT 3.2),\n"
           " * and the exact position (Q4, 16 = 1 px) for a 64 px step from rest. */\n");
    printf("#define TC_SPRINGS %d\n#define TC_STEPS %d\n", NPRE, STEPS);
    printf("typedef struct { int a1, a2, c; int pos[TC_STEPS]; } TcSpring;\n");
    printf("static const TcSpring TC_SPRING[TC_SPRINGS] = {\n");
    for (p = 0; p < NPRE; p++) {
        double wd = 2.0 * M_PI / presets[p].period, z = presets[p].zeta;
        double sigma = z * wd / sqrt(1.0 - z * z), r = exp(-sigma);
        double a1 = 2.0 * r * cos(wd), a2 = -r * r;
        double c = (cos(wd) - (sigma / wd) * sin(wd)) / r;
        if (fabs(c) >= 2.0) { fprintf(stderr, "c out of Q14 range\n"); return 1; }
        printf("    /* %-9s period %4.1f zeta %.3f */ { %ld, %ld, %ld, {", presets[p].name,
               presets[p].period, z, rnd(a1 * 16384.0), rnd(a2 * 16384.0), rnd(c * 16384.0));
        for (n = 0; n < STEPS; n++) {
            double e = -1024.0 * pow(r, n) * (cos(wd * n) + (sigma / wd) * sin(wd * n));
            printf("%s%ld", n ? ", " : " ", rnd(1024.0 + e));
        }
        printf(" } },\n");
    }
    printf("};\n\n#endif\n");
    return 0;
}
