/* ulgen.c - the unlock lookup index generator (host tool, owner: foundation; speed package X3).
 *
 *   ulgen --out-root DIR    write DIR/core/gen/unlock_index.c
 *
 * unlock_find(cat, list, index) used to scan every team's unlock table (~700 entries, 16 tables) for each locked
 * option a menu draws, every frame: 13% of the GBA creator, 3.6% of the options screen. The index is the whole
 * registry (unlock_count() / unlock_at()) as a sorted key array, key = cat << 24 | list << 16 | index, with each
 * key's entries in registry order (a stable sort), so a binary search finds the first match exactly as the scan
 * did. It is const (ROM on the GBA); the PS1 leaves it out (its EXE is RAM, and its menus already hold 30 fps).
 *
 * The tool links the native core (core/Makefile `gen`): the registry is the tables as compiled, weak defaults and
 * all. unlocks.c checks the index against the registry once (ul_init) and scans as before when they differ, so a
 * stale index costs speed, never correctness; check-gen fails until `make -C core gen` refreshes it.
 * Deterministic: the same tables give the same bytes. */
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include "doomo/unlocks.h"

typedef struct { uint32_t key; uint16_t at; } Ent;

static int cmp_ent(const void *a, const void *b)
{
    const Ent *x = a, *y = b;
    if (x->key != y->key) return x->key < y->key ? -1 : 1;
    return x->at < y->at ? -1 : x->at > y->at ? 1 : 0;      /* registry order: a stable sort */
}

int main(int argc, char **argv)
{
    const char *out_root = NULL;
    char path[1024];
    FILE *f;
    Ent *e;
    int i, n;
    for (i = 1; i < argc; i++) {
        if (!strcmp(argv[i], "--out-root") && i + 1 < argc) out_root = argv[++i];
        else { fprintf(stderr, "usage: ulgen --out-root DIR\n"); return 2; }
    }
    if (!out_root) { fprintf(stderr, "usage: ulgen --out-root DIR\n"); return 2; }
    n = unlock_count();
    if (n <= 0 || n > 0xFFFF) { fprintf(stderr, "ulgen: %d unlocks?\n", n); return 1; }
    e = calloc((size_t)n, sizeof(*e));
    if (!e) return 1;
    for (i = 0; i < n; i++) {
        const DoomoUnlock *u = unlock_at(i);
        e[i].key = (uint32_t)u->cat << 24 | (uint32_t)u->list << 16 | (uint32_t)u->index;
        e[i].at = (uint16_t)i;
    }
    qsort(e, (size_t)n, sizeof(*e), cmp_ent);
    snprintf(path, sizeof path, "%s/core/gen/unlock_index.c", out_root);
    f = fopen(path, "w");
    if (!f) { fprintf(stderr, "ulgen: cannot write %s\n", path); free(e); return 1; }
    fprintf(f, "/* unlock_index.c - GENERATED by core/tools/ulgen.c (make -C core gen); do not edit.\n"
               " * The unlock registry sorted by key = cat << 24 | list << 16 | index, each key's entries in registry\n"
               " * order, for unlock_find's binary search (unlocks.c checks it against the registry at first use). */\n"
               "#include \"doomo/unlocks.h\"\n\n"
               "#if !defined(DOOMO_PLATFORM_PS1)\n"
               "const uint16_t doomo_ul_index_n = %d;\n\n"
               "const uint32_t doomo_ul_index_key[%d] = {\n", n, n);
    for (i = 0; i < n; i++)
        fprintf(f, "%s0x%08xu,%s", i % 8 ? " " : "    ", (unsigned)e[i].key, (i % 8 == 7 || i == n - 1) ? "\n" : "");
    fprintf(f, "};\n\nconst uint16_t doomo_ul_index_at[%d] = {\n", n);
    for (i = 0; i < n; i++)
        fprintf(f, "%s%u,%s", i % 12 ? " " : "    ", (unsigned)e[i].at, (i % 12 == 11 || i == n - 1) ? "\n" : "");
    fprintf(f, "};\n#endif\n");
    if (fclose(f)) { free(e); return 1; }
    free(e);
    return 0;
}
