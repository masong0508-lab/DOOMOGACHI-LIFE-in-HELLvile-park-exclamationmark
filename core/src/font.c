/* bit c of a row (c = 0 is the leftmost pixel) */
#define FONT_B(r, c) (((r) >> (4 - (c))) & 1)
#define FONT_COL(c, r0, r1, r2, r3, r4, r5, r6, r7) \
    (uint8_t)(FONT_B(r0, c) | FONT_B(r1, c) << 1 | FONT_B(r2, c) << 2 | \
              FONT_B(r3, c) << 3 | FONT_B(r4, c) << 4 | FONT_B(r5, c) << 5 | \
              FONT_B(r6, c) << 6 | FONT_B(r7, c) << 7)
#define FONT_G(r0, r1, r2, r3, r4, r5, r6, r7) { \
    FONT_COL(0, r0, r1, r2, r3, r4, r5, r6, r7), \
    FONT_COL(1, r0, r1, r2, r3, r4, r5, r6, r7), \
    FONT_COL(2, r0, r1, r2, r3, r4, r5, r6, r7), \
    FONT_COL(3, r0, r1, r2, r3, r4, r5, r6, r7), \
    FONT_COL(4, r0, r1, r2, r3, r4, r5, r6, r7) }

