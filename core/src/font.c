/* font.c - the shared 5x8 bitmap font (owner: foundation).
 *
 * A friendly rounded 5x8 face: capitals and digits are 7 rows tall (rows
 * 0-6), lowercase has a 5-row x-height (rows 2-6) and real descenders
 * (g j p q y reach row 7). Glyphs are drawn here as readable row art:
 * every row is a 5-letter identifier made of `o` (empty) and `X` (ink),
 * left to right; FONT_G() turns 8 rows into the column-major bytes the
 * renderers want (bit 0 = top row). 0x80..0x9F are the 32 icon glyphs;
 * 0xA0..0xAF are the Spanish letters (accents, n-tilde, inverted ? and !).
 */
