int font_text_width(const char *s)
{
    int best = 0, cur = 0;
    if (!s) return 0;
    s = lang_tr(s);
    for (; *s; s++) {
        if (*s == '\n') {
            if (cur > best) best = cur;
            cur = 0;
            continue;
        }
        cur += FONT_ADVANCE;
    }
    if (cur > best) best = cur;
    /* the last glyph's 1 px spacing column is not ink */
    return best ? best - 1 : 0;
}
