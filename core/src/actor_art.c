const DoomoImage *actor_art_image(int art, int frame)
{
    if (art < 0 || art >= ART_COUNT) art = 0;
    if (frame < 0) frame = 0;
    frame %= art_defs[art].frames;
    return &art_imgs[art][frame];
}

int actor_art_frames(int art)
{
    return (art >= 0 && art < ART_COUNT) ? art_defs[art].frames : 1;
}
