#!/usr/bin/env python3
"""wp6run.py - build, run and read the WP6 PS1 test program (show/tests/engine/wp6).

    python3 show/tests/engine/wp6/wp6run.py            build + run + sheets (show_out/engine/)
    from wp6run import run_all; res = run_all()       (test_wp6.py)

1. gen_wp6.py writes show/build/test-wp6/gen/wp6_data.c + scenes.json
   (every scene built with showtk.actors from the ART lane's cast).
2. cmake configures show/engine into show/build/test-wp6 with wp6_inject.cmake
   (the driver joins the `show` target; no engine file is touched) and builds.
3. The game's ps1/harness/run.py (read-only) boots the disc and takes the
   frames scenes.json names; the TTY carries the "wp6 ..." measurements.
4. The model sheets and contact sheets are composed from those PS1 frames
   into show_out/engine/<feature>/ (labels and borders are host-drawn; every
   picture pixel is the PS1's).
"""
import json
import os
import re
import shutil
import subprocess
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parents[2] / "tools"))

from showtk import paths  # noqa: E402

BDIR = paths.BUILD / "test-wp6"
GEN = BDIR / "gen"
WORK = paths.SHOW_WORK / "wp6"
OUT = paths.SHOW_OUT / "engine"


def build(jobs=2):
    GEN.mkdir(parents=True, exist_ok=True)
    data_c, meta = GEN / "wp6_data.c", GEN / "scenes.json"
    p = subprocess.run([sys.executable, str(HERE / "gen_wp6.py"), str(data_c), str(meta)],
                       stdout=subprocess.PIPE, stderr=subprocess.STDOUT, text=True)
    if p.returncode:
        raise RuntimeError("gen_wp6.py failed:\n" + p.stdout[-3000:])
    env = paths.env_for_build()
    if not (BDIR / "build.ninja").exists():
        p = subprocess.run(["cmake", "--preset", "ps1-show", "-B", str(BDIR),
                            "-DCMAKE_PROJECT_doomo_show_INCLUDE=" + str(HERE / "wp6_inject.cmake"),
                            "-DWP6_DATA=" + str(data_c)], cwd=str(paths.ENGINE), env=env,
                           stdout=subprocess.PIPE, stderr=subprocess.STDOUT, text=True)
        if p.returncode:
            raise RuntimeError("configure failed:\n" + p.stdout[-3000:])
    p = subprocess.run(["cmake", "--build", str(BDIR), "-j", str(jobs)], cwd=str(paths.ENGINE), env=env,
                       stdout=subprocess.PIPE, stderr=subprocess.STDOUT, text=True)
    if p.returncode:
        lines = [l for l in p.stdout.splitlines() if ": error:" in l or "FAILED" in l or "undefined" in l]
        raise RuntimeError("build failed:\n" + ("\n".join(lines[:20]) or p.stdout[-3000:]))
    return json.loads(meta.read_text())


def harness_script(meta):
    """wait/shot lines for every frame scenes.json wants (frame numbers are absolute)"""
    shots = []
    for s in meta["scenes"]:
        if s["mode"] == "sheet":
            for page in range(s["frames"] // 3):     # each page's last (third) frame
                shots.append((s["start"] + 3 * page + 2, "%s_p%d" % (s["name"], page)))
        for t, name in s["shots"]:
            shots.append((s["start"] + t, name))
    shots.sort()
    lines, now = ["# generated by wp6run.py"], 0
    for f, name in shots:
        if f > now:
            lines.append("wait %d" % (f - now))
            now = f
        lines.append("shot %s" % name)
    end = meta["total"] + 2
    if end > now:
        lines.append("wait %d" % (end - now))
    lines.append("expect-log wp6 done")
    return "\n".join(lines) + "\n", shots


def run(meta, timeout=600):
    out = WORK / "run"
    if out.exists():
        shutil.rmtree(out)
    out.mkdir(parents=True)
    text, shots = harness_script(meta)
    (WORK / "wp6.txt").write_text(text)
    p = subprocess.run([sys.executable, str(paths.GAME_HARNESS), "--cue", str(BDIR / "show.cue"),
                        "--map", str(BDIR / "show.map"), "--script", str(WORK / "wp6.txt"), "--out", str(out),
                        "--timeout", str(timeout)], stdout=subprocess.PIPE, stderr=subprocess.STDOUT, text=True)
    tty = (out / "tty.log").read_text(errors="replace") if (out / "tty.log").exists() else ""
    if p.returncode:
        raise RuntimeError("harness failed (rc %d):\n%s\n--- tty tail ---\n%s" % (p.returncode, p.stdout[-2500:],
                                                                                 tty[-2500:]))
    return tty, out


def kv(line):
    return {k: v for k, v in re.findall(r"(\w+)=(\S+)", line)}


def lines(tty, tag):
    return [kv(l) for l in tty.splitlines() if l.startswith("wp6 " + tag + " ")]


# ---- pictures ---------------------------------------------------------------------
def _img():
    from PIL import Image, ImageDraw
    return Image, ImageDraw


def picture(png, full=False):
    """the 320x180 picture (screen lines 30-209) of a captured frame"""
    Image, _ = _img()
    im = Image.open(png).convert("RGB")
    if im.size != (320, 240):
        im = im.resize((320, 240), Image.NEAREST)
    return im if full else im.crop((0, 30, 320, 210))


def contact(frames, out_png, cols=4, scale=2, title=None):
    """frames: [(png path, caption)] -> one sheet, each tile the 320x180 picture x scale"""
    Image, ImageDraw = _img()
    tw, th, cap = 320 * scale, 180 * scale, 14
    rows = (len(frames) + cols - 1) // cols
    top = 18 if title else 0
    sheet = Image.new("RGB", (cols * tw + (cols + 1) * 4, top + rows * (th + cap) + (rows + 1) * 4), (24, 24, 28))
    d = ImageDraw.Draw(sheet)
    if title:
        d.text((6, 4), title, fill=(230, 230, 230))
    for i, (png, caption) in enumerate(frames):
        x = 4 + (i % cols) * (tw + 4)
        y = top + 4 + (i // cols) * (th + cap + 4)
        sheet.paste(picture(png).resize((tw, th), Image.NEAREST), (x, y))
        d.text((x + 2, y + th + 1), caption, fill=(220, 220, 160))
    out_png.parent.mkdir(parents=True, exist_ok=True)
    sheet.save(out_png)
    return out_png


def model_sheet(tty, rundir, who, out_png, scale=3):
    """compose the PS1-drawn cells of sheet_<who> into one labelled sheet"""
    Image, ImageDraw = _img()
    # the cells were printed in order: sheet_mayor's 7 pages, then sheet_nana's
    pages = {}
    seq = [l for l in tty.splitlines() if l.startswith("wp6 sheet ") or l.startswith("wp6 cell ")]
    cur = None
    for l in seq:
        if l.startswith("wp6 sheet "):
            cur = (l.split()[2], int(kv(l)["page"]))
            pages[cur] = []
        elif cur:
            pages[cur].append(kv(l))
    name = "sheet_" + who
    exprs = ["neutral", "happy", "sad", "angry", "love", "shock", "sleepy", "sick", "possessed", "dead", "talk"]
    vis = "XMCEAOUF"
    busts, figs, chibis, fighters = {}, {}, {}, {}
    for (sn, page), cl in pages.items():
        if sn != name:
            continue
        frame = Image.open(rundir / ("%s_p%d.png" % (name, page))).convert("RGB")
        for c in cl:
            x, y, w, h = int(c["x"]), int(c["y"]), int(c["w"]), int(c["h"])
            tile = frame.crop((x, y, x + w, y + h))
            a, b = int(c["a"]), int(c["b"])
            if c["kind"] == "bust":
                busts[(a, b)] = tile
            elif c["kind"] == "figure":
                figs[(a, b)] = tile
            elif c["kind"] == "chibi":
                chibis[(a, b)] = tile
            else:
                fighters[a] = tile
    s = scale
    lw = 70                              # label column
    bw, bh = 52 * s, 58 * s
    W = lw + 9 * (bw + 2) + 10
    H = 40 + 11 * (bh + 2) + 30 + (84 * s + 20) * 2 + 54 * s * 2 + 100 * s + 120
    sheet = Image.new("RGB", (W, H), (20, 20, 24))
    d = ImageDraw.Draw(sheet)
    d.text((8, 8), "%s - model sheet rendered on the PS1 (show.exe test build), x%d" % (who.upper(), s),
           fill=(240, 240, 240))
    d.text((8, 22), "busts: 11 expressions x 8 visemes (X rest M C E A O U F) + eyes shut", fill=(180, 180, 180))
    y0 = 40
    for j, ch in enumerate(vis + "-"):
        d.text((lw + j * (bw + 2) + bw // 2 - 4, y0 - 12), "shut" if ch == "-" else ch, fill=(250, 220, 120))
    for e in range(11):
        y = y0 + e * (bh + 2)
        d.text((4, y + bh // 2), exprs[e], fill=(200, 200, 200))
        for v in range(8):
            t = busts.get((e, v))
            if t:
                sheet.paste(t.resize((bw, bh), Image.NEAREST), (lw + v * (bw + 2), y))
        t = busts.get((e, -1))
        if t:
            sheet.paste(t.resize((bw, bh), Image.NEAREST), (lw + 8 * (bw + 2), y))
    y = y0 + 11 * (bh + 2) + 16
    d.text((8, y - 12), "figures: 11 expressions + eyes shut", fill=(180, 180, 180))
    fw, fh = 52 * s, 84 * s
    k = 0
    for (a, b), t in sorted(figs.items(), key=lambda kv_: (kv_[0][1], kv_[0][0])):
        xx = lw + (k % 6) * (fw + 4)
        yy = y + (k // 6) * (fh + 18)
        sheet.paste(t.resize((fw, fh), Image.NEAREST), (xx, yy))
        d.text((xx + 2, yy + fh + 2), exprs[a] + (" shut" if b else ""), fill=(200, 200, 200))
        k += 1
    y += 2 * (fh + 18) + 16
    d.text((8, y - 12), "chibi: 4 dirs x 4 walk frames, mouth open per dir; fighter: 5 views (x2)",
           fill=(180, 180, 180))
    cw, chh = 30 * s, 52 * s
    k = 0
    for (a, b), t in sorted(chibis.items()):
        xx = lw + (k % 10) * (cw + 4)
        yy = y + (k // 10) * (chh + 4)
        sheet.paste(t.resize((cw, chh), Image.NEAREST), (xx, yy))
        k += 1
    y += 2 * (chh + 4) + 8
    for a, t in sorted(fighters.items()):
        sheet.paste(t.resize((60 * s // 2 * 2, 100 * s // 2 * 2), Image.NEAREST), (lw + a * (60 * s + 6), y))
    out_png.parent.mkdir(parents=True, exist_ok=True)
    sheet.save(out_png)
    return out_png, len(busts), len(figs), len(chibis), len(fighters)


def run_all(jobs=2):
    meta = build(jobs)
    tty, rundir = run(meta)
    (WORK / "tty.log").write_text(tty)
    return meta, tty, rundir


if __name__ == "__main__":
    meta, tty, rundir = run_all()
    print("ran %d frames; tty %d lines; frames in %s" % (meta["total"], len(tty.splitlines()), rundir))
