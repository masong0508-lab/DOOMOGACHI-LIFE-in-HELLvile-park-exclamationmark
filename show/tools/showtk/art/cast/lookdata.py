class Look:
    def __init__(self, lid, where):
        self.id = lid
        self.where = where
        self.base = None
        self.age = None
        self.tags = []
        self.note = ""
        self.over = []          # [(key, raw, where)]
        self.values = None      # {look key: int}, after resolve()

    def pack(self):
        cat = catalog()
        by_struct = {FIELDS[k][0]: v for k, v in self.values.items()}
        return bytes(by_struct[f] for f in cat.look_order)


class KSet:
    def __init__(self, kid, where):
        self.id = kid
        self.where = where
        self.age = None
        self.note = ""
        self.register = "pixel" # the register its shots draw it in (crayon = storybook)
        self.members = []       # ('roster', N) | ('look', id) | ('gen', seed, hell, species)


class Char:
    def __init__(self, cid, where):
        self.id = cid
        self.where = where
        self.opts = {}
        self.over = []
        self.look = None        # resolved Look (portrait cast) or None (sprite cast)


def species_default(species_name, where):
    """a plain look of one species with the roster builder's coherent defaults"""
    sys.path.insert(0, os.path.join(ROOT, "tools"))
    import roster_build as rb
    schema = rb.Schema(rb.Contract())
    short = species_name[len("SPECIES_"):]
    if short not in schema.enums["species"]:
        raise LookError(where, "base=%s: not a SPECIES_* value" % species_name)
    d = schema.defaults(short, False)
    d["species"] = schema.enums["species"][short]
    return {k: d[k] for k in rb.LOOK_ORDER}


class Bible:
    """Everything in series/cast.shw and series/looks/*.shw, resolved."""

    def __init__(self, series=SERIES):
        self.series = series
        self.looks = {}
        self.ksets = {}
        self.chars = {}
        self.order = []
        self.errors = []
        looks_dir = os.path.join(series, "looks")
        files = sorted(os.path.join(looks_dir, f) for f in os.listdir(looks_dir)
                       if f.endswith(".shw")) if os.path.isdir(looks_dir) else []
        for p in files:
            self._load_looks(p)
        cast = os.path.join(series, "cast.shw")
        if os.path.exists(cast):
            self._load_cast(cast)
        for lid in list(self.looks):
            self._try(self.resolve_look, lid, ())
        for c in self.chars.values():
            self._try(self._resolve_char, c)
        for k in self.ksets.values():
            self._try(self._check_kset, k)

    def _try(self, fn, *a):
        try:
            return fn(*a)
        except LookError as e:
            self.errors.append(str(e))
            return None

    # -- loading --------------------------------------------------------------
    def _load_looks(self, path):
        try:
            stmts = parse_file(path)
        except LookError as e:
            self.errors.append(str(e))
            return
        for st in stmts:
            if st.kw == "look":
                if len(st.words) != 1:
                    self.errors.append("%s: `look <id> ...`" % st.where)
                    continue
                lk = Look(st.words[0], st.where)
                if lk.id in self.looks:
                    self.errors.append("%s: look %s already defined at %s" % (st.where, lk.id, self.looks[lk.id].where))
                    continue
                for k, v, w in st.kv:
                    if k == "base":
                        lk.base = (v, w)
                    elif k == "age":
                        lk.age = v
                    elif k == "tags":
                        lk.tags = v.split(",")
                    elif k == "note":
                        lk.note = v
                    else:
                        lk.over.append((k, v, w))
                for inner in st.body:
                    self.errors.append("%s: only key=value lines go inside a look block" % inner.where)
                self.looks[lk.id] = lk
            elif st.kw == "kset":
                if len(st.words) != 1:
                    self.errors.append("%s: `kset <id> ...`" % st.where)
                    continue
                ks = KSet(st.words[0], st.where)
                for k, v, w in st.kv:
                    if k == "age":
                        ks.age = v
                    elif k == "note":
                        ks.note = v
                    elif k == "register":
                        if v not in REGISTERS:
                            self.errors.append("%s: register=%s" % (w, "|".join(REGISTERS)))
                        ks.register = v
                    elif k == "looks":
                        for part in v.split(","):
                            self._try(self._kset_member, ks, part, w)
                    elif k == "gen":
                        m = re.match(r"^(\d+)\.\.(\d+)$", v)
                        if not m:
                            self.errors.append("%s: gen=<seed>..<seed>" % w)
                            continue
                        hell = st.get("hell", "0") == "1"
                        sp = st.get("species")
                        for s in range(int(m.group(1)), int(m.group(2)) + 1):
                            ks.members.append(("gen", s, hell, sp))
                    elif k in ("hell", "species"):
                        pass
                    else:
                        self.errors.append("%s: unknown kset key %r" % (w, k))
                if ks.id in self.ksets:
                    self.errors.append("%s: kset %s already defined" % (st.where, ks.id))
                self.ksets[ks.id] = ks
            else:
                self.errors.append("%s: looks/*.shw holds `look` and `kset` blocks (got `%s`)" % (st.where, st.kw))

    @staticmethod
    def _kset_member(ks, part, where):
        part = part.strip()
        m = re.match(r"^roster:(\d+)(?:\.\.(\d+))?$", part)
        if m:
            a = int(m.group(1))
            b = int(m.group(2)) if m.group(2) else a
            for i in range(a, b + 1):
                ks.members.append(("roster", i))
            return
        m = re.match(r"^(?:look|show):([\w-]+)$", part)
        if m:
            ks.members.append(("look", m.group(1)))
            return
        raise LookError(where, "kset member %r: roster:<N>[..<M>] or look:<id>" % part)

    def _load_cast(self, path):
        try:
            stmts = parse_file(path)
        except LookError as e:
            self.errors.append(str(e))
            return
        for st in stmts:
            if st.kw != "char":
                self.errors.append("%s: cast.shw holds `char` statements (got `%s`)" % (st.where, st.kw))
                continue
            if len(st.words) != 1:
                self.errors.append("%s: `char <id> ...`" % st.where)
                continue
            c = Char(st.words[0], st.where)
            if c.id in self.chars:
                self.errors.append("%s: char %s already defined at %s" % (st.where, c.id, self.chars[c.id].where))
                continue
            for k, v, w in st.kv:
                if field_key(k) in FIELDS:
                    c.over.append((k, v, w))
                else:
                    c.opts[k] = (v, w)
            self.chars[c.id] = c
            self.order.append(c.id)

    # -- resolving --------------------------------------------------------------
    def resolve_look(self, lid, chain):
        lk = self.looks.get(lid)
        if lk is None:
            raise LookError(chain[-1] if chain else "series/looks", "no look %r" % lid)
        if lk.values is not None:
            return lk
        if lid in chain:
            raise LookError(lk.where, "look base cycle: %s" % " -> ".join(chain + (lid,)))
        if lk.base is None:
            raise LookError(lk.where, "look %s needs base=roster:<N>, base=look:<id> or base=SPECIES_*" % lid)
        v, w = lk.base
        vals = self.base_values(v, w, chain + (lid,))
        for k, raw, where in lk.over:
            vals[field_key(k)] = parse_value(k, raw, where)
        if lk.age is None:
            m = re.match(r"^roster:(\d+)$", v)
            if m:
                lk.age = roster_age(int(m.group(1)))
            elif v.startswith(("look:", "show:")):
                lk.age = self.looks[v.split(":", 1)[1]].age
        lk.values = vals
        if lk.age not in AGES:
            raise LookError(lk.where, "look %s: age=adult|teen|child is required (STD-AGE)" % lid)
        if lk.age == "child":
            probs = kid_problems(vals)
            if probs:
                raise LookError(lk.where, "look %s is a child's look but %s (hard limit 3)" % (lid, "; ".join(probs)))
        return lk

    def base_values(self, v, where, chain=()):
        m = re.match(r"^roster:(\d+)$", v)
        if m:
            rid = int(m.group(1))
            if rid not in roster():
                raise LookError(where, "no roster citizen %d" % rid)
            return dict(roster()[rid][1])
        m = re.match(r"^(?:look|show):([\w-]+)$", v)
        if m:
            return dict(self.resolve_look(m.group(1), chain).values)
        if v.startswith("SPECIES_"):
            return species_default(v, where)
        raise LookError(where, "base=%s: roster:<N>, look:<id> or SPECIES_*" % v)

    def _resolve_char(self, c):
        o = c.opts
        age = o.get("age", (None, c.where))
        if age[0] not in AGES:
            raise LookError(c.where, "char %s: age=adult|teen|child is required (STD-AGE)" % c.id)
        kinds = o.get("kinds", ("", c.where))[0].split(",") if "kinds" in o else []
        for k in kinds:
            if k not in KINDS:
                raise LookError(o["kinds"][1], "char %s: unknown kind %r (%s)" % (c.id, k, ",".join(KINDS)))
        if "state" in o and o["state"][0] not in STATES:
            raise LookError(o["state"][1], "char %s: state=%s" % (c.id, "|".join(STATES)))
        if "idle" in o and o["idle"][0] not in IDLES:
            raise LookError(o["idle"][1], "char %s: idle=%s" % (c.id, "|".join(IDLES)))
        if "register" in o and o["register"][0] not in REGISTERS:
            raise LookError(o["register"][1], "char %s: register=%s" % (c.id, "|".join(REGISTERS)))
        if "squash" in o and not re.match(r"^[a-z]+:\d+$", o["squash"][0]):
            raise LookError(o["squash"][1], "char %s: squash=<material>:<pct>" % c.id)
        if "phase" in o and not (o["phase"][0].isdigit() and int(o["phase"][0]) < 256):
            raise LookError(o["phase"][1], "char %s: phase=0..255" % c.id)
        tags = o.get("tags", ("", c.where))[0].split(",") if "tags" in o else []
        if age[0] == "child" and "KID" not in tags:
            raise LookError(c.where, "char %s: age=child needs tags=KID (hard limit 3)" % c.id)
        if "KID" in tags and age[0] != "child":
            raise LookError(c.where, "char %s: tags=KID needs age=child" % c.id)
        if age[0] == "child" and "state" in o and o["state"][0] != "normal":
            raise LookError(o["state"][1], "char %s: a child is never %s (canon; hard limit 3)" % (c.id, o["state"][0]))
        if "first" in o and not re.match(r"^ep\d{3}$", o["first"][0]):
            raise LookError(o["first"][1], "char %s: first=ep<NNN>" % c.id)
        if "sprite" in o:
            if c.over or "look" in o:
                raise LookError(c.where, "char %s: a sprite cast member has no DoomoLook" % c.id)
            return
        if "look" not in o:
            if "VOICE_ONLY" in tags and not kinds:
                return
            raise LookError(c.where, "char %s: look=roster:<N> | look:<id> (or sprite=..., "
                                     "or tags=VOICE_ONLY with no kinds)" % c.id)
        v, w = o["look"]
        if v.startswith(("look:", "show:")):
            base = self.resolve_look(v.split(":", 1)[1], (w,))
            vals = dict(base.values)
        else:
            vals = self.base_values(v, w)
        for k, raw, where in c.over:
            vals[field_key(k)] = parse_value(k, raw, where)
        lk = Look(c.id, c.where)
        lk.values = vals
        lk.age = age[0]
        if lk.age == "child":
            probs = kid_problems(vals)
            if probs:
                raise LookError(c.where, "char %s is a child but %s (hard limit 3)" % (c.id, "; ".join(probs)))
        c.look = lk

    def _check_kset(self, ks):
        if ks.age not in AGES:
            raise LookError(ks.where, "kset %s: age=adult|teen|child is required (STD-AGE)" % ks.id)
        if not 1 <= len(ks.members) <= KSET_MAX:
            raise LookError(ks.where, "kset %s: %d looks (K is 1..%d, sec.8.5)" % (ks.id, len(ks.members), KSET_MAX))
        for m in ks.members:
            if m[0] == "roster":
                if m[1] not in roster():
                    raise LookError(ks.where, "kset %s: no roster citizen %d" % (ks.id, m[1]))
                ra = roster_age(m[1])
                if ra != ks.age:
                    raise LookError(ks.where, "kset %s (age=%s): roster %d %s is %s" %
                                    (ks.id, ks.age, m[1], roster()[m[1]][0], ra))
                if ra == "child":
                    probs = kid_problems(roster()[m[1]][1])
                    if probs:
                        raise LookError(ks.where, "kset %s: roster kid %d %s: %s (hard limit 3)" %
                                        (ks.id, m[1], roster()[m[1]][0], "; ".join(probs)))
            elif m[0] == "look":
                lk = self.resolve_look(m[1], (ks.where,))
                if lk.age != ks.age:
                    raise LookError(ks.where, "kset %s (age=%s): look %s is %s" % (ks.id, ks.age, m[1], lk.age))

    def kset_looks(self, kid):
        """[(label, 48-byte look)] of a kset; generated members run the game's
        own resident_randomize_look() through the native host"""
        ks = self.ksets[kid]
        out, gens = [], []
        for m in ks.members:
            if m[0] == "roster":
                vals = roster()[m[1]][1]
                lk = Look("r%d" % m[1], ks.where)
                lk.values = dict(vals)
                out.append(("%d %s" % (m[1], roster()[m[1]][0]), lk.pack()))
            elif m[0] == "look":
                out.append((m[1], self.looks[m[1]].pack()))
            else:
                gens.append((len(out), m))
                out.append(None)
        if gens:
            from . import host
            byhell = {}
            for idx, m in gens:
                byhell.setdefault(m[2], []).append((idx, m))
            for hell, items in byhell.items():
                looks = host.generate([m[1] for _i, m in items], hell)
                for (idx, m), lb in zip(items, looks):
                    lb = bytearray(lb)
                    if m[3]:
                        lb[0] = catalog().value(m[3])
                    out[idx] = ("seed %d" % m[1], bytes(lb))
        return out

    def char_look_bytes(self, cid):
        c = self.chars[cid]
        return c.look.pack() if c.look else None


# ----------------------------------------------------------------------------
# hard limit 3: a child's look is designed as a kid's
# ----------------------------------------------------------------------------
def kid_problems(v):
    """Reasons a look cannot be a child's (empty list = fine)."""
    cat = catalog()
    E = lambda p, n: cat.value(p + n)  # noqa: E731
    out = []
    if v["height"] > 4:
        out.append("height %d > 4 (kids are the smallest in town)" % v["height"])
    if v["body"] not in (E("BODY_", "TINY"), E("BODY_", "ROUND"), E("BODY_", "AVERAGE")):
        out.append("body must be BODY_TINY, BODY_ROUND or BODY_AVERAGE")
    if v["facial_hair"] != E("FHAIR_", "NONE"):
        out.append("facial hair")
    bad_tops = ("CROP_TOP", "TANK", "LEATHER_JACKET", "NURSE", "MAID", "PRIEST", "SUIT", "LAB_COAT",
                "ARMOR", "PLATE_ARMOR", "HAZMAT")
    if v["top"] in [E("TOP_", t) for t in bad_tops]:
        out.append("an adult-coded top (%s)" % value_name("top", v["top"]))
    if v["shoes"] in (E("SHOES_", "HEELS"), E("SHOES_", "PLATFORM")):
        out.append("heels or platforms")
    if v["mouth"] in (E("MOUTH_", "LIPSTICK"), E("MOUTH_", "TONGUE"), E("MOUTH_", "DROOL"), E("MOUTH_", "SHARK")):
        out.append("an adult-coded mouth (%s)" % value_name("mouth", v["mouth"]))
    if v["marking"] in (E("MARK_", "EYELINER"), E("MARK_", "TEARS"), E("MARK_", "SKULL_PAINT"),
                        E("MARK_", "PENTAGRAM"), E("MARK_", "TRIBAL")):
        out.append("an adult-coded marking (%s)" % value_name("marking", v["marking"]))
    if v["cheeks"] & (E("CHEEK_", "BEAUTY_MARK") | E("CHEEK_", "TEAR_TATTOO") | E("CHEEK_", "SCAR")):
        out.append("a beauty mark, tear tattoo or scar")
    if v["accessory"] in (E("ACC_", "CHAINS"), E("ACC_", "GAS_MASK"), E("ACC_", "SKULL_NECKLACE"),
                          E("ACC_", "NOSE_RING"), E("ACC_", "EARRINGS")):
        out.append("an adult-coded accessory (%s)" % value_name("accessory", v["accessory"]))
    if v["aura"] in (E("AURA_", "FLAMES"), E("AURA_", "FLIES"), E("AURA_", "HEARTS"), E("AURA_", "SMOKE"),
                     E("AURA_", "GLITCH")):
        out.append("an aura a kid never carries (%s)" % value_name("aura", v["aura"]))
    if v["eyes"] in (E("EYE_", "LASHES"), E("EYE_", "DEMON_SLIT"), E("EYE_", "VOID"), E("EYE_", "HOLLOW"),
                     E("EYE_", "X"), E("EYE_", "GLOW")):
        out.append("adult or creepy eyes (%s)" % value_name("eyes", v["eyes"]))
    return out


def dump_look(values):
    """canonical `key=VALUE` text of a look, in DoomoLook order"""
    order = sorted(FIELDS, key=lambda k: catalog().look_order.index(FIELDS[k][0]))
    return " ".join("%s=%s" % (k, value_name(k, values[k])) for k in order)


