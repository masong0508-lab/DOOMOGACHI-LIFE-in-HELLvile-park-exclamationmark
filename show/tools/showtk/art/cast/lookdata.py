SERIES = os.path.join(ROOT, "show", "series")
AGES = ("adult", "teen", "child")
KINDS = ("bust", "figure", "chibi", "fighter", "model3d", "sprite")
STATES = ("possessed", "ghost", "dead", "normal")
IDLES = ("on", "still", "frozen", "none")
REGISTERS = ("pixel", "crayon", "sepia")
KSET_MAX = 48


class LookError(Exception):
    def __init__(self, where, msg):
        Exception.__init__(self, "%s: %s" % (where, msg))
        self.where = where
        self.msg = msg


# ----------------------------------------------------------------------------
# lexing
# ----------------------------------------------------------------------------
TOKEN = re.compile(r'([A-Za-z_][\w.]*)=("(?:[^"\\]|\\.)*"|\S+)|"((?:[^"\\]|\\.)*)"|(\S+)')


def strip_comment(line):
    out, q = [], False
    for i, ch in enumerate(line):
        if ch == '"' and (i == 0 or line[i - 1] != "\\"):
            q = not q
        if ch == "#" and not q:
            break
        out.append(ch)
    return "".join(out)


def tokens(text):
    """[(kind, a, b)]: ('kv', key, value) | ('str', s, None) | ('word', w, None)"""
    out = []
    for m in TOKEN.finditer(text):
        if m.group(1):
            v = m.group(2)
            if v.startswith('"'):
                v = v[1:-1].replace('\\"', '"')
            out.append(("kv", m.group(1), v))
        elif m.group(3) is not None:
            out.append(("str", m.group(3).replace('\\"', '"'), None))
        else:
            out.append(("word", m.group(4), None))
    return out


class Stmt:
    """One statement: a keyword, its words, its key=value pairs (ordered),
    and for blocks the statements inside."""

    def __init__(self, where, toks):
        self.where = where
        self.kw = toks[0][1]
        self.words = [t[1] for t in toks[1:] if t[0] in ("word", "str")]
        self.kv = []
        for t in toks[1:]:
            if t[0] == "kv":
                self.kv.append((t[1], t[2], where))
        self.body = []
        self.raw = None

    def add(self, toks, where):
        for t in toks:
            if t[0] == "kv":
                self.kv.append((t[1], t[2], where))
            else:
                raise LookError(where, "a continuation line holds key=value pairs only (got %r)" % t[1])

    def get(self, key, default=None):
        for k, v, _w in self.kv:
            if k == key:
                return v
        return default


BLOCKS = ("look", "kset", "macro", "set", "shot", "crowd")


def parse_file(path, keep_raw_blocks=("macro",)):
    """Statements of one .shw file.  Blocks keep their inner statements in
    .body; blocks named in keep_raw_blocks keep raw (where, text) lines."""
    rel = os.path.relpath(path, ROOT)
    top, stack = [], []
    with open(path, encoding="utf-8") as f:
        lines = f.read().split("\n")
    last = None
    for ln, raw in enumerate(lines, 1):
        where = "%s:%d" % (rel, ln)
        text = strip_comment(raw).strip()
        if not text:
            continue
        if stack and stack[-1].kw in keep_raw_blocks:
            if text == "end":
                stack.pop()
                last = None
            else:
                stack[-1].raw.append((where, text))
            continue
        toks = tokens(text)
        if toks[0][0] == "kv":
            if last is None:
                raise LookError(where, "key=value line with no statement to continue")
            last.add(toks, where)
            continue
        if toks[0][1] == "end":
            if not stack:
                raise LookError(where, "`end` with no open block")
            stack.pop()
            last = None
            continue
        st = Stmt(where, toks)
        (stack[-1].body if stack else top).append(st)
        last = st
        if st.kw in BLOCKS:
            if st.kw in keep_raw_blocks:
                st.raw = []
            stack.append(st)
    if stack:
        raise LookError(stack[-1].where, "block `%s` has no `end`" % stack[-1].kw)
    return top


# ----------------------------------------------------------------------------
# values
# ----------------------------------------------------------------------------
def field_key(key):
    return ALIASES.get(key, key)


def parse_value(key, raw, where):
    cat = catalog()
    k = field_key(key)
    if k not in FIELDS:
        raise LookError(where, "unknown look key %r" % key)
    _struct, kind, arg = FIELDS[k]
    if kind == "enum":
        table = cat.enum(arg)
        if raw not in table:
            hint = ""
            if (arg + raw) in table:
                hint = " (write %s%s: engine constants use the repo's own names)" % (arg, raw)
            raise LookError(where, "%s=%s: not a %s* value%s" % (key, raw, arg, hint))
        return table[raw]
    if kind == "int":
        if not re.match(r"^\d+$", raw):
            raise LookError(where, "%s=%s: not a number" % (key, raw))
        n = int(raw)
        if not arg[0] <= n <= arg[1]:
            raise LookError(where, "%s=%s: out of range %d..%d" % (key, raw, arg[0], arg[1]))
        return n
    if kind in ("paint", "paint_or_none"):
        if kind == "paint_or_none" and raw == "NONE":
            return LOOK_NO_COLOR
        p = cat.paints()
        if raw not in p:
            raise LookError(where, "%s=%s: not a PAINT_* colour" % (key, raw))
        return p[raw]
    if kind == "skin":
        if raw in cat.skins():
            return cat.skins()[raw]
        if raw in cat.paints():
            return 8 + cat.paints()[raw]
        raise LookError(where, "skin=%s: not a SKIN_* tone or PAINT_* colour" % raw)
    if kind == "cheeks":
        if raw in ("CHEEK_NONE", "NONE"):
            return 0
        bits = 0
        flags = cat.enum("CHEEK_")
        for part in raw.split(","):
            if part not in flags:
                raise LookError(where, "cheeks=%s: %s is not a CHEEK_* flag" % (raw, part))
            bits |= flags[part]
        return bits
    raise LookError(where, "internal: kind %s" % kind)


def value_name(key, v):
    """the canonical text of a look value (for dumps and diffs)"""
    cat = catalog()
    _s, kind, arg = FIELDS[key]
    if kind == "enum":
        return cat.name_of(arg, v)
    if kind == "int":
        return str(v)
    if kind in ("paint", "paint_or_none"):
        if v == LOOK_NO_COLOR:
            return "NONE"
        return cat.name_of("PAINT_", v)
    if kind == "skin":
        return cat.name_of("SKIN_", v) if v < 8 else cat.name_of("PAINT_", v - 8)
    if kind == "cheeks":
        if not v:
            return "CHEEK_NONE"
        return ",".join(n for n, b in sorted(cat.enum("CHEEK_").items(), key=lambda x: x[1]) if v & b)
    return str(v)


