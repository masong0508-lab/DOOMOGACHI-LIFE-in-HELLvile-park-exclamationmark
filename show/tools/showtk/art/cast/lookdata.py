"""showtk.art.cast.lookdata - the cast as data: show/series/cast.shw and
show/series/looks/*.shw (ART track; SHOW_ENGINE_SPEC.md sec.5.1, 5.2, 9.1).

THE FORMAT (the spec's lexical rules, sec.5.2, plus the cast statements)

  * One statement per line; `#` starts a comment outside quotes; indentation
    is ignored.  A line whose first token is `key=value` CONTINUES the
    previous statement (the sec.9.1 excerpt writes `char mayor ...` over two
    lines that way).  A block (`look`, `kset`, `macro`) ends at `end`.
  * Engine constants are the repo's own names: SPECIES_CHERUB, EYE_BUTTON,
    MOUTH_BIG_GRIN, PAINT_ROSE, SKIN_PEACH, CHEEK_BLUSH, EXPR_HAPPY, ...
    They are checked against the game's headers (showtk.art.cast.catalog).
  * Look keys are the roster text's keys (docs/ROSTER.md), which the spec's
    cast excerpt already uses: species body height build skin head head_size
    eyes eye_color eye_size eye_spacing eye_height eye_tilt eye_count brows
    brow_height nose nose_size mouth mouth_size fangs hair hair_color
    highlight facial_hair ears horns horn_color horn_size tail wings halo
    marking marking_color cheeks top top_color bottom bottom_color shoes
    shoes_color hat hat_color accessory accessory_color aura pattern
    pattern_color.  The DoomoLook struct spellings (eye_style, hair_style,
    head_shape, ...) are accepted as aliases.  cheeks= takes CHEEK_* flags
    joined by `,` (or CHEEK_NONE); highlight= takes a PAINT_* or NONE; skin=
    takes SKIN_* (natural tone 0-7) or PAINT_* (8 + paint).

  looks/*.shw
      look <id> [base=roster:<N> | base=look:<id> | base=<SPECIES_*>] [age=adult|teen|child]
                [tags=A,B] [note="..."]
        <key>=<value> ...                      # any number of lines
      end
      kset <id> age=adult|teen|child [register=pixel|crayon] [note="..."]
        looks=roster:<N>,<N>..<M>,look:<id>,... # K looks (K <= 48) for crowds
        gen=<seed>..<seed> [hell=1] [species=SPECIES_*] # or generated by the
      end                                      # game's resident_randomize_look()

  cast.shw
      char <id> look=roster:<N>|look:<id> age=adult|teen|child
                kinds=bust,figure,chibi[,fighter,model3d,sprite]
                [voice=<voice id>|none] [tags=KID,SILENT,...] [squash=<material>:<pct>]
                [phase=<0..255>] [idle=on|still|none] [state=possessed|ghost|dead]
                [name="..."] [roster=<N>] [first=ep<NNN>] [register=pixel|crayon|sepia] [note="..."]
                [<look key>=<value> ...]       # last-minute overrides on the look
      char <id> sprite=<SPR_*|pet:<form>> ...  # cast drawn by the game's sprite
                                               # or pet engines, not portrait.c

  `look=show:<id>` (the spec's sec.9.1 spelling) is the same as look:<id>.

What a resolved look is: 48 bytes in DoomoLook order (resident.h), which is
exactly what the LOOK chunk carries to the PS1 (sec.7.3) and what
show_cast.c writes into doomo_town.res[].look.

KID LOOKS (hard limit 3): a look or char with age=child is checked by
kid_problems(): kid-designed proportions, nothing adult-coded, nothing
sexualised.  It is an error, never a waiver.
"""
