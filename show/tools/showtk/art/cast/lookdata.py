_ROSTER = None


def roster():
    """{id: (name, {look key: value}, traits_names)} for the 1000 citizens"""
    global _ROSTER
    if _ROSTER is None:
        sys.path.insert(0, os.path.join(ROOT, "tools"))
        import roster_build as rb
        schema, by_id, _edges, _story, errors, _w = rb.load()
        if errors:
            raise LookError("core/data/roster", "roster does not load: %s" % errors[0])
        out = {}
        for i, c in by_id.items():
            look = {k: c.v[k] for k in rb.LOOK_ORDER}
            traits = [t for n, t in enumerate(rb.TRAIT_NAMES) if c.v["traits"] & (1 << n)]
            out[i] = (c.name, look, traits)
        _ROSTER = out
    return _ROSTER


def roster_age(rid):
    traits = roster()[rid][2]
    return "child" if "KID" in traits else ("teen" if "TEEN" in traits else "adult")


