"""CUE_SHEET.md: the episode's music, readable (WP10). Written by spot.run()."""
from __future__ import annotations

from pathlib import Path

from . import barmap as BM
from . import cuelib
from .spotting import SPF, SR, tc

SEG = {"co": "COLD OPEN", "mt": "MAIN TITLE", "1": "ACT ONE", "ec1": "EYECATCH PAIR 1",
       "2": "ACT TWO", "ec2": "EYECATCH PAIR 2", "3": "ACT THREE", "ec3": "EYECATCH PAIR 3",
       "4": "ACT FOUR", "t": "TAG", "cr": "END CREDITS", "pc": "POST-CREDITS BUTTON"}


def _comment(where: str) -> str:
    try:
        path, line = where.rsplit(":", 1)
        raw = Path(path).read_text(encoding="utf-8").splitlines()[int(line) - 1]
    except Exception:
        return ""
    q, out = False, None
    for i, c in enumerate(raw):
        if c == '"':
            q = not q
        if c == "#" and not q:
            out = raw[i + 1:].strip()
            break
    return (out or "").replace("|", "/")


def _beat_of(frame, rd):
    for bid, f0, n in rd:
        if f0 <= frame < f0 + n:
            return bid, frame - f0
    bid, f0, n = rd[-1]
    return bid, frame - f0


def _op_text(e):
    op = e.get("op", "start")
    if op == "start":
        return f"**start** {e['from']} at {e['gain_db']:+.0f} dB"
    if op == "mute":
        return f"mute {e['over_smp'] // SPF} f"
    if op == "duck":
        return f"duck {e['gain_db']:+.0f} dB for {e['over_smp'] // SPF} f"
    if op == "to":
        return f"level to {e['gain_db']:+.0f} dB over {e['over_smp'] // SPF} f"
    if op == "bend":
        return f"bend {e['from_st']:+g} -> {e['to_st']:+g} st over {e['over_smp'] // SPF} f"
    if op == "tapestop":
        return f"tape-stop {e['over_smp'] // SPF} f (then held silent)"
    if op == "stop":
        ov = e.get("over_smp", 0) // SPF
        return "**stop**" + (f" (fade {ov} f)" if ov else "")
    return op


def write(out, path, ep="ep101"):
    evs, rd, metas, defs = out["events"], out["rundown"], out["metas"], out["defs"]
    L = []
    L.append(f"# {ep} \"Mingle Night\": cue sheet (music)\n")
    L.append("Generated by `python3 -m showtk.music.spot " + ep + "` from `show/" + ep + "/cues.shw` "
             "(spotting) and `show/series/music.shw` (the cue library). Timing source: "
             "`docs/show/PILOT_BEATSHEET.md`; the cold open frame-exact from `COLD_OPEN_SHOTLIST.md`. "
             "Programme TC is HH:MM:SS:FF at 30 fps; frame *f* starts at sample 1,600·*f*.\n")
    L.append("**Levels** are relative to each cue's *unity* (the library render at -16 LUFS, or the "
             "-1 dBTP ceiling when lower); WP11 sets the final mix against dialogue. "
             "**Every op is a shot `mx` op**: STAGING can copy it into the shot that contains its frame "
             "(the `beat +f` column) unchanged. Bar positions are the cue's own bar map (`@<cue>:bar:B.b`).\n")
    # ---- the library
    L.append("## 1. The cue library\n")
    L.append("| Cue | Source | Tempo / key | f per bar | Length | Unity | What it is |")
    L.append("|---|---|---|---|---|---|---|")
    used = sorted({e["src"][4:] for e in evs})
    for cid in used:
        m = metas[cid]
        bm = BM.BarMap.from_json(m["barmap"])
        src = m["src"].replace("|", "/")
        L.append(f"| `{cid}` | `{src}` | {m['bpm']:g} bpm {m.get('key', '')} | {bm.frames_per_bar:.2f} | "
                 f"{m['length_smp'] / SR:.1f} s | {m['level']['lufs']} LUFS / {m['level']['tp']} dBTP | "
                 f"{m.get('desc', '')} |")
    L.append("")
    # ---- spotting
    L.append("## 2. Spotting, beat by beat\n")
    by_beat = {}
    for e in evs:
        bid, off = _beat_of(e["frame"], rd)
        by_beat.setdefault(bid, []).append((off, e))
    seg_now = None
    starts = {}
    for bid, f0, n in rd:
        seg = SEG.get(bid.split("_")[1], bid)
        if seg != seg_now:
            L.append(f"\n### {seg}\n")
            L.append("| Beat | TC | f (beat +f) | smp | Cue | Op | Cue bar | Note |")
            L.append("|---|---|---|---|---|---|---|---|")
            seg_now = seg
        rows = by_beat.get(bid, [])
        if not rows:
            L.append(f"| {bid} | {tc(f0)} | {f0} (+0) | | — | *no music op* | | |")
            continue
        for off, e in rows:
            cue = e["src"][4:]
            bm = BM.BarMap.from_json(metas[cue]["barmap"])
            if "op" not in e:
                starts[e["inst"]] = (e["smp"], bm.at(e["from"]))
            s0, o0 = starts.get(e["inst"], (e["smp"], 0))
            b, bt = bm.bar_of_smp(e["smp"] - s0 + o0)
            L.append(f"| {bid} | {tc(e['frame'])} | {e['frame']} (+{off}) | {e['smp']:,} | `{cue}` | "
                     f"{_op_text(e)} | {b}.{bt:.2f} | {_comment(e['where'])} |")
    L.append("")
    # ---- named notes
    L.append("## 3. Named notes (sec.10.4)\n")
    L.append("| Cue | Note | Where | Pitch | Hum | Use |")
    L.append("|---|---|---|---|---|---|")
    for cid in used:
        for name, nv in (metas[cid].get("named_notes") or {}).items():
            L.append(f"| `{cid}` | `{name}` | bar {nv.get('bar', '')} (phrase {nv.get('phrase', '')}) | "
                     f"{nv.get('pitch', '')} | {nv.get('hum', '')} | {nv.get('use', '')} |")
    L.append("")
    # ---- bar maps
    L.append("## 4. Bar maps\n")
    L.append("Every cue's full table is `show/lib/music/barmaps/<cue>.json` (`bar_smp`, `bar_frame`, "
             "sections); `python3 -m showtk.music.render barmap <cue>` prints it. Sections with "
             "their first bar, counted from the cue's sample 0:\n")
    for cid in used:
        bm = BM.BarMap.from_json(metas[cid]["barmap"])
        secs = ", ".join(f"{nm} bar {b0} (+{bm.frame(b0)} f)" for nm, b0, nn in bm.sections) or "—"
        L.append(f"- `{cid}`: {bm.bpm:g} bpm {bm.meter}/4, {bm.frames_per_bar:.3f} f per bar, "
                 f"{bm.bars} bars. {secs}")
    L.append("")
    if "mx_qa" in out:
        L.append("## 5. The temp MX track: unscored share per segment\n")
        L.append("Measured on `ep101_mx_temp.flac` (MX bus only, 0.1 s windows below -50 dBFS). "
                 "The beat sheet's target: 20-25 % of each act unscored (the cold open allows 26 %; "
                 "diegetic music counts as music).\n")
        L.append("| Segment | In | Out | Unscored | Peak |")
        L.append("|---|---|---|---|---|")
        for r in out["mx_qa"]:
            L.append(f"| {r['segment']} | {r['tc_in']} | {r['tc_out']} | {r['unscored_pct']} % | {r['peak_db']} dBFS |")
        L.append("")
    if out.get("qa_rows"):
        L.append("## 6. Listening check, every cue\n")
        L.append("| Cue | LUFS | True peak | Clipped | Onsets | Median to grid | Within 10 ms | Credit lines |")
        L.append("|---|---|---|---|---|---|---|---|")
        for r in out["qa_rows"]:
            L.append(r)
        L.append("")
    if out.get("extra_md"):
        L.append(out["extra_md"])
    Path(path).write_text("\n".join(L) + "\n", encoding="utf-8")
