"""pxt.py - .pxt show fonts (spec 8.6, 9.4 item 3): one character per pixel,
so a glyph is edited with a text diff.

    pxt font <name> h=<rows> line=<advance> space=<gap>
    glyph "A"            (or: glyph code=0x22)
    ..#...               h rows of '.' (paper) and '#' (ink), all one width
    ...

`python3 -m showtk.picture.pxt` (run from show/tools) regenerates
show/engine/show_font_child.c from show/engine/fonts/child_hand.pxt; with
--check it only reports whether the C file is current (the test does that).
"""
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
SHOW = os.path.normpath(os.path.join(HERE, "..", "..", ".."))
CHILD_PXT = os.path.join(SHOW, "engine", "fonts", "child_hand.pxt")
CHILD_C = os.path.join(SHOW, "engine", "show_font_child.c")


class PxtError(ValueError):
    pass


class Font:
    def __init__(self, name, h, line, space):
        self.name, self.h, self.line, self.space = name, h, line, space
        self.glyphs = {}            # code -> list of h strings

    def width(self, code):
        g = self.glyphs.get(code)
        return len(g[0]) if g else 0

    def advance(self, code):
        if code == 0x20:
            return self.width(0x20) + self.space if 0x20 in self.glyphs else 4
        w = self.width(code)
        return w + self.space if w else 0

    def line_w(self, s):
        """width of one line in px at scale 1 (show_text_line_w)."""
        w = sum(self.advance(ord(c)) for c in s)
        return w - self.space if w > 0 else 0


def parse(path):
    font = None
    cur = None
    rows = []
    with open(path, encoding="utf-8") as f:
        lines = f.read().splitlines()

    def close(lineno):
        nonlocal cur, rows
        if cur is None:
            return
        if len(rows) != font.h:
            raise PxtError("%s:%d: glyph 0x%02x has %d rows, the font has %d"
                           % (path, lineno, cur, len(rows), font.h))
        if len(set(len(r) for r in rows)) != 1:
            raise PxtError("%s:%d: glyph 0x%02x rows differ in width" % (path, lineno, cur))
        if len(rows[0]) > 8:
            raise PxtError("%s:%d: glyph 0x%02x is wider than 8" % (path, lineno, cur))
        font.glyphs[cur] = rows
        cur, rows = None, []

    for n, raw in enumerate(lines, 1):
        line = raw.split("#", 1)[0].rstrip() if not re.fullmatch(r"[.#]+", raw.strip()) else raw.strip()
        if not line.strip():
            continue
        if line.startswith("pxt font"):
            kv = dict(re.findall(r"(\w+)=(\S+)", line))
            font = Font(line.split()[2], int(kv.get("h", 12)), int(kv.get("line", 14)),
                        int(kv.get("space", 1)))
            continue
        if line.startswith("glyph"):
            close(n)
            m = re.match(r'glyph\s+"(.)"', line)
            if m:
                cur = ord(m.group(1))
            else:
                m = re.match(r"glyph\s+code=(0x[0-9a-fA-F]+|\d+)", line)
                if not m:
                    raise PxtError("%s:%d: bad glyph line" % (path, n))
                cur = int(m.group(1), 0)
            continue
        if cur is None or font is None:
            raise PxtError("%s:%d: pixels outside a glyph" % (path, n))
        if not re.fullmatch(r"[.#]+", line.strip()):
            raise PxtError("%s:%d: a row may only hold '.' and '#'" % (path, n))
        rows.append(line.strip())
    close(len(lines))
    if font is None:
        raise PxtError("%s: no 'pxt font' line" % path)
    return font


def to_c(font, symbol):
    first = min(font.glyphs)
    last = max(font.glyphs)
    count = last - first + 1
    widths, data = [], []
    for code in range(first, last + 1):
        g = font.glyphs.get(code)
        widths.append(len(g[0]) if g else 0)
        for r in range(font.h):
            if not g:
                data.append(0)
                continue
            b = 0
            for x, ch in enumerate(g[r]):
                if ch == "#":
                    b |= 0x80 >> x
            data.append(b)
    out = ["/* show_font_child.c - GENERATED by showtk/picture/pxt.py from",
           " * show/engine/fonts/%s.pxt. Do not edit: edit the .pxt and regenerate. */" % font.name,
           '#include "show/show_text.h"', "",
           "static const uint8_t W[%d] = {" % count]
    for i in range(0, count, 16):
        out.append("    " + ", ".join(str(w) for w in widths[i:i + 16]) + ",")
    out.append("};")
    out.append("static const uint8_t R[%d] = {" % len(data))
    for i in range(0, len(data), font.h):
        code = first + i // font.h
        ch = chr(code) if 0x21 <= code < 0x7f and chr(code) not in "\\*/" else "0x%02x" % code
        out.append("    " + ", ".join("0x%02x" % b for b in data[i:i + font.h]) + ",  /* %s */" % ch)
    out.append("};")
    out.append("const ShowPxtFont %s = { %d, %d, %d, %d, %d, { 0, 0, 0 }, W, R };"
               % (symbol, first, count, font.h, font.line, font.space))
    return "\n".join(out) + "\n"


def child_font():
    return parse(CHILD_PXT)


def main(argv):
    font = child_font()
    text = to_c(font, "show_font_child")
    if "--check" in argv:
        cur = open(CHILD_C).read() if os.path.exists(CHILD_C) else ""
        if cur != text:
            print("show_font_child.c is stale: run python3 -m showtk.picture.pxt")
            return 1
        print("show_font_child.c is current (%d glyphs)" % len(font.glyphs))
        return 0
    with open(CHILD_C, "w") as f:
        f.write(text)
    print("wrote %s (%d glyphs)" % (CHILD_C, len(font.glyphs)))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
