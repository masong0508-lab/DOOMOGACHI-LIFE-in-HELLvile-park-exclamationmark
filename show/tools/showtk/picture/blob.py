"""blob.py - the lane-2 sections of a shot, as one self-describing blob ("PIC1").

The player binds it with show_l2_bind() (show_l2.c): every section the
lane-2 modules read, in the order the shot draws them. showc's emit puts
the blob in the shot chunk as it is; the lane-2 test driver
(show/tests/engine/picture/) runs it on its own, on the host and on the PS1.

    u32 'PIC1', u16 frames, u16 nsections, then per section:
    u32 tag, u32 bytes, payload (padded to 4)
      'CAM '  ShowCamSetup, u32 n, ShowCamKey[n]
      'FX  '  ShowFxSetup, ShowWipe[nwipes]
      'PLAN'  u8 kind (0 IMAGE 1 STROKES 2 TILEMAP 3 FILL), u8 side (0 A, 1 B: the Split),
              u8 px, u8 boil, ShowPlaneCam, u32 bytes, payload
                IMAGE: u16 w, u16 h, pixels;  FILL: u8 colour (a flat backdrop)
      'TEXT'  ShowTextSet payload
      'EVTS'  u32 n, n x { u16 t, u16 op, i16 args[8] }  (op < 0x100: a BOP_*, a/b in
              args[0..1], run as beat.c would; else a lane-2 SOP)
      'SLOT'  u32 n, n x { i16 x, i16 y }   (prop/actor anchors, test driver only)
"""
import struct

from . import fmt

PLANE_IMAGE, PLANE_STROKES, PLANE_TILEMAP, PLANE_FILL = 0, 1, 2, 3
EV = struct.Struct("<HH8h")


def _sec(tag, payload):
    payload = fmt.pad4(payload)
    return tag.encode("ascii").ljust(4)[:4] + struct.pack("<I", len(payload)) + payload


class Shot:
    def __init__(self, frames):
        self.frames = frames
        self.secs = []
        self.events = []
        self.slots = []

    def camera(self, setup, keys):
        self.secs.append(_sec("CAM ", setup + struct.pack("<I", len(keys)) + b"".join(keys)))

    def fx(self, setup, wipes=()):
        self.secs.append(_sec("FX  ", setup + b"".join(wipes)))

    def plane(self, kind, payload, planecam, px=1, side=0, boil=0):
        body = struct.pack("<BBBB", kind, side, px, boil) + planecam + struct.pack("<I", len(payload)) + payload
        self.secs.append(_sec("PLAN", body))

    def image_plane(self, a, planecam, px=1, side=0, boil=0):
        import numpy as np
        a = np.asarray(a, np.uint8)
        h, w = a.shape
        self.plane(PLANE_IMAGE, struct.pack("<HH", w, h) + a.tobytes(), planecam, px, side, boil)

    def fill_plane(self, color, side=0):
        self.plane(PLANE_FILL, struct.pack("<B3x", color), fmt.planecam(), 1, side)

    def text(self, payload):
        self.secs.append(_sec("TEXT", payload))

    def event(self, t, op, *args):
        a = list(args)[:8] + [0] * (8 - len(args[:8]))
        self.events.append((t, op, a))

    def slot(self, x, y):
        self.slots.append((x, y))
        return len(self.slots) - 1

    def pack(self):
        secs = list(self.secs)
        if self.events:
            ev = sorted(self.events, key=lambda e: e[0])
            secs.append(_sec("EVTS", struct.pack("<I", len(ev)) +
                             b"".join(EV.pack(t, op, *a) for t, op, a in ev)))
        if self.slots:
            secs.append(_sec("SLOT", struct.pack("<I", len(self.slots)) +
                             b"".join(struct.pack("<hh", x, y) for x, y in self.slots)))
        return b"PIC1" + struct.pack("<HH", self.frames, len(secs)) + b"".join(secs)


def to_c(blob, symbol="pic_blob"):
    lines = ["/* generated by showtk/picture/blob.py */", "#include <stdint.h>",
             "const uint32_t %s_len = %d;" % (symbol, len(blob)),
             "const uint8_t %s[%d] __attribute__((aligned(4))) = {" % (symbol, len(blob))]
    for i in range(0, len(blob), 24):
        lines.append("  " + ",".join(str(b) for b in blob[i:i + 24]) + ",")
    lines.append("};")
    return "\n".join(lines) + "\n"
