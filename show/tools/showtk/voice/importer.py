"""`show voice import-lines`: gather the `line` statements of the script drafts (the fenced
```shw blocks at the end of each writer's file, or docs/show/ep101/PILOT_SCRIPT.md once
published) into <ep>/lines.shw, in play order, keeping any line already there.

Normalisation, so every line renders without hand edits:
  - dir="possessed..."           -> mode=possessed (voices.shw variant <voice>.possessed)
  - text that is only a stage parenthetical, "(laughter)" -> say="Ha ha ha!" asr=skip
  - library takes keep take=lib:... lock=identical
"""
from __future__ import annotations

import os
import re

from . import env, shwio

NONVERBAL = {
    "(laughter)": "Ha ha ha! Ha ha!",
    "(a laugh)": "Ha!",
    "(gasps)": "Oh!",
    "(gasp)": "Oh!",
    "(cheers)": "Yay!",
    "(applause)": "Yay! Yay!",
}


def extract(md_path):
    """-> [statement text] of every `line`/`walla` statement inside ```shw fences."""
    out = []
    with open(md_path, encoding="utf-8") as fh:
        txt = fh.read()
    for m in re.finditer(r"```shw\n(.*?)```", txt, re.S):
        for ln in m.group(1).splitlines():
            s = ln.strip()
            if s.startswith("line ") or s.startswith("walla "):
                out.append(s)
    return out


def normalise(stmt):
    toks = shwio.tokenize(stmt)
    if toks[0] != "line":
        return stmt
    kv = {t[1]: t[2] for t in toks if isinstance(t, tuple) and t[0] == "kv"}
    text = next(t[1] for t in toks if isinstance(t, tuple) and t[0] == "str")
    add = []
    d = kv.get("dir", "")
    if d.lower().startswith("possessed") and "mode" not in kv:
        add.append("mode=possessed")
    t = text.strip()
    if t.startswith("(") and t.endswith(")") and "say" not in kv:
        add.append(f'say="{NONVERBAL.get(t.lower(), "Ha ha!")}"')
        if "asr" not in kv:
            add.append("asr=skip")
    if not add:
        return stmt
    # insert before a trailing comment, if any
    body, sep, com = _split_comment(stmt)
    return body.rstrip() + " " + " ".join(add) + (("   " + sep + com) if sep else "")


def _split_comment(s):
    q = False
    for i, c in enumerate(s):
        if c == '"' and (i == 0 or s[i - 1] != "\\"):
            q = not q
        elif c == "#" and not q:
            return s[:i], "#", s[i + 1:]
    return s, "", ""


def import_lines(ep, sources, header=None):
    d = env.ep_dir(ep)
    os.makedirs(d, exist_ok=True)
    dst = os.path.join(d, "lines.shw")
    have, _ = shwio.read_lines(dst)
    stmts = []
    for s in sources:
        stmts.extend(extract(s))
    seen = set()
    out = [header or f"# show/{ep}/lines.shw: dialogue, one line per id (spec §5.6). Generated by "
                     f"`show voice import-lines`; edit freely, ids are stable forever."]
    kept_old = [lid for lid in have if lid]
    for s in stmts:
        s2 = normalise(s)
        toks = shwio.tokenize(s2)
        if toks[0] == "line":
            lid = toks[1]
            if lid in seen:
                continue
            seen.add(lid)
        out.append(s2)
    missing = [lid for lid in kept_old if lid not in seen]
    if missing:
        out.append("# ---- kept from the previous lines.shw (not in the sources)")
        with open(dst, encoding="utf-8") as fh:
            for ln in fh:
                toks = shwio.tokenize(ln.strip()) if ln.strip() else []
                if toks and toks[0] == "line" and toks[1] in missing:
                    out.append(ln.rstrip("\n"))
    with open(dst, "w", encoding="utf-8") as fh:
        fh.write("\n".join(out) + "\n")
    lines, beds = shwio.read_lines(dst)
    return dst, len(lines), len(beds)
