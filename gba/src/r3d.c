static void setup_map(const DoomoMap *m)
{
    int i, n = m->w * m->h, x, y;
    int32_t top = -32768;
    for (i = 0; i < n; i++) {
        const DoomoCell *c = &m->cells[i];
        int32_t a = c->floor_h, b = c->ceil_h;
        if (a > top) top = a;
        if (b > top) top = b;
        if ((c->flags & CELL_LIFT) && (int8_t)c->tag > top) top = (int8_t)c->tag;
    }
    /* roofs: a roofed open cell next to blocks with an explicit top
     * (a doorway in a house) has its roof at the tallest of them */
    for (y = 0; y < m->h; y++) {
        for (x = 0; x < m->w; x++) {
            const DoomoCell *c = &m->cells[y * m->w + x];
            int k, roof = 127;
            static const int8_t nb[4][2] = { { 1, 0 }, { -1, 0 }, { 0, 1 }, { 0, -1 } };
            if (!c->wall && c->ceil_tex != DOOMO_TEX_SKY) {
                for (k = 0; k < 4; k++) {
                    int nx = x + nb[k][0], ny = y + nb[k][1];
                    const DoomoCell *o;
                    if (nx < 0 || ny < 0 || nx >= m->w || ny >= m->h) continue;
                    o = &m->cells[ny * m->w + nx];
                    if (o->wall && o->ceil_h > o->floor_h &&
                        (roof == 127 || o->ceil_h > roof))
                        roof = o->ceil_h;
                }
            }
            r3d_roof[y * m->w + x] = (int8_t)roof;
        }
    }
    /* walls without an explicit top are 256 units above the floor they
     * are seen from (reference semantics) */
    r3f.maxtop4 = (top * 8 + 256 + 32) << 4;
    cache_mapdef = m->def;
    cache_mw = m->w;
    cache_mh = m->h;
    memset(r3d_avgc, 0, sizeof(r3d_avgc));
}

/* ------------------------------------------------------------------------- */
typedef struct SprOrder { int32_t depth; int16_t idx; } SprOrder;
#define R3D_MAXSPR 128
#define spr_order ((SprOrder *)(gba_big + GBA_BIG_SPR))

static void draw_sprites(const DoomoView3D *v)
{
    int i, n = 0, count = v->sprite_count;
    if (!v->sprites || count <= 0) return;
    if (count > R3D_MAXSPR) count = R3D_MAXSPR;
    for (i = 0; i < count; i++) {
        const DoomoBillboard *b = &v->sprites[i];
        int32_t dx, dy, depth;
        if (!b->img || !b->img->pix || !b->img->w || !b->img->h) continue;
        dx = b->x - r3f.ex;
        dy = b->y - r3f.ey;
        depth = (int32_t)((r3d_smull(dx, r3f.fx) + r3d_smull(dy, r3f.fy)) >> 16);
        if (depth < (4 << 16)) continue;                 /* behind / at the eye */
        if (depth > (R3D_MAXDIST * 64) << 16) continue;
        spr_order[n].depth = depth;
        spr_order[n].idx = (int16_t)i;
        n++;
    }
    /* far to near (insertion sort, n is small) */
    for (i = 1; i < n; i++) {
        SprOrder k = spr_order[i];
        int j = i - 1;
        while (j >= 0 && spr_order[j].depth < k.depth) { spr_order[j + 1] = spr_order[j]; j--; }
        spr_order[j + 1] = k;
    }
    for (i = 0; i < n; i++) {
        const DoomoBillboard *b = &v->sprites[spr_order[i].idx];
        const DoomoImage *img = b->img;
        R3DSprite s;
        int32_t depth = spr_order[i].depth;
        int32_t dx = b->x - r3f.ex, dy = b->y - r3f.ey;
        int32_t lat = (int32_t)((r3d_smull(dx, r3f.rx) + r3d_smull(dy, r3f.ry)) >> 16);
        int32_t k8 = r3d_k8((uint32_t)depth);
        uint32_t scale = b->scale ? b->scale : 256;
        int32_t ww16 = (int32_t)(img->w * scale) << 8;     /* world width 16.16 */
        int32_t wh16 = (int32_t)(img->h * scale) << 8;
        int32_t sx12 = (r3f.halfw << 12) + R3D_MULSHR(lat, k8, 12);
        int32_t w12 = R3D_MULSHR(ww16, k8, 12);
        int32_t h12 = R3D_MULSHR(wh16, k8, 12);
        int level;
        if (w12 < 0x400 || h12 < 0x400) continue;                  /* < 1/4 px */
        if (sx12 + (w12 >> 1) <= 0 || sx12 - (w12 >> 1) >= (r3f.vw << 12)) continue;
        s.img = img;
        s.depth16 = depth;
        s.x0_12 = sx12 - (w12 >> 1);
        s.w12 = w12;
        s.h12 = h12;
        s.ytop12 = r3f.hor12 +
                   R3D_MULSHR(r3f.ez - (b->z + wh16), k8, 12);
        {
            uint32_t den = scale * (uint32_t)k8;
            s.step16 = den ? 0xFFFFFFFFu / den : 0x10000u;
        }
        if (b->flags & BB_FULLBRIGHT) {
            level = 15;
        } else {
            int cx = b->x >> 22, cy = b->y >> 22, l = 0;
            uint32_t bk = (uint32_t)depth >> 21;
            if ((unsigned)cx < (unsigned)r3f.mw && (unsigned)cy < (unsigned)r3f.mh)
                l = r3f.cells[cy * r3f.mw + cx].light;
            if (!l) l = r3f.amb;
            level = l - r3d_fade[bk < R3D_FADE_N ? bk : R3D_FADE_N - 1];
            if (level < 1) level = 1;
            level += b->light;
        }
        s.level = (uint8_t)(level < 1 ? 1 : (level > 15 ? 15 : level));
        s.flags = b->flags;
        s.trans = (b->flags & BB_TRANSLUCENT) ||
                  (i >= 0 && spr_order[i].idx == v->player_sprite && depth < (40 << 16));
        s.shadow_y12 = 0;
        s.shadow_hh = 0;
        if (b->flags & BB_SHADOW) {
            int cx = b->x >> 22, cy = b->y >> 22;
            int32_t fz = b->z;
            int32_t hw = (w12 * 3) >> 15;                          /* px */
            if ((unsigned)cx < (unsigned)r3f.mw && (unsigned)cy < (unsigned)r3f.mh) {
                const DoomoCell *c = &r3f.cells[cy * r3f.mw + cx];
                int32_t cf = (c->flags & (CELL_DOOR | CELL_LIFT))
                                 ? map_floor_z(r3f.map, cx, cy) << 16
                                 : (int32_t)c->floor_h << 19;
                if (cf <= b->z) fz = cf;
            }
            s.shadow_y12 = r3f.hor12 + R3D_MULSHR(r3f.ez - fz, k8, 12);
            s.shadow_hh = (int32_t)(r3d_smull(hw, (r3f.ez - fz) >> 8) / ((depth >> 8) + 1));
            if (s.shadow_hh < 1) s.shadow_hh = 1;
            if (s.shadow_hh > 12) s.shadow_hh = 12;
            if (r3f.ez <= fz) s.flags &= (uint8_t)~BB_SHADOW;
        }
        r3d_draw_sprite(&s);
    }
}

