static int cache_fov = -1;

static void setup_viewport(int vw, int vh, int fov)
{
    /* OPT_FOV 0/1/2: tan(fov/2) = 0.55 / 0.66 / 0.79 (same as the native
     * reference renderer) */
    static const int32_t plane[3] = { 36000, 43250, 52000 };
    int c, m;
    int ncol = vw >> 1;
    int proj = (int)(((int32_t)(vw >> 1) << 16) / plane[fov < 0 || fov > 2 ? 1 : fov]);
    if (proj < 16) proj = 16;
    r3f.proj = proj;
    r3f.invproj = 0xFFFFFFFFu / (uint32_t)proj;
    r3f.vw = vw;
    r3f.vh = vh;
    r3f.ncol = ncol;
    r3f.halfw = vw >> 1;
    for (c = 0; c < ncol; c++) {
        int32_t X = 2 * c + 1 - (vw >> 1);
        r3d_colt[c] = (int32_t)((X * 65536) / proj);
        r3d_colang[c] = (int16_t)iatan16(r3d_colt[c]);
        /* 4-bit bit-reversed column index: a 1D ordered dither */
        r3d_dither[c] = (uint8_t)(((c & 1) << 3) | ((c & 2) << 1) | ((c & 4) >> 1) |
                                  ((c & 8) >> 3));
    }
    for (m = 0; m < R3D_KROWS; m++)
        r3d_rowk[m] = (int32_t)(((uint32_t)proj << 17) / (uint32_t)(2 * m + 1));
    for (m = 1; m <= 4; m++) {
        r3d_rowk[-m] = r3d_rowk[0];
        r3d_rowk[R3D_KROWS - 1 + m] = r3d_rowk[R3D_KROWS - 1];
    }
    cache_vw = vw;
    cache_vh = vh;
    cache_fov = fov;
}

static void setup_fade(int amb)
{
    /* Distance fade (reference semantics): one light level per 128 world
     * units. One bucket = 32 units. */
    int b;
    for (b = 0; b < R3D_FADE_N; b++) {
        int f = b >> 2;
        r3d_fade[b] = (uint8_t)(f > 15 ? 15 : f);
    }
    r3f.amb = amb ? amb : 12;              /* light of cells with light 0 */
    cache_amb = amb;
}

static void setup_colormaps(void)
{
    uint32_t sig = 0;
    int i;
    /* the core may (re)build doomo_colormap at any time: cheap signature */
    for (i = 0; i < 16; i++) sig = sig * 31u + doomo_colormap[i][(i * 37 + 11) & 255] +
                                     doomo_colormap[7][i * 16 + 3];
    sig ^= doomo_colormap[0][200] * 7u;
    if (sig != cm_sig || cache_vw < 0) {
        memcpy(r3d_cmap, doomo_colormap, sizeof(r3d_cmap));
        cm_sig = sig;
    }
    r3f.cm = r3d_cmap;
}

