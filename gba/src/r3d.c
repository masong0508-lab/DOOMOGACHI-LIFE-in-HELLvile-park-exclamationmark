/* A closed ray can never admit a billboard at or behind that checkpoint.
 * Keep the farthest closure in each group, or infinity if any ray still
 * has an opening. A visible arch or window keeps its sector eligible. */
static unsigned wall_depth_bounds(uint16_t bins[WALL_BIN_N])
{
    unsigned far = 0;
    int c;
    memset(bins, 0, WALL_BIN_N * sizeof(*bins));
    for (c = 0; c < r3f.ncol; c++) {
        int bin = c >> WALL_BIN_SHIFT;
        int n = r3d_nclips[c];
        unsigned depth = UINT16_MAX;
        if (bins[bin] == UINT16_MAX) continue;
        if (n) {
            const R3DClip *end = &r3d_clips[c][n - 1];
            if (end->top >= end->bot) depth = end->d8;
        }
        if (depth > bins[bin]) bins[bin] = (uint16_t)depth;
        if (depth > far) far = depth;
    }
    return far;
}

static int behind_wall(const uint16_t bins[WALL_BIN_N], int32_t x0, int32_t x1, unsigned depth)
{
    int start = DOOMO_MAX(0, (x0 - 1) >> 13);
    int end = DOOMO_MIN(r3f.ncol, (x1 + 0x17FF) >> 13);
    int b;
    if (start >= end) return 0;
    /* A drop shadow fits horizontally inside the sprite's projected span. */
    for (b = start >> WALL_BIN_SHIFT; b <= (end - 1) >> WALL_BIN_SHIFT; b++)
        if (depth < bins[b]) return 0;
    return 1;
}

/* Resolve two sprite samples per geometry ray. They share the wall
 * checkpoint, but each lane has its own silhouette and transparency. */
__attribute__((target("arm")))
void r3d_draw_sprite_pairs(const R3DSprite *s, int r0, int r1, int32_t vr0)
{
    const DoomoImage *img = s->img;
    const int iw = img->w;
    const uint8_t *cm = r3d_cmrow[s->level];
    const uint32_t depth8 = (uint32_t)s->depth16 >> 13;
    const int32_t x0 = s->x0_12, x1 = x0 + s->w12;
    int c = DOOMO_MAX(0, (x0 + 0x7FF) >> 13);
    int end = DOOMO_MIN(r3f.ncol, (x1 + 0x17FF) >> 13);
    int32_t left = (c << 13) + 0x800;
    uint32_t step = s->step16;
    uint32_t u = r3d_sprite_u16(left - x0, step);
    for (; c < end; c++, left += 0x2000, u += step << 1) {
        int top, bot, from, to, u0, u1;
        uint32_t v;
        volatile uint16_t *dst;
        r3d_clip_at(c, depth8, &top, &bot);
        from = DOOMO_MAX(r0, top);
        to = DOOMO_MIN(r1, bot);
        if (from >= to) continue;
        u0 = left >= x0 && left < x1 ? DOOMO_CLAMP((int32_t)u >> 16, 0, iw - 1) : -1;
        u1 = left + 0x1000 >= x0 && left + 0x1000 < x1 ?
             DOOMO_CLAMP((int32_t)(u + step) >> 16, 0, iw - 1) : -1;
        if (s->flags & BB_FLIPX) {
            if (u0 >= 0) u0 = iw - 1 - u0;
            if (u1 >= 0) u1 = iw - 1 - u1;
        }
        v = (uint32_t)vr0 + (uint32_t)(from - r0) * step;
        dst = r3f.dst + from * (SCREEN_W / 2) + c;
        if (u0 == u1) {
            if (u0 >= 0)
                r3d_sprite_loop((uint16_t *)dst, to - from, img->pix + u0, v, step, cm, SCREEN_W, iw);
        } else if (u0 >= 0 && u1 >= 0) {
            r3d_sprite_pair_loop((uint16_t *)dst, to - from, img->pix + u0, v, step, cm, iw, u1 - u0);
        } else {
            for (; from < to; from++, dst += SCREEN_W / 2, v += step) {
                const uint8_t *row = img->pix + (v >> 16) * iw;
                unsigned lo = u0 < 0 ? 0 : row[u0], hi = u1 < 0 ? 0 : row[u1];
                if (lo) *dst = (uint16_t)((*dst & 0xFF00u) | cm[lo]);
                else if (hi) *dst = (uint16_t)((*dst & 0xFFu) | (cm[hi] << 8));
            }
        }
    }
}

/* Set up the texture rows once per billboard in ROM. The clipped
 * pixel kernels stay in the IWRAM overlay. */
__attribute__((target("arm")))
void r3d_draw_sprite(const R3DSprite *s)
{
    int r0 = DOOMO_MAX(0, (s->ytop12 + 0x800) >> 12);
    int r1 = DOOMO_MIN(r3f.vh, (s->ytop12 + s->h12 + 0x800) >> 12);
    uint32_t v0 = (uint32_t)(((int64_t)(((r0 << 12) + 0x800) - s->ytop12) * s->step16) >> 12);
    while (r1 > r0 && ((v0 + (uint32_t)(r1 - 1 - r0) * s->step16) >> 16) >= s->img->h)
        r1--;
    r3d_render_sprite(s, r0, r1, (int32_t)v0);
}

static void draw_sprites(const DoomoView3D *v, int bone, const uint16_t *bins, unsigned far)
{
    int i, n = 0, count = v->sprite_count;
    const int32_t smax = (int32_t)(r3f.maxd << 6);     /* (LV4) the level's view distance in 16.16 world units (64 a cell) */
    if (!v->sprites || count <= 0) return;
    if (count > R3D_MAXSPR) count = R3D_MAXSPR;
    /* (SP8, from G9) the list comes nearest first (combat_build_view):
     * walked backwards it is nearly far to near already, so the insertion
     * sort below moves little (front to back it shifted every entry: O(n^2)
     * with the ~50 billboards of a combat map) */
    for (i = count - 1; i >= 0; i--) {
        const DoomoBillboard *b = &v->sprites[i];
        int32_t dx, dy, depth;
        if (!b->img || !b->img->pix || !b->img->w || !b->img->h) continue;
        dx = b->x - r3f.ex;
        dy = b->y - r3f.ey;
        depth = r3d_dot16(dx, r3f.fx, dy, r3f.fy);
        if (depth < (4 << 16)) continue;                 /* behind / at the eye */
        if (depth > smax) continue;
        if (((uint32_t)depth >> 13) >= far) {
            r3d_stats.occluded_sprites++;
            continue;
        }
        spr_order[n].depth = depth;
        spr_order[n].idx = (int16_t)i;
        n++;
    }
    /* far to near, equal depths in list order (the order the stable sort
     * of the list gave before: same frames) */
    for (i = 1; i < n; i++) {
        SprOrder k = spr_order[i];
        int j = i - 1;
        while (j >= 0 && (spr_order[j].depth < k.depth ||
                          (spr_order[j].depth == k.depth && spr_order[j].idx > k.idx))) {
            spr_order[j + 1] = spr_order[j];
            j--;
        }
        spr_order[j + 1] = k;
    }
    for (i = 0; i < n; i++) {
        const DoomoBillboard *b = &v->sprites[spr_order[i].idx];
        const DoomoImage *img = b->img;
        R3DSprite s;
        int32_t depth = spr_order[i].depth;
        int32_t dx = b->x - r3f.ex, dy = b->y - r3f.ey;
        int32_t lat = r3d_dot16(dx, r3f.rx, dy, r3f.ry);
        int32_t k8 = r3d_k8((uint32_t)depth);
        uint32_t scale = b->scale ? b->scale : 256;
        int32_t ww16 = (int32_t)(img->w * scale) << 8;     /* world width 16.16 */
        int32_t wh16 = (int32_t)(img->h * scale) << 8;
        int32_t sx12 = (r3f.halfw << 12) + R3D_MULSHR(lat, k8, 12);
        int32_t w12 = R3D_MULSHR(ww16, k8, 12);
        int32_t h12 = R3D_MULSHR(wh16, k8, 12);
        int32_t effect_center12 = 0;
        int small_effect = 0;
        int level;
        /* Impacts can start almost at the eye. Bound the burst's size
         * around its projected centre and keep its true occlusion depth. */
        if ((b->flags & BB_EFFECT) && (w12 > (r3f.vw << 11) || h12 > (r3f.vh << 11))) {
            int32_t kw = (r3f.vw << 15) / (img->w * (int32_t)scale);
            int32_t kh = (r3f.vh << 15) / (img->h * (int32_t)scale);
            effect_center12 = r3f.hor12 + R3D_MULSHR(r3f.ez - (b->z + wh16 / 2), k8, 12);
            k8 = DOOMO_MIN(kw, kh);
            w12 = R3D_MULSHR(ww16, k8, 12);
            h12 = R3D_MULSHR(wh16, k8, 12);
            small_effect = 1;
        }
        if (w12 < 0x400 || h12 < 0x400) continue;                  /* < 1/4 px */
        if (sx12 + (w12 >> 1) <= 0 || sx12 - (w12 >> 1) >= (r3f.vw << 12)) continue;
        if (bins && behind_wall(bins, sx12 - (w12 >> 1),
                                      sx12 - (w12 >> 1) + w12, (uint32_t)depth >> 13)) {
            r3d_stats.occluded_sprites++;
            continue;
        }
        s.img = img;
        s.depth16 = depth;
        s.x0_12 = sx12 - (w12 >> 1);
        s.w12 = w12;
        s.h12 = h12;
        s.ytop12 = small_effect ? effect_center12 - h12 / 2 :
                   r3f.hor12 + R3D_MULSHR(r3f.ez - (b->z + wh16), k8, 12);
        {
            uint32_t den = scale * (uint32_t)k8;
            s.step16 = den ? 0xFFFFFFFFu / den : 0x10000u;
        }
        /* Project the first visible texel in ROM, avoiding one ARM7 64-bit
         * multiply PER sprite column inside the tightly budgeted IWRAM
         * 3D overlay. The exact original integer truncation is retained. */
        {
            int c0 = (s.x0_12 - 1) >> 13;
            if (c0 < 0) c0 = 0;
            s.u16_start = r3d_sprite_u16(((c0 * 2 + 1) << 12) - s.x0_12, s.step16);
        }
        if (b->flags & BB_FULLBRIGHT) {
            level = 15;
        } else {
            int cx = b->x >> 22, cy = b->y >> 22, l = 0;
            uint32_t bk = (uint32_t)depth >> 21;
            if ((unsigned)cx < (unsigned)r3f.mw && (unsigned)cy < (unsigned)r3f.mh)
                l = r3f.cells[cy * r3f.mw + cx].light;
            if (!l) l = r3f.amb;
            level = l - r3d_fade[bk < R3D_FADE_N ? bk : R3D_FADE_N - 1];
            if (level < 1) level = 1;
            level += b->light;
            /* Bone readability: retain the actor's existing sprite and
             * colour palette, but keep it discernible against the newly
             * illuminated skull/stone walls and lava. Only a per-billboard
             * clamp; no silhouette outline, pixel pass, asset or heap RAM.
             * Fullbright sprites and normal maps are unchanged. */
            if (level < 8 && bone) level = 8;
        }
        s.level = (uint8_t)(level < 1 ? 1 : (level > 15 ? 15 : level));
        s.flags = b->flags;
        s.trans = (b->flags & BB_TRANSLUCENT) ||
                  (i >= 0 && spr_order[i].idx == v->player_sprite && depth < (40 << 16));
        /* Keep the outline of small and mid-size combat sprites precise
         * even when Smooth turns their shadows off. Large sprites use runs. */
        s.pairs = r3f.pair_wall && !s.trans &&
                  (b->flags & BB_DETAIL ? s.step16 >= 0x8000u :
                   (b->flags & BB_SHADOW) && s.step16 >= 0x10000u);
        s.shadow_y12 = 0;
        s.shadow_hh = 0;
        if (b->flags & BB_SHADOW) {
            int cx = b->x >> 22, cy = b->y >> 22;
            int32_t fz = b->z;
            int32_t hw = (w12 * 3) >> 15;                          /* px */
            if ((unsigned)cx < (unsigned)r3f.mw && (unsigned)cy < (unsigned)r3f.mh) {
                const DoomoCell *c = &r3f.cells[cy * r3f.mw + cx];
                int32_t cf = (c->flags & (CELL_DOOR | CELL_LIFT))
                                 ? map_floor_z(r3f.map, cx, cy) << 16
                                 : (int32_t)c->floor_h << 19;
                if (cf <= b->z) fz = cf;
            }
            s.shadow_y12 = r3f.hor12 + R3D_MULSHR(r3f.ez - fz, k8, 12);
            if (r3f.ez <= fz) {
                /* Below the shadow plane: it was never drawn. */
                s.flags &= (uint8_t)~BB_SHADOW;
                s.shadow_hh = 1;
            } else {
                /* Shadow height is clamped to 1..12 pixels. Compare first,
                 * then use the cheaper 32-bit divide only in the narrow
                 * unclamped case. This gives the same integer height as
                 * the old per-sprite 64-bit division, without a new LUT,
                 * IWRAM routine, asset or framebuffer. */
                int64_t num = r3d_smull(hw, (r3f.ez - fz) >> 8);
                uint32_t den = ((uint32_t)depth >> 8) + 1u;
                if (num <= (int64_t)den) s.shadow_hh = 1;
                else if (num >= (int64_t)den * 12) s.shadow_hh = 12;
                else s.shadow_hh = (int32_t)((uint32_t)num / den);
            }
        }
        r3d_draw_sprite(&s);
    }
}

