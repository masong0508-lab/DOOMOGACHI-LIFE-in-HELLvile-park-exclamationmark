static int cache_fov = -1;

static void setup_viewport(int vw, int vh, int fov)
{
    /* OPT_FOV 0/1/2: tan(fov/2) = 0.55 / 0.66 / 0.79 (same as the native
     * reference renderer) */
    static const int32_t plane[3] = { 36000, 43250, 52000 };
    int c, m;
    int ncol = vw >> 1;
    int fov_index = fov < 0 || fov > 2 ? 1 : fov;
    int preset;
    for (preset = 0; preset < R3D_VIEWPORT_PRESET_N; preset++)
        if (vw == gba_viewport_widths[preset]) break;
    if (preset < R3D_VIEWPORT_PRESET_N) {
        /* A quality-tier switch copies the same tables from ROM instead
         * of doing hundreds of divides and angle searches on that frame. */
        const R3DViewportPreset *t = &gba_viewport_presets[preset][fov_index];
        r3f.proj = t->proj;
        r3f.invproj = t->invproj;
        memcpy(r3d_colt, t->colt, ncol * sizeof(*r3d_colt));
        memcpy(r3d_colang, t->colang, ncol * sizeof(*r3d_colang));
        memcpy(r3d_rowk, t->rowk, sizeof(t->rowk));
    } else {
        int proj = (ncol << 16) / plane[fov_index];
        if (proj < 16) proj = 16;
        r3f.proj = proj;
        r3f.invproj = 0xFFFFFFFFu / (uint32_t)proj;
        for (c = 0; c < ncol; c++) {
            int32_t x = 2 * c + 1 - ncol;
            r3d_colt[c] = (x * 65536) / proj;
            r3d_colang[c] = (int16_t)iatan16(r3d_colt[c]);
        }
        for (m = 0; m < R3D_KROWS; m++)
            r3d_rowk[m] = (int32_t)(((uint32_t)proj << 17) / (uint32_t)(2 * m + 1));
    }
    r3f.vw = vw;
    r3f.vh = vh;
    r3f.ncol = ncol;
    r3f.halfw = ncol;
    for (c = 0; c < ncol; c++) {
        /* 4-bit bit-reversed column index: a 1D ordered dither */
        r3d_dither[c] = (uint8_t)(((c & 1) << 3) | ((c & 2) << 1) | ((c & 4) >> 1) |
                                  ((c & 8) >> 3));
    }
    for (m = 1; m <= 4; m++) {
        r3d_rowk[-m] = r3d_rowk[0];
        r3d_rowk[R3D_KROWS - 1 + m] = r3d_rowk[R3D_KROWS - 1];
    }
    cache_vw = vw;
    cache_vh = vh;
    cache_fov = fov;
}

static void setup_fade(int amb, const DoomoMapDef *def)
{
    /* Cathedral/Capital readability: their long aisles and city vistas
     * otherwise fade toward black before their landmarks can be seen.
     * Preserve the authored near/mid-range lighting curve, but retain
     * a little dim light in the farthest distance so silhouettes stay
     * legible. The shared 128-byte LUT does all the work on map changes:
     * no extra ray steps, per-pixel instructions, or framebuffer RAM. */
    const int cathedral = def == doomo_maps[MAPID_BONE_CATHEDRAL];
    const int capital = def == doomo_maps[MAPID_BONE_CAPITAL];
    /* Distance fade (reference semantics): one light level per 128 world
     * units. One bucket = 32 units. The Cathedral's dark, narrow aisles
     * need two additional retained light levels at far range to expose
     * the arches against the roofline. Near/mid lighting (fade <= 5)
     * stays unchanged. Capital now retains three extra levels at far
     * range so its skyline and street gateways stay distinguishable.
     * This is a 128-entry setup LUT, not a new per-texel effect. */
    int b;
    for (b = 0; b < R3D_FADE_N; b++) {
        int f = b >> 2;
        if ((cathedral || capital) && f > 5) {
            int far_cap = cathedral ? 5 : 6; /* Capital far facades stay distinguishable too; LUT only */
            f = 5 + ((f - 5) >> 1);
            if (f > far_cap) f = far_cap;
        }
        r3d_fade[b] = (uint8_t)(f > 15 ? 15 : f);
    }
    r3f.amb = amb ? amb : 12;              /* light of cells with light 0 */
    cache_amb = amb;
    cache_fade_mapdef = def;
}

static void setup_colormaps(void)
{
    uint32_t sig = 0;
    int i;
    /* the core may (re)build doomo_colormap at any time: cheap signature */
    for (i = 0; i < 16; i++) sig = sig * 31u + doomo_colormap[i][(i * 37 + 11) & 255] +
                                     doomo_colormap[7][i * 16 + 3];
    sig ^= doomo_colormap[0][200] * 7u;
    if (sig != cm_sig || !r3d_cmrow[0]) {
        /* rows 0-9 fill the gap after page 0, rows 10-15 the one after
         * page 1 (VRAM takes halfword / word writes only) */
        for (i = 0; i < 16; i++) {
            uint8_t *dst = i < 10 ? R3D_CM_GAP_A + i * 256 : R3D_CM_GAP_B + (i - 10) * 256;
            const uint8_t *src = doomo_colormap[i];
            if (((uintptr_t)src & 3) == 0) {
                dma3_copy32(dst, src, 256 / 4);
            } else {
                volatile uint16_t *d = (volatile uint16_t *)dst;
                int k;
                for (k = 0; k < 128; k++) d[k] = (uint16_t)(src[2 * k] | (src[2 * k + 1] << 8));
            }
            r3d_cmrow[i] = dst;
        }
        cm_sig = sig;
    }
}

