/* VRAM texture cache. Texels fetched from the cartridge cost 6 cycles,
 * from VRAM 3: the free OBJ tile VRAM of the bitmap modes (16 KB at
 * 0x06014000, no hardware sprites are used) holds the 4 textures that
 * covered the most pixels in the previous frame. The pixel loops only
 * read it (VRAM ignores byte writes, not byte reads). Animated textures
 * are re-copied when their frame changes. */
#define VTEX_SLOTS 4
#define VTEX_BASE  ((uint8_t *)0x06014000)
#define VTEX_SIZE  DOOMO_TEX_SIZE_PX
static uint8_t vtex_id[VTEX_SLOTS];              /* texture id + 1, 0 = free */
static const uint8_t *vtex_src[VTEX_SLOTS];

static void vtex_update(void)
{
    int best[VTEX_SLOTS], i, k, n = 0;
    /* the most drawn textures of the last frame (at least 256 pixels) */
    for (k = 0; k < VTEX_SLOTS; k++) best[k] = -1;
    for (i = 1; i < R3D_MAXTEX; i++) {
        uint32_t px = r3d_texpix[i];
        if (px < 256) continue;
        for (k = 0; k < VTEX_SLOTS; k++) {
            if (best[k] < 0 || px > r3d_texpix[best[k]]) {
                int j;
                for (j = VTEX_SLOTS - 1; j > k; j--) best[j] = best[j - 1];
                best[k] = i;
                break;
            }
        }
    }
    for (k = 0; k < VTEX_SLOTS; k++) if (best[k] >= 0) n++;
    /* free the slots whose texture dropped out */
    for (i = 0; i < VTEX_SLOTS; i++) {
        int keep = 0;
        for (k = 0; k < n; k++) if (vtex_id[i] == best[k] + 1) keep = 1;
        if (!keep) vtex_id[i] = 0;
    }
    /* place the newcomers */
    for (k = 0; k < n; k++) {
        int have = 0;
        for (i = 0; i < VTEX_SLOTS; i++) if (vtex_id[i] == best[k] + 1) have = 1;
        if (have) continue;
        for (i = 0; i < VTEX_SLOTS; i++)
            if (!vtex_id[i]) { vtex_id[i] = (uint8_t)(best[k] + 1); vtex_src[i] = NULL; break; }
    }
    /* copy what changed, point the frame's texture cache at the copies */
    for (i = 0; i < VTEX_SLOTS; i++) {
        int id = vtex_id[i] - 1;
        const uint8_t *src;
        uint8_t *dst = VTEX_BASE + i * VTEX_SIZE;
        if (id < 0) continue;
        src = texture_pixels(id, r3f.time);
        if (!src) { vtex_id[i] = 0; continue; }
        if (src != vtex_src[i]) {
            if (((uintptr_t)src & 3) == 0) dma3_copy32(dst, src, VTEX_SIZE / 4);
            else { vtex_id[i] = 0; continue; }
            vtex_src[i] = src;
        }
        r3d_texc[id] = dst;
    }
    memset(r3d_texpix, 0, sizeof(r3d_texpix));
}

void plat_view3d(const DoomoView3D *v)
{
    uint32_t t0, t1, t2, t3;
    int vx, vy, vw, vh;
    int a;
    const DoomoMap *m;
    if (gba_nodraw || !v || !v->map) return;
    gba_big_claim(GBA_BIG_BY_R3D);
    t0 = gba_cycles();
    m = v->map;

    /* viewport: even x / width (2-pixel columns), clipped to the screen */
    vx = v->vx & ~1;
    vy = v->vy;
    vw = (v->vw + (v->vx & 1)) & ~1;
    vh = v->vh;
    if (vx < 0) { vw += vx; vx = 0; }
    if (vy < 0) { vh += vy; vy = 0; }
    if (vx + vw > SCREEN_W) vw = SCREEN_W - vx;
    if (vy + vh > SCREEN_H) vh = SCREEN_H - vy;
    if (vw < 8 || vh < 8) return;
    {
        int fov = opt_get(OPT_FOV);
        if (vw != cache_vw || vh != cache_vh || fov != cache_fov) setup_viewport(vw, vh, fov);
    }
    r3f.dst = gba_back + vy * (SCREEN_W / 2) + (vx >> 1);

    /* camera */
    a = v->angle & 4095;
    r3f.fx = icos(a);
    r3f.fy = isin(a);
    r3f.rx = -isin(a);
    r3f.ry = icos(a);
    r3f.rxpp = (int32_t)(((int64_t)r3f.rx * (int64_t)r3f.invproj) >> 16);
    r3f.rypp = (int32_t)(((int64_t)r3f.ry * (int64_t)r3f.invproj) >> 16);
    r3f.ex = v->x;
    r3f.ey = v->y;
    r3f.ez = v->z + ((int32_t)v->bob << 16);
    r3f.ez4 = r3f.ez >> 12;
    {
        /* look up/down: y-shearing, pitch * focal * 0.84 / 256 rows */
        int p = v->pitch;
        int off, lim = R3D_KROWS - vh / 2 - 8;
        if (p > 256) p = 256;
        if (p < -256) p = -256;
        off = (p * r3f.proj * 84) / (256 * 100);
        if (off > lim) off = lim;
        if (off < -lim) off = -lim;
        r3f.hor = vh / 2 + off;
        r3f.hor12 = r3f.hor << 12;
        /* sky: 88 rows over 3/4 of the view height above the horizon */
        {
            int span = vh * 3 / 4;
            r3f.sky_dv = (88 << 16) / (span ? span : 1);
            r3f.sky_ya = r3f.hor - span;                   /* row 0 there */
            r3f.sky_yb = r3f.hor + (int)(((8 << 16) + r3f.sky_dv - 1) / r3f.sky_dv);
        }
    }

    /* map */
    r3f.map = m;
    r3f.cells = m->cells;
    r3f.mw = m->w;
    r3f.mh = m->h;
    r3f.maxd = (uint32_t)R3D_MAXDIST << 16;
    if (m->def != cache_mapdef || m->w != cache_mw || m->h != cache_mh || frame_no == 0)
        setup_map(m);
    if (m->ambient != cache_amb) setup_fade(m->ambient);

    /* colormaps, textures, sky */
    setup_colormaps();
    memset(r3d_texc, 0, sizeof(r3d_texc));
    vtex_update();
    r3f.time = v->time;
    r3f.sky = sky_pixels(m->sky, v->time);
    if (!r3f.sky) r3f.sky = gba_missing_tex;
    r3f.skyang = a;
    r3f.frame = ++frame_no;
    r3f.cp_over = 0;

    r3d_columns();
    t1 = gba_cycles();
    t2 = t1;
    draw_sprites(v);
    if (v->tint > TINT_NONE && v->tint < TINT_COUNT && v->tint_level > 0)
        r3d_tint_pass(doomo_tintmap[v->tint], v->tint_level > 16 ? 16 : v->tint_level);
    t3 = gba_cycles();

    r3d_stats.cycles_cols = t1 - t0;
    r3d_stats.cycles_planes = t2 - t1;
    r3d_stats.cycles_sprites = t3 - t2;
    r3d_stats.cycles_total = t3 - t0;
    r3d_stats.planes = 0;
    r3d_stats.spans = (uint16_t)(r3f.dbg_flatpx > 65535 ? 65535 : r3f.dbg_flatpx);
    r3d_stats.events_overflow = r3f.cp_over;
    r3d_stats.columns = (uint16_t)r3f.ncol;
    r3d_dbg[0] = r3f.dbg_steps; r3d_dbg[1] = r3f.dbg_facepx;
    r3d_dbg[2] = r3f.dbg_skypx; r3d_dbg[3] = r3f.dbg_flatpx;
}
