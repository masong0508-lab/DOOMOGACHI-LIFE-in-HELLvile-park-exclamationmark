static inline int32_t isin(int a) { return gba_sin16[a & 4095]; }
static inline int32_t icos(int a) { return gba_sin16[(a & 4095) + 1024]; }

/* angle (4096 units, -1023..1023) whose tangent is t (16.16) */
static int iatan16(int32_t t)
{
    int lo = -1023, hi = 1023;
    while (lo < hi) {
        int mid = (lo + hi + 1) >> 1;
        /* tan(mid) <= t  <=>  sin(mid) <= t * cos(mid) (cos > 0) */
        int64_t lhs = (int64_t)isin(mid) << 16;
        int64_t rhs = (int64_t)t * icos(mid);
        if (lhs <= rhs) lo = mid;
        else hi = mid - 1;
    }
    return lo;
}

const uint8_t *r3d_texture(int id)
{
    const uint8_t *t = texture_pixels(id, r3f.time);
    if (!t) t = gba_missing_tex;
    r3d_texc[id & (R3D_MAXTEX - 1)] = t;
    return t;
}

uint8_t r3d_texavg(int id)
{
    uint8_t a;
    id &= R3D_MAXTEX - 1;
    a = r3d_avgc[id];
    if (!a) {
        a = texture_avg(id);
        if (!a) {
            /* derive from the pixels: the centre texel is a fair guess */
            const uint8_t *t = r3d_texc[id] ? r3d_texc[id] : r3d_texture(id);
            a = t[32 * 64 + 32] ? t[32 * 64 + 32] : 4;
        }
        r3d_avgc[id] = a;
    }
    return a;
}

