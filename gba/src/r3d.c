/* r3d.c - plat_view3d(): the GBA height raycaster (owner: gba).
 *
 * "Not just Wolfenstein": every cell has its own floor and ceiling
 * height, so the world has stairs, ledges, pits, platforms, low
 * ceilings, lifts, doors and blocks you can look over. Per frame:
 *
 *   1. setup (THUMB, here): camera basis, y-shearing horizon for pitch,
 *      distance fade for the map's ambient light, composed colormaps for
 *      tints, per-frame texture cache (animated textures resolve once).
 *   2. column pass (ARM/IWRAM, r3d.iwram.c): 120 rays (2-pixel columns),
 *      front to back with Doom-style per-column clip windows; risers,
 *      upper faces, walls and blocks drawn as textured columns, sky as
 *      the background, floors/ceilings collected into visplanes, and a
 *      window checkpoint list per column for sprite clipping.
 *   3. plane pass (ARM): visplanes -> horizontal spans, constant depth per
 *      span (per-row distance light, linear texture stepping).
 *   4. sprites: transformed + z-sorted here, drawn far to near by ARM
 *      code, each column clipped against the window at its depth.
 *
 * Fixed point throughout; 1/z from a 32K-entry ROM table (gba_tables.c,
 * generated by tools/mktables.py).
 */
