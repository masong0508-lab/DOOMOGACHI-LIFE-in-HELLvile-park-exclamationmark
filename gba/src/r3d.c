/* VRAM texture cache. Texels fetched from the cartridge cost 6 cycles,
 * from VRAM 3: the free OBJ tile VRAM of the bitmap modes (16 KB at
 * 0x06014000, no hardware sprites inside a 3D view) holds the 4 textures that
 * covered the most pixels in the previous frame. The pixel loops only
 * read it (VRAM ignores byte writes, not byte reads). Animated textures
 * are re-copied when their frame changes. */
#define VTEX_SLOTS 4
#define VTEX_BASE  ((uint8_t *)0x06014000)
#define VTEX_SIZE  DOOMO_TEX_SIZE_PX
static uint8_t vtex_id[VTEX_SLOTS];              /* texture id + 1, 0 = free */
static const uint8_t *vtex_src[VTEX_SLOTS];

static void vtex_update(void)
{
    int best[VTEX_SLOTS], i, k, n = 0;
    /* OBJ VRAM is shared with obj.c's squash OBJs (SPEC C7.4) */
    if (gba_objvram_claim(OBJV_R3D) != OBJV_R3D) memset(vtex_id, 0, sizeof(vtex_id));
    /* the most drawn textures of the last frame (at least 256 pixels) */
    for (k = 0; k < VTEX_SLOTS; k++) best[k] = -1;
    for (i = 1; i < R3D_MAXTEX; i++) {
        uint32_t px = r3d_texpix[i];
        if (px < 256) continue;
        for (k = 0; k < VTEX_SLOTS; k++) {
            if (best[k] < 0 || px > r3d_texpix[best[k]]) {
                int j;
                for (j = VTEX_SLOTS - 1; j > k; j--) best[j] = best[j - 1];
                best[k] = i;
                break;
            }
        }
    }
    for (k = 0; k < VTEX_SLOTS; k++) if (best[k] >= 0) n++;
    /* free the slots whose texture dropped out */
    for (i = 0; i < VTEX_SLOTS; i++) {
        int keep = 0;
        for (k = 0; k < n; k++) if (vtex_id[i] == best[k] + 1) keep = 1;
        if (!keep) vtex_id[i] = 0;
    }
    /* place the newcomers */
    for (k = 0; k < n; k++) {
        int have = 0;
        for (i = 0; i < VTEX_SLOTS; i++) if (vtex_id[i] == best[k] + 1) have = 1;
        if (have) continue;
        for (i = 0; i < VTEX_SLOTS; i++)
            if (!vtex_id[i]) { vtex_id[i] = (uint8_t)(best[k] + 1); vtex_src[i] = NULL; break; }
    }
    /* copy what changed, point the frame's texture cache at the copies */
    for (i = 0; i < VTEX_SLOTS; i++) {
        int id = vtex_id[i] - 1;
        const uint8_t *src;
        uint8_t *dst = VTEX_BASE + i * VTEX_SIZE;
        if (id < 0) continue;
        src = view_texture_pixels(id);
        if (!src) { vtex_id[i] = 0; continue; }
        if (src != vtex_src[i]) {
            if (((uintptr_t)src & 3) == 0) dma3_copy32(dst, src, VTEX_SIZE / 4);
            else { vtex_id[i] = 0; continue; }
            vtex_src[i] = src;
        }
        r3d_texc[id] = dst;
    }
    memset(r3d_texpix, 0, sizeof(r3d_texpix));
}

/* Resolve the shared starting sector once in ROM. Door and lift cells
 * still read their actual moving heights for this frame. */
static void setup_ray_start(RayStart *start)
{
    int cx = r3f.ex >> 22, cy = r3f.ey >> 22;
    const DoomoCell *cell;
    const uint32_t *words;
    uint32_t w0, w1;
    start->idx8 = -1;
    if ((unsigned)cx >= (unsigned)r3f.mw || (unsigned)cy >= (unsigned)r3f.mh) return;
    start->px = r3f.ex >> 6;
    start->py = r3f.ey >> 6;
    start->idx8 = (cy * r3f.mw + cx) * sizeof(*cell);
    cell = &r3f.cells[cy * r3f.mw + cx];
    words = (const uint32_t *)cell;
    w0 = words[0]; w1 = words[1];
    if (cell->flags & (CELL_DOOR | CELL_LIFT)) {
        start->floor = map_floor_z(r3f.map, cx, cy) * 16;
        start->ceil = map_ceil_z(r3f.map, cx, cy) * 16;
    } else {
        start->floor = cell->floor_h * 128;
        start->ceil = cell->ceil_h * 128;
    }
    start->floor_tex = cell->floor_tex;
    start->ceil_tex = cell->ceil_tex;
    start->light = cell->light ? cell->light : r3f.amb;
    start->sky = cell->ceil_tex == DOOMO_TEX_SKY;
    start->c0 = (cell->wall || (cell->flags & (CELL_DOOR | CELL_LIFT))) ? UINT32_MAX : w0;
    start->c1 = w1;
}

void plat_view3d(const DoomoView3D *v)
{
    uint32_t t0, t1, t2, t3, collect_cycles = 0;
    DoomoView3D resolved;
    RayStart start;
    uint16_t bins[WALL_BIN_N];
    unsigned far = UINT16_MAX;
    int vx, vy, vw, vh, detail = 0;
    int a, bone;
    const DoomoMap *m;
    ViewQuality *q;
    if (gba_nodraw == 1 || !v || !v->map) return;
    if (gba_nodraw) {                         /* G5: the view draws into a page */
        cv_need_m4();
        if (gba_nodraw == 1) return;
        if (gba_nodraw == GBA_NODRAW_FIRST) gba_nodraw = 0;
    }
    /* r3d.iwram.c + r3d_loops.s live in the IWRAM overlay slot (G4) */
    iwram_ovl_use(OVL_3D);
    gba_big_claim(GBA_BIG_BY_R3D);
    t0 = gba_cycles();
    m = v->map;
    bone = bone_readability_map(m->def);
    r3f.indoors = (uint8_t)(bone && (v->collect_sprites || doomo_view_under_roof(v)));
    r3f.interior_quality = (uint8_t)(r3f.indoors && room_quality(v));
    q = &view_quality[r3f.interior_quality];
    /* Scene changes invalidate cost estimates from the previous level:
     * otherwise entering an intricate map may inherit its 4x fallback. */
    if (gov_mapdef != m->def) {
        gov_mapdef = m->def;
        memset(view_quality, 0, sizeof(view_quality));
        view_quality[0].backoff = view_quality[1].backoff = 16;
        /* A new interior begins at 120x80, then follows the measured room cost. */
        view_quality[1].detail = 1;
    }

    /* viewport: even x / width (2-pixel columns), clipped to the screen */
    vx = v->vx & ~1;
    vy = v->vy;
    vw = (v->vw + (v->vx & 1)) & ~1;
    vh = v->vh;
    if (vx < 0) { vw += vx; vx = 0; }
    if (vy < 0) { vh += vy; vy = 0; }
    if (vx + vw > SCREEN_W) vw = SCREEN_W - vx;
    if (vy + vh > SCREEN_H) vh = SCREEN_H - vy;
    if (vw < 8 || vh < 8) return;
    view_hold_drop();                         /* (S2-2) VRAM the copy lives in is the raycaster's again */
    r3d_last_x = (int16_t)vx; r3d_last_y = (int16_t)vy; r3d_last_w = (int16_t)vw; r3d_last_h = (int16_t)vh;
    r3d_last_frame = gba_frames;
    /* 2x: 120x80, 4x: 60x40 for a full-screen view. Both use the same
     * Mode 4 page; the UI is rendered afterwards at its original size.
     * 4x is legal only with whole 4-pixel blocks and enough view area. */
#if !defined(ENGINE_TEST)
    if (!(vx & 3) && !(vw & 3) && !(vh & 1) && vw >= 32 && vh >= 32) {
        detail = view_half(q) ? 1 : 0;
        if (detail && q->detail == 2 && opt_get(OPT_3D_FAST) == OPT3D_BALANCED &&
            !(vx & 7) && !(vw & 7) && !(vh & 3) && vw >= 64 && vh >= 64)
            detail = 2;
    }
#endif
    if (q->detail >= 3 && vx == 0 && vy == 0 && vw == SCREEN_W && vh == SCREEN_H &&
        bone && opt_get(OPT_3D_FAST) == OPT3D_BALANCED) {
        detail = q->detail;
        vw = detail == 3 ? 96 : 80;
        vh = detail == 3 ? 64 : 54;
    } else if (detail) { vw >>= detail; vh >>= detail; }
    gba_view3d_frame = (uint8_t)(detail + 1);
    /* The full tier stores both samples directly. The Bone scaling tiers
     * expand each sample separately. */
    r3f.pair_wall = bone && detail != 2;
    {
        int fov = opt_get(OPT_FOV);
        if (vw != cache_vw || vh != cache_vh || fov != cache_fov) setup_viewport(vw, vh, fov);
    }
    r3f.dst = gba_back + vy * (SCREEN_W / 2) + (vx >> 1);

    /* camera */
    a = v->angle & 4095;
    r3f.fx = icos(a);
    r3f.fy = isin(a);
    r3f.rx = -isin(a);
    r3f.ry = icos(a);
    r3f.rxpp = (int32_t)(((int64_t)r3f.rx * (int64_t)r3f.invproj) >> 16);
    r3f.rypp = (int32_t)(((int64_t)r3f.ry * (int64_t)r3f.invproj) >> 16);
    r3f.ex = v->x;
    r3f.ey = v->y;
    r3f.ez = v->z + ((int32_t)v->bob << 16);
    r3f.ez4 = r3f.ez >> 12;
    {
        /* look up/down: y-shearing, pitch * focal * 0.84 / 256 rows */
        int p = v->pitch;
        int off, lim = R3D_KROWS - vh / 2 - 8;
        if (p > 256) p = 256;
        if (p < -256) p = -256;
        off = (p * r3f.proj * 84) / (256 * 100);
        if (off > lim) off = lim;
        if (off < -lim) off = -lim;
        r3f.hor = vh / 2 + off;
        r3f.hor12 = r3f.hor << 12;
        /* sky: 88 rows over 3/4 of the view height above the horizon */
        {
            int span = vh * 3 / 4;
            r3f.sky_dv = (88 << 16) / (span ? span : 1);
            r3f.sky_ya = r3f.hor - span;                   /* row 0 there */
            r3f.sky_yb = r3f.hor + (int)(((8 << 16) + r3f.sky_dv - 1) / r3f.sky_dv);
        }
    }

    /* map */
    r3f.map = m;
    r3f.cells = m->cells;
    r3f.mw = m->w;
    r3f.mh = m->h;
    {   /* (LV4) per-level view distance: a short one stops the ray walk early (the floor and ceiling run to
         * the horizon there); 0 or out of range = R3D_MAXDIST, the same frames as before */
        uint32_t vd = v->view_dist;
        if (vd < R3D_MINDIST || vd > R3D_MAXDIST) vd = R3D_MAXDIST;
        /* GBA-only compact Bone presentation. Rendering 40-cell-long
         * outdoor/nave sightlines costs far more than the extra stone
         * detail is worth at 96x64. Keep recognizable nearby facades
         * and the actual full-sized walkable map; limit only the rays
         * (and sprites beyond the same horizon). Max detail gets a
         * longer panorama, Balanced/Smooth favor playable frame pacing.
         * No changes to AI, targeting, collisions, goals or map data. */
        if (bone) {
            int cathedral = m->def == doomo_maps[MAPID_BONE_CATHEDRAL];
            /* The Cathedral alone still spends ~51-54ms per frame and
             * falls into the 80x54 emergency scaler, blurring its skulls,
             * arches and stained-glass silhouettes. Its 48x56 map has
             * long decoration-only sightlines. Render the closest 14
             * cells in Balanced/Smooth and 12 in emergency, but leave
             * the actual 3D map, physics, AI, doors and exit untouched.
             * This may help the governor reach the sharper 96x64 tier.
             * Keep the Capital and manual Max quality budgets intact. */
            uint32_t cap = (opt_get(OPT_3D_FAST) == OPT3D_MAX) ? 26u :
                           (cathedral ? (detail == 4 ? 12u : 14u) :
                            (detail == 4 ? 16u : 20u));
            if (vd > cap) vd = cap;
        }
        /* Graveyard's long outdoor rays are still costly at quarter
         * detail. Shorten the render horizon only in Balanced's fallback. */
        if (detail == 2 && vd > 16 && m->def == doomo_maps[MAPID_GRAVEYARD_SHIFT])
            vd = 16;
        r3f.maxd = vd << 16;
    }
    if (m->def != cache_mapdef || m->w != cache_mw || m->h != cache_mh || frame_no == 0)
        setup_map(m);
    if (m->ambient != cache_amb || m->def != cache_fade_mapdef)
        setup_fade(m->ambient, m->def);

    /* colormaps, textures, sky */
    setup_colormaps();
    memset(r3d_texc, 0, sizeof(r3d_texc));
    vtex_update();
    r3f.time = v->time;
    r3f.sky = bone && m->sky == SKY_HELL ? bone_sky_pixels : sky_pixels(m->sky, v->time);
    if (!r3f.sky) r3f.sky = gba_missing_tex;
    r3f.skyang = a;
    r3f.frame = ++frame_no;
    r3f.cp_over = 0;

    /* The low-resolution Bone tiers use the average-colour floor beyond
     * a minification cutoff: this prevents checkerboard shimmer near the
     * horizon. Preserve recognisable carpet/road texture a little farther
     * (768 rather than 640 world units) before switching to the average.
     * Full resolution, other levels and view distance stay untouched.
     * No extra rays, textures or allocations; reassess the extra floor
     * sampling in the GBA emulator census before increasing it further. */
    FL.far = ((detail == 1 || detail == 3 || detail == 4) && bone &&
              opt_get(OPT_3D_FAST) == OPT3D_BALANCED ? 768u : 1400u) << 8;
    setup_ray_start(&start);
    r3d_columns(&start);
    t1 = gba_cycles();
    t2 = t1;
    r3d_stats.occluded_sprites = 0;
    if (r3f.indoors) far = wall_depth_bounds(bins);
    if (v->collect_sprites) {
        fix16 limit = far == UINT16_MAX ? INT32_MAX : (fix16)(far << 13) + INT2FIX(1);
        uint32_t start = gba_cycles();
        resolved = *v;
        r3d_stats.occluded_sprites = (uint16_t)v->collect_sprites(&resolved, limit);
        collect_cycles = gba_cycles() - start;
        v = &resolved;
    }
    draw_sprites(v, bone, r3f.indoors ? bins : NULL, far);
    if (v->tint > TINT_NONE && v->tint < TINT_COUNT && v->tint_level > 0) {
        /* Unlike the old 4x4 per-pixel ordered dither, a subtle palette
         * lerp never paints isolated red/purple dots over stonework when
         * the player is hurt. Let postfx_vblank blend the whole finished
         * image, including the HUD, uniformly at just 1..3 of 16.
         * No framebuffer scan, extra RAM or texture-detail loss.
         * It also avoids the full-view tint pass on every hit frame. */
        static const uint8_t colors[TINT_COUNT] = {
            PAL_BLACK, PAL_UI_RED, PAL_UI_GOLD, PAL_UI_MINT,
            PAL_UI_PURPLE, PAL_BLACK
        };
        int strength = ((int)v->tint_level + 3) >> 2;
        if (strength > 3) strength = 3;
        plat_post_blend(colors[v->tint], strength);
    }
    if (detail == 4) {
        r3d_up3(r3f.dst);
    } else if (detail == 3) {
        r3d_up5x2(r3f.dst);
    } else if (detail == 2) {
        /* Exact one-pass 4x expansion: avoids the 120x80 intermediate
         * VRAM write/read of two consecutive r3d_up2 calls. */
        r3d_up4(r3f.dst, vw >> 1, vh);
    } else if (detail == 1) {
        r3d_up2(r3f.dst, vw >> 1, vh);
    }
    t3 = gba_cycles();

    q->cost[detail] = t3 - t0 - collect_cycles;      /* renderer cost, excluding core actor work */
    r3d_stats.cycles_cols = t1 - t0;
    r3d_stats.cycles_planes = t2 - t1;
    r3d_stats.cycles_sprites = t3 - t2 - collect_cycles;
    r3d_stats.cycles_total = q->cost[detail];
    r3d_stats.planes = 0;
    r3d_stats.spans = (uint16_t)(r3f.dbg_flatpx > 65535 ? 65535 : r3f.dbg_flatpx);
    r3d_stats.events_overflow = r3f.cp_over;
    r3d_stats.columns = (uint16_t)r3f.ncol;
    r3d_stats.indoors = r3f.indoors;
    r3d_dbg[0] = r3f.dbg_steps; r3d_dbg[1] = r3f.dbg_facepx;
    r3d_dbg[2] = r3f.dbg_skypx; r3d_dbg[3] = r3f.dbg_flatpx;
}
