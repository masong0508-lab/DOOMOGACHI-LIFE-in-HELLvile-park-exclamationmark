#!/usr/bin/env python3
"""mktables.py - generate the GBA renderer's constant lookup tables
(owner: gba). Stdlib only, deterministic.

    python3 gba/tools/mktables.py OUT.c

Tables (all const -> ROM, they cost no RAM):
  gba_sin16[5120]     sin(i * 2pi / 4096) in 16.16, i = 0..5119, so
                      cos(a) = gba_sin16[(a & 4095) + 1024]
  gba_recip8[32768]   2^26 / i  (i = a distance in 1/8 world units,
                      clamped to i >= 8): the renderer's 1/z table
  gba_missing_tex     64x64 checker for textures the core cannot supply
"""
import math
import sys

def main():
    if len(sys.argv) != 2:
        sys.exit("usage: mktables.py OUT.c")
    out = []
    w = out.append
    w("/* gba_tables.c - GENERATED by gba/tools/mktables.py. Do not edit. */")
    w("#include <stdint.h>")
    w("")
    w("const int32_t gba_sin16[5120] = {")
    row = []
    for i in range(5120):
        v = int(round(math.sin(i * 2.0 * math.pi / 4096.0) * 65536.0))
        row.append("%d" % v)
        if len(row) == 12:
            w("    " + ", ".join(row) + ",")
            row = []
    if row:
        w("    " + ", ".join(row) + ",")
    w("};")
    w("")
    w("const uint32_t gba_recip8[32768] = {")
    row = []
    for i in range(32768):
        j = max(i, 8)
        row.append("%du" % ((1 << 26) // j))
        if len(row) == 10:
            w("    " + ", ".join(row) + ",")
            row = []
    if row:
        w("    " + ", ".join(row) + ",")
    w("};")
    w("")
    # 64x64 "missing texture" checker (pink / dark pink, palette.h UI
    # colours 6 and 7) used when the core returns no pixels.
    w("const uint8_t gba_missing_tex[64 * 64] = {")
    for y in range(64):
        w("    " + ",".join("6" if ((x >> 3) ^ (y >> 3)) & 1 else "7"
                             for x in range(64)) + ",")
    w("};")
    w("")
    with open(sys.argv[1], "w") as f:
        f.write("\n".join(out))

if __name__ == "__main__":
    main()
