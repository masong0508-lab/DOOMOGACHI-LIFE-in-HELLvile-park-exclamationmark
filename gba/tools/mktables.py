#!/usr/bin/env python3
"""mktables.py - generate the GBA renderer's constant lookup tables
(owner: gba). Stdlib only, deterministic.

    python3 gba/tools/mktables.py OUT.c

Tables (all const -> ROM, they cost no RAM):
  gba_sin16[5120]     sin(i * 2pi / 4096) in 16.16, i = 0..5119, so
                      cos(a) = gba_sin16[(a & 4095) + 1024]
  gba_recip8[32768]   2^26 / i  (i = a distance in 1/8 world units,
                      clamped to i >= 8): the renderer's 1/z table
  gba_viewport_presets  projection tables for the standard 3D widths
  gba_missing_tex     64x64 checker for textures the core cannot supply
"""
import math
import sys


def column_angle(sine, offset):
    lo, hi = -1023, 1023
    while lo < hi:
        mid = (lo + hi + 1) // 2
        idx = mid & 4095
        if (sine[idx] << 16) <= offset * sine[idx + 1024]:
            lo = mid
        else:
            hi = mid - 1
    return lo


def viewport_presets(write, sine):
    widths = (60, 80, 96, 120, 240)
    planes = (36000, 43250, 52000)
    write(f"DOOMO_STATIC_ASSERT(R3D_VIEWPORT_PRESET_N == {len(widths)}, viewport_preset_count);")
    write("DOOMO_STATIC_ASSERT(R3D_KROWS == 256, viewport_preset_rows);")
    write("const uint8_t gba_viewport_widths[R3D_VIEWPORT_PRESET_N] = { "
          + ", ".join(map(str, widths)) + " };")
    write("")
    for width in widths:
        ncol = width // 2
        for fov, plane in enumerate(planes):
            proj = (ncol << 16) // plane
            x = [2 * c + 1 - ncol for c in range(ncol)]
            # C truncates negative division toward zero.
            colt = [(abs(v) * 65536 // proj) * (-1 if v < 0 else 1) for v in x]
            for ctype, name, values in (("int32_t", "colt", colt),
                                        ("int16_t", "colang", [column_angle(sine, v) for v in colt])):
                write(f"static const {ctype} {name}_{width}_{fov}[{ncol}] = {{")
                for i in range(0, len(values), 12):
                    write("    " + ", ".join(map(str, values[i:i + 12])) + ",")
                write("};")
                write("")
    write("const R3DViewportPreset gba_viewport_presets[R3D_VIEWPORT_PRESET_N][3] = {")
    for width in widths:
        write("    {")
        for fov, plane in enumerate(planes):
            proj = ((width // 2) << 16) // plane
            rowk = [(proj << 17) // (2 * y + 1) for y in range(256)]
            write(f"        {{ .proj = {proj}, .invproj = {0xFFFFFFFF // proj}u,")
            write(f"          .colt = colt_{width}_{fov}, .colang = colang_{width}_{fov},")
            write("          .rowk = {")
            for i in range(0, len(rowk), 12):
                write("            " + ", ".join(map(str, rowk[i:i + 12])) + ",")
            write("          },")
            write("        },")
        write("    },")
    write("};")
    write("")


def main():
    if len(sys.argv) != 2:
        sys.exit("usage: mktables.py OUT.c")
    out = []
    w = out.append
    w("/* gba_tables.c - GENERATED by gba/tools/mktables.py. Do not edit. */")
    w('#include "r3d_int.h"')
    w("")
    sine = [round(math.sin(i * 2.0 * math.pi / 4096.0) * 65536.0) for i in range(5120)]
    w("const int32_t gba_sin16[5120] = {")
    row = []
    for v in sine:
        row.append("%d" % v)
        if len(row) == 12:
            w("    " + ", ".join(row) + ",")
            row = []
    if row:
        w("    " + ", ".join(row) + ",")
    w("};")
    w("")
    w("const uint32_t gba_recip8[32768] = {")
    row = []
    for i in range(32768):
        j = max(i, 8)
        row.append("%du" % ((1 << 26) // j))
        if len(row) == 10:
            w("    " + ", ".join(row) + ",")
            row = []
    if row:
        w("    " + ", ".join(row) + ",")
    w("};")
    w("")
    viewport_presets(w, sine)
    # 64x64 "missing texture" checker (pink / dark pink, palette.h UI
    # colours 6 and 7) used when the core returns no pixels.
    w("const uint8_t gba_missing_tex[64 * 64] = {")
    for y in range(64):
        w("    " + ",".join("6" if ((x >> 3) ^ (y >> 3)) & 1 else "7"
                             for x in range(64)) + ",")
    w("};")
    w("")
    with open(sys.argv[1], "w") as f:
        f.write("\n".join(out))

if __name__ == "__main__":
    main()
