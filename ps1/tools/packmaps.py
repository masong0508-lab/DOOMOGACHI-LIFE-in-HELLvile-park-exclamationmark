#!/usr/bin/env python3
"""packmaps.py - keep the maps' cell grids LZ-compressed in PS1 RAM
(owner: ps1). Stdlib only, deterministic.

    packmaps.py OUT_DIR core/gen/map_*.c

The 12 maps' cell grids are ~270 KB of const data, and the core only ever
reads them in one place: map.c copies a map's cells into the live map
(doomo_map) when it loads it, through map_def_cells() (map.h). So the PS1
build compiles a copy of every core/gen/map_<name>.c whose
`cells_<name>[]` array is replaced by its LZ-compressed bytes (the save
codec's format, packart.py), and DoomoMapDef.cells points at those bytes.
ps1/src/packart.c overrides map_def_cells() and decodes them straight
into the live map. Blob layout: "LZMC", u32 cell count, LZ stream.
"""
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from packart import lz, unlz, c_bytes  # noqa: E402

CELL = 8   # sizeof(DoomoCell)


def pack_file(src, dst):
    text = open(src).read()
    m = re.search(r"^static const DoomoCell (cells_\w+)\[(\d+)\] = \{\n", text, re.M)
    if not m:
        raise SystemExit("packmaps: %s: no cells array" % src)
    name, count = m.group(1), int(m.group(2))
    end = text.index("\n};\n", m.end())
    body = re.sub(r"/\*.*?\*/", "", text[m.end():end], flags=re.S)
    vals = [int(v) for v in re.findall(r"-?\d+", body)]
    if len(vals) != count * CELL:
        raise SystemExit("packmaps: %s: %d values for %d cells" % (src, len(vals), count))
    raw = bytes(v & 0xFF for v in vals)        # int8 heights as bytes
    blob = lz(raw)
    assert unlz(blob, len(raw)) == raw
    head = b"LZMC" + count.to_bytes(4, "little")
    packed = ("/* %s: LZ-packed for the PS1 (ps1/tools/packmaps.py); map_def_cells()\n"
              " * in ps1/src/packart.c decodes it into the live map */\n"
              "static const unsigned char %s_lz[%d] __attribute__((aligned(4))) = {\n%s\n};\n"
              "#define %s ((const DoomoCell *)(const void *)%s_lz)\n" % (
                  name, name, len(head) + len(blob), c_bytes(head + blob), name, name))
    out = text[:m.start()] + packed + text[end + 4:]
    with open(dst, "w") as f:
        f.write("/* generated by ps1/tools/packmaps.py from %s - do not edit */\n" %
                os.path.basename(src))
        f.write(out)
    return len(raw), len(head) + len(blob)


def main(argv):
    if len(argv) < 3:
        print(__doc__)
        return 2
    out_dir = argv[1]
    os.makedirs(out_dir, exist_ok=True)
    raw = packed = 0
    for src in sorted(argv[2:]):
        r, p = pack_file(src, os.path.join(out_dir, os.path.basename(src)))
        raw += r
        packed += p
    print("packmaps: %d maps, cells %d KB -> %d KB" % (len(argv) - 2, raw // 1024, packed // 1024))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
