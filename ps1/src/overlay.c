/* overlay.c - scene code overlays, read from the disc (owner: ps1).
 *
 * The whole EXE has to fit in the console's 2 MB of RAM, and the game's
 * scenes no longer do. Most of their code only runs while its own scene
 * is on screen, so the game disc links it into OVERLAYS: groups of code
 * and const data (tools/ovl_plan.py decides what may go where, from the
 * relocations of the object files) that all share ONE address range, the
 * slot after the BSS. tools/ovl_pack.py writes the groups to OVL.BIN on
 * the disc; this file reads the group a scene needs into the slot.
 *
 * The core's scene.c brackets every call into a scene with
 * plat_scene_code() / plat_scene_code_end() (scene.h):
 *
 *   - before the call, the scene's group is loaded if it is not there;
 *   - after it, when the call came from inside another scene (a scene
 *     switched from its update()), the caller's group is loaded back, so
 *     the caller's code is there again when the call returns.
 *
 * Everything that is not reached only through a scene's four entry
 * points stays resident (ovl_plan.py), so nothing else ever calls into
 * the slot. A load is ~0.1-0.3 s at 2x CD speed; it happens when a scene
 * of another group starts (three loads when a scene starts another one:
 * the new group, the caller's back, then the new one again next frame).
 */
#include <string.h>
#include <psxapi.h>
#include <psxcd.h>
#include "ps1.h"

#ifdef DOOMO_OVERLAYS

/* generated by ovl_plan.py (ovl_table.c) */
extern const DoomoScene *const ps1_ovl_scene[];
extern const unsigned char ps1_ovl_scene_grp[];
extern const unsigned ps1_ovl_ngroups;
extern const char *const ps1_ovl_name[];
/* the slot (linker script) */
extern uint8_t __ovl_slot[], __ovl_slot_end[];

#define OVL_MAGIC   0x4C564F44u          /* "DOVL" */
#define OVL_MAXG    32

typedef struct OvlGroup { uint32_t sector, bytes; } OvlGroup;

static OvlGroup s_grp[OVL_MAXG + 1];
static int      s_lba = -1;              /* OVL.BIN on the disc          */
static int      s_cur;                   /* group in the slot, 0 = none  */
static int      s_depth;                 /* nesting of scene calls       */
static uint32_t s_loads;

static int group_of(const DoomoScene *s)
{
    int i;
    for (i = 0; ps1_ovl_scene[i]; i++)
        if (ps1_ovl_scene[i] == s)
            return ps1_ovl_scene_grp[i];
    return 0;
}

static int read_sectors(int lba, int n, void *dst)
{
    CdlLOC loc;
    int tries;
    for (tries = 0; tries < 4; tries++) {
        CdIntToPos(lba, &loc);
        if (!CdControl(CdlSetloc, &loc, 0))
            continue;
        if (!CdRead(n, (uint32_t *)dst, CdlModeSpeed))
            continue;
        if (CdReadSync(0, 0) >= 0)
            return 1;
    }
    return 0;
}

static void load(int g)
{
    uint32_t t0 = timer_us(), n;
    if (g < 1 || g > (int)ps1_ovl_ngroups || s_lba < 0) {
        dbg("ovl: cannot load group %d (no OVL.BIN)\n", g);
        s_cur = 0;
        return;
    }
    n = (s_grp[g].bytes + 2047) / 2048;
    while (!read_sectors(s_lba + (int)s_grp[g].sector, (int)n, __ovl_slot)) {
        dbg("ovl: read error, group %d (%s), retrying\n", g, ps1_ovl_name[g]);
        VSync(30);
    }
    FlushCache();                         /* new code in the slot */
    s_cur = g;
    s_loads++;
    dbg("ovl: %s (%u KB) in %u ms\n", ps1_ovl_name[g], (unsigned)(s_grp[g].bytes / 1024),
        (unsigned)((timer_us() - t0) / 1000));
}

int plat_scene_code(const DoomoScene *s)
{
    int prev = s_cur, g = group_of(s);
    s_depth++;
    if (g && g != s_cur)
        load(g);
    return prev;
}

void plat_scene_code_end(int prev)
{
    s_depth--;
    /* still inside a scene call: that scene's code must be back */
    if (s_depth > 0 && prev && prev != s_cur)
        load(prev);
}

uint32_t overlay_loads(void) { return s_loads; }

void overlay_init(void)
{
    CdlFILE f;
    uint32_t *h = (uint32_t *)__ovl_slot;     /* empty until the first load */
    uint32_t slot = (uint32_t)(__ovl_slot_end - __ovl_slot), i, n;
    if (!CdInit()) {
        dbg("ovl: no CD drive\n");
        return;
    }
    if (!CdSearchFile(&f, "\\OVL.BIN;1")) {
        dbg("ovl: OVL.BIN not found on the disc\n");
        return;
    }
    if (!read_sectors(CdPosToInt(&f.pos), 1, h)) {
        dbg("ovl: cannot read OVL.BIN\n");
        return;
    }
    n = h[2];
    if (h[0] != OVL_MAGIC || n != ps1_ovl_ngroups || n > OVL_MAXG ||
        h[3] != (uint32_t)__ovl_slot || h[4] > slot) {
        dbg("ovl: OVL.BIN does not match this EXE (magic %08x, %u groups, slot %08x)\n",
            (unsigned)h[0], (unsigned)n, (unsigned)h[3]);
        return;
    }
    for (i = 1; i <= n; i++) {
        s_grp[i].sector = h[4 + i * 2 - 1];
        s_grp[i].bytes = h[4 + i * 2];
        if (s_grp[i].bytes > slot) {
            dbg("ovl: group %u is bigger than the slot\n", (unsigned)i);
            return;
        }
    }
    s_lba = CdPosToInt(&f.pos);
    s_cur = 0;
    dbg("ovl: %u groups, slot %u KB at %08x\n", (unsigned)n, (unsigned)(slot / 1024),
        (unsigned)(uint32_t)__ovl_slot);
}

#else  /* engine test: everything is resident */

void overlay_init(void) {}
uint32_t overlay_loads(void) { return 0; }

#endif
