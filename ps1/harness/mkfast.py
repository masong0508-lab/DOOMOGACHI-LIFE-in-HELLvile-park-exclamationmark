#!/usr/bin/env python3
"""mkfast.py - write fast-movement 3D stress scripts (run.py / GBA harness format).

Each script holds forward + strafe + turn at full speed, does quick 180s and
wall/corner hugging, and takes a screenshot every STEP game frames, so holes,
popping and stale frames show up frame by frame.
usage: mkfast.py OUT.txt SCENE ARG [--tp] [--step N] [--prefix P]
"""
import sys


def main():
    a = sys.argv[1:]
    out, scene, arg = a[0], a[1], a[2]
    tp = "--tp" in a
    step = int(a[a.index("--step") + 1]) if "--step" in a else 2
    pre = a[a.index("--prefix") + 1] if "--prefix" in a else "f"
    lines = ["# fast-movement stress: %s %s%s (generated by mkfast.py)"
             % (scene, arg, " third-person" if tp else ""),
             "scene %s %s" % (scene, arg), "wait 90"]
    if tp:
        lines += ["press SELECT", "wait 20"]
    n = [0]

    def seg(keys, frames):
        for k in keys:
            lines.append("down " + k)
        for _ in range(frames // step):
            lines.append("wait %d" % step)
            lines.append("shot %s_%04d" % (pre, n[0]))
            n[0] += 1
        lines.append("release")

    lines.append("fps fast")
    seg(["UP", "R", "RIGHT"], 60)      # forward + strafe + turn
    seg(["UP", "RIGHT"], 24)           # quick 180
    seg(["UP", "L", "LEFT"], 60)
    seg(["LEFT"], 24)                  # spin in place
    seg(["UP"], 60)                    # run into a wall, keep pushing
    seg(["UP", "R"], 40)               # slide along it into the corner
    seg(["UP", "L", "RIGHT"], 60)
    seg(["DOWN", "LEFT"], 40)          # backpedal turning
    lines.append("fpsend fast")
    open(out, "w").write("\n".join(lines) + "\n")


main()
