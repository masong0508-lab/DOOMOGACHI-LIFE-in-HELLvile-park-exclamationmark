#!/usr/bin/env python3
"""mkperf.py - build ps1/harness/scripts/perf_*.txt from the core scripts.

Each perf script plays a core runner script up to a marker line, then
measures the presented frame rate (fps/fpsend) of the scene it reached.
usage: python3 ps1/harness/mkperf.py   (from the repo root)
"""
import os

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..")
CORE = os.path.join(ROOT, "core", "tests", "scripts")
OUT = os.path.join(ROOT, "ps1", "harness", "scripts")


def upto(name, marker):
    out = []
    for line in open(os.path.join(CORE, name)):
        out.append(line.rstrip("\n"))
        if line.strip() == marker:
            return out
    raise SystemExit("%s: marker %r not found" % (name, marker))


PROF = os.environ.get("PROF") == "1"   # PROF=1: sample the PC instead


def meas(tag, frames=120):
    if PROF:
        return ["prof", "wait %d" % frames, "profend " + tag]
    return ["fps " + tag, "wait %d" % frames, "fpsend " + tag, "shot " + tag]


PERF = {
    "concert": upto("concert_band.txt", "shot curtain_up") + meas("concert"),
    "island": upto("fp_island.txt", "shot island_day") + meas("island")
    + ["press A", "wait 20"] + meas("townhall", 90),
    "dialogue": upto("story_ch1.txt", "wait 25") + meas("dialogue", 90),
    "title": ["scene TITLE", "wait 90"] + meas("title"),
    "creator": upto("creator.txt", "expect-scene CREATOR") + ["wait 20"]
    + meas("creator"),
    "pet": upto("life_pet.txt", "scene PET") + ["wait 30"] + meas("pet"),
    "exorcism": upto("life_exorcism.txt", "scene EXORCISM -1") + ["wait 40"]
    + meas("exorcism"),
}

for k, v in PERF.items():
    with open(os.path.join(OUT, ("prof_%s.txt" if PROF else "perf_%s.txt") % k), "w") as f:
        f.write("# generated by ps1/harness/mkperf.py\n" + "\n".join(v) + "\n")
print("wrote", len(PERF), "perf scripts")
