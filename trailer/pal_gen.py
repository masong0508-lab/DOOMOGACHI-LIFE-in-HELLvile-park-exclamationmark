#!/usr/bin/env python3
"""Extract the game's real master palette (core/src/palette.c) as 8-bit RGB
so the trailer is painted with exactly the colours the GBA/PS1 builds use."""
import re, sys
src = open(sys.argv[1]).read()
body = src[src.index('doomo_palette[256]'):]
body = body[body.index('{') + 1:body.index('};')]
body = re.sub(r'/\*.*?\*/', '', body, flags=re.S)
vals = []
for m in re.finditer(r'\b(C3|C)\s*\(([^)]*)\)', body):
    nums = [int(x.strip()) for x in m.group(2).split(',')]
    for i in range(0, len(nums), 3):
        vals.append(tuple(nums[i:i + 3]))
if len(vals) != 256:
    sys.exit('expected 256 colours, got %d' % len(vals))
out = ['/* generated by pal_gen.py from core/src/palette.c */',
       'static const unsigned char TK_PAL[256][3] = {']
out += ['    {%d,%d,%d},' % (r & 0xF8, g & 0xF8, b & 0xF8) for r, g, b in vals]
out.append('};')
open(sys.argv[2], 'w').write('\n'.join(out) + '\n')
