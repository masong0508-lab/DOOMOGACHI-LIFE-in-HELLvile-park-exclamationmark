#!/usr/bin/env python3
# doomo-generator
"""Pre-render the GBA Bone HUD digits from the shared font at scale 2."""
import argparse
from pathlib import Path
import re


ROOT = Path(__file__).resolve().parent.parent


def digit_pixels(rows):
    # One pixel of padding above and left of the 5x8 glyph, as in ur_text_big.
    ink = {(1 + 2 * x + dx, 1 + 2 * y + dy)
           for y, row in enumerate(rows) for x, pixel in enumerate(row) if pixel == 'X'
           for dy in range(2) for dx in range(2)}
    edge = {(x + dx, y + dy) for x, y in ink for dy in range(-1, 2) for dx in range(-1, 2)}
    # The Bone outline is the bottom of its ramp, so the shadow uses the same index.
    edge.update((x + 1, y + 3) for x, y in ink)
    light = {(x, y) for x, y in ink if y in (1, 3, 5)}
    for y in range(20):
        yield ','.join('L' if (x, y) in light else 'I' if (x, y) in ink
                       else 'E' if (x, y) in edge else '0' for x in range(12))


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--out-root', type=Path, default=ROOT)
    args = parser.parse_args()
    font = (ROOT / 'core/src/font.c').read_text()
    lines = ['#define BONE_DIGITS(L, I, E) {']
    for digit in range(10):
        glyph = re.search(rf"/\* '{digit}' \*/\s*FONT_G\(([^)]+)\)", font)
        if glyph is None:
            raise ValueError(f'missing digit {digit} in the shared font')
        rows = [row.strip() for row in glyph[1].split(',')]
        if len(rows) != 8 or any(not re.fullmatch('[oX]{5}', row) for row in rows):
            raise ValueError(f'invalid font glyph for {digit}')
        lines.append(f'    {{  /* {digit} */')
        lines.extend(f'        {row},' for row in digit_pixels(rows))
        lines.append('    },')
    out = args.out_root / 'core/gen/bone_digits.inc'
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text('/* Generated by tools/gen_bone_digits.py. */\n' +
                   ' \\\n'.join(lines) + ' \\\n}\n')


if __name__ == '__main__':
    main()
