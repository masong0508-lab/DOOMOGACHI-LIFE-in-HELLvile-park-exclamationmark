#!/usr/bin/env python3
"""speed2.py - speed tour 2 (SA2): one set of scene scripts, measured on the GBA, the PS1 and the Dreamcast.

The scripts are gba/harness/scripts/speed2_*.txt (the GBA harness format; docs/GBA.md "Speed tour 2"). A
measurement window in them is always

    fps start            (the settle before it is not measured)
    wait N               (N logic ticks; a press may come first when the window times a load)
    fps GROUP: NAME      (closes the window: logic ticks/s, drawn fps, work avg / max)

usage:
  speed2.py ps1 SCRIPT [--prof]   the script for ps1/harness/run.py on stdout: each window becomes
                                  `fps TAG` / `wait N` / `fpsend TAG` (the vsyncs-per-frame histogram), or with
                                  --prof `prof` / `wait N` / `profend TAG` (a PC profile, harness/prof.py);
                                  GBA-only lines (sync, profile, vhash, latency, tips, room-parity, ...) dropped
  speed2.py dc SCRIPT             the script for dc/harness/dcrun on stdout: each window becomes
                                  `log speed2: begin N NAME` / `mark-ticks` / `frames 2N` / `expect-ticks 0 99999`
                                  / `log speed2: end NAME` (dcrun prints every tick over 33.3 ms of work)
  speed2.py table LOG [LOG..]     a markdown table of every window of a GBA log (harness --worklog --quiet),
                                  a PS1 tty.log (run.py OUT/tty.log) or a dcrun log; the format is detected

GBA columns: logic ticks/s, drawn fps, work avg / max ms per drawn tick, the presented frames by vblanks
taken (the harness's "gaps" line: 2 = 33 ms, 3 = 50 ms, 4+ = 67 ms and more), frames over 33 ms (3+) and
over 50 ms (4+), the worst frame, and the load: the scene command's own time (the harness's "command 7/8 ...
in N ms": the scene's enter runs there, outside a tick's work) plus the first drawn tick's work after it.
PS1 columns: fps (= logic, one tick per frame), frames by vsyncs (2 = 33 ms, 3 = 50 ms, 4+ = a hitch), the
worst frame, the overlay loads ("ovl: ... in N ms") since the previous window (the PS1's scene-change freeze:
OVL.BIN read from the disc). Dreamcast columns: logic ticks/s over the window (frames 2N video frames), ticks
over 33.3 ms and over 50 ms of work, the worst tick; MISS when a tenth of the window's ticks are over budget.

Verdict (owner, SPEED WAVE 2: a steady 30 with no hitches): MISS when drawn fps < 29.5 or logic < 29.5;
"hitch" when any frame of the window took longer than 33.4 ms (a 50 ms frame) though the average holds;
ok otherwise. Stdlib only.
"""
import re
import statistics as st
import sys

GBA_ONLY = ("sync", "profile", "vhash", "vhash-seq", "latency", "expect-fps", "room-parity", "audio",
            "audio-reset", "expect-audio", "frames", "post", "town-fill", "town-crc", "expect-town-crc",
            "story-fp")


def tag_of(label):
    return re.sub(r"[^A-Za-z0-9]+", "_", label).strip("_").lower()


def windows(lines):
    """yield (kind, payload) over a speed2 script: ('line', text) or ('window', (label, body_lines))"""
    i = 0
    while i < len(lines):
        s = lines[i].strip()
        if s == "fps start":
            body = []
            j = i + 1
            while j < len(lines) and not lines[j].strip().startswith("fps"):
                body.append(lines[j].rstrip("\n"))
                j += 1
            if j >= len(lines):
                raise SystemExit("speed2: 'fps start' at line %d has no closing 'fps LABEL'" % (i + 1))
            label = lines[j].strip()[3:].strip()
            yield "window", (label, body)
            i = j + 1
            continue
        yield "line", lines[i].rstrip("\n")
        i += 1


def conv(path, target, prof=False):
    out = ["# generated by tools/speed2.py %s from %s" % (target, path.split("/")[-1])]
    for kind, p in windows(open(path).readlines()):
        if kind == "line":
            s = p.strip()
            op = s.split()[0] if s and not s.startswith("#") else ""
            if op in GBA_ONLY or s.startswith("expect-log doomo: init"):
                continue
            if target == "ps1" and op == "tips":
                continue      # the PS1 harness has no tips switch (cards stay off, as in the runner)
            if target == "ps1" and op == "release" and len(s.split()) > 1:
                out.extend("up " + b for b in s.split()[1:])
                continue
            if target == "dc" and op == "room-test":
                continue
            out.append(p)
            continue
        label, body = p
        tag = tag_of(label)
        if target == "ps1":
            out.append("prof" if prof else "fps " + tag)
            out.extend(body)
            out.append(("profend " if prof else "fpsend ") + tag)
        else:
            # the window's length in ticks: its waits, and 3 ticks per press (dcrun unsynced: 2 down, 1 up)
            n = sum(int(m.group(1)) for m in (re.match(r"\s*wait\s+(\d+)", b) for b in body) if m)
            n += 3 * sum(1 for b in body if b.strip().startswith("press "))
            out.append("log speed2: begin %d %s" % (n, label))
            out.append("mark-ticks")
            for b in body:
                m = re.match(r"\s*wait\s+(\d+)", b)
                out.append("frames %d" % (2 * int(m.group(1))) if m else b)
            out.append("expect-ticks 0 99999")
            out.append("log speed2: end " + label)
    print("\n".join(out))


def verdict(fps, logic, over33):
    if fps < 29.5 or logic < 29.5:
        return "MISS"
    return "hitch" if over33 else "ok"


def table_gba(path):
    print("| window | logic t/s | drawn fps | work avg ms | work max ms | frames by vblanks | >33 ms | >50 ms "
          "| worst frame ms | load ms | verdict |")
    print("|---|---:|---:|---:|---:|---|---:|---:|---:|---:|---|")
    cur, cmd_ms, first, row = [], None, None, None
    for line in open(path, errors="replace"):
        m = re.match(r"harness: command ([78])\(\S+\) -> \S+ in ([\d.]+) ms", line)
        if m:
            cmd_ms, first = float(m.group(2)), None
            continue
        m = re.match(r"harness: work (\d+) ([\d.]+)", line)
        if m:
            w = float(m.group(2))
            cur.append(w)
            if cmd_ms is not None and first is None:
                first = w
            continue
        m = re.match(r"harness: fps (.+?): ([\d.]+) logic ticks/s, ([\d.]+) drawn frames/s, "
                     r"work avg ([\d.]+) ms max ([\d.]+) ms", line)
        if m:
            row = None
            if m.group(1) == "start":
                cur = []
                continue
            v = cur or [float(m.group(4))]
            row = dict(name=m.group(1), logic=float(m.group(2)), fps=float(m.group(3)), avg=st.mean(v),
                       mx=max(v), load="%.0f" % (cmd_ms + (first or 0)) if cmd_ms is not None else "-")
            cur, cmd_ms, first = [], None, None
            continue
        m = re.match(r"harness: gaps (.+?): vblanks-per-frame histogram(.*?) max (\d+) \(([\d.]+) ms\)", line)
        if m and row and m.group(1) == row["name"]:
            h = {}
            for x in m.group(2).split():
                a, b = x.split(":")
                h[int(a.rstrip("+"))] = int(b)
            o33 = sum(n for g, n in h.items() if g >= 3)
            o50 = sum(n for g, n in h.items() if g >= 4)
            print("| %s | %.1f | %.1f | %.1f | %.1f | %s | %d | %d | %.0f | %s | %s |" % (
                row["name"], row["logic"], row["fps"], row["avg"], row["mx"], m.group(2).strip(), o33, o50,
                float(m.group(4)), row["load"], verdict(row["fps"], row["logic"], o33)))
            row = None


def table_ps1(path):
    print("| window | fps (= logic) | frames by vsyncs | >33 ms | >50 ms | worst ms | overlay load ms | verdict |")
    print("|---|---:|---|---:|---:|---:|---:|---|")
    fps, ovl = {}, []
    for line in open(path, errors="replace"):
        m = re.search(r"ovl: (\S+) \((\d+) KB\) in (\d+) ms", line)
        if m:
            ovl.append(int(m.group(3)))
            continue
        m = re.search(r"fps (\S+) ([\d.]+) \((\d+) frames / (\d+) vsyncs\)", line)
        if m:
            fps[m.group(1)] = float(m.group(2))
            continue
        m = re.search(r"gaps (\S+) vsyncs-per-frame histogram (.*?) max (\d+) \(([\d.]+) ms\)", line)
        if m:
            tag = m.group(1)
            h = {int(a): int(b) for a, b in (x.split(":") for x in m.group(2).split())}
            # the first frame of a window can carry the lockstep resume (one 3): not counted as a hitch
            o33 = sum(n for g, n in h.items() if g >= 3)
            o50 = sum(n for g, n in h.items() if g >= 4)
            if h.get(3) and o33 == 1:
                o33 = 0
            if int(m.group(3)) > max(h or {0: 0}):   # a frame over 200 vsyncs is past the histogram (a save)
                o33, o50 = o33 + 1, o50 + 1
            f = fps.get(tag, 0.0)
            print("| %s | %.2f | %s | %d | %d | %.0f | %s | %s |" % (
                tag, f, m.group(2), o33, o50, float(m.group(4)), "+".join(map(str, ovl)) or "-", verdict(f, f, o33)))
            ovl = []


def table_dc(path):
    print("| window | logic t/s | ticks >33.3 ms | >50 ms | worst ms | verdict |")
    print("|---|---:|---:|---:|---:|---|")
    win, want, works, ticks = None, 1, [], None
    for line in open(path, errors="replace"):
        m = re.match(r"speed2: begin (\d+) (.*)", line.strip())
        if m:
            want, win, works, ticks = max(1, int(m.group(1))), m.group(2), [], None
            continue
        m = re.match(r"work: tick \d+ took (\d+) us", line)
        if m and win:
            works.append(int(m.group(1)) / 1000.0)
            continue
        m = re.match(r"ticks: (\d+) since mark-ticks", line)
        if m and win:
            ticks = int(m.group(1))
            continue
        m = re.match(r"speed2: end (.*)", line.strip())
        if m and win:
            logic = 30.0 * ticks / want if ticks is not None else 0.0
            o33, o50 = len(works), sum(w > 50.0 for w in works)
            print("| %s | %.1f | %d | %d | %s | %s |" % (win, logic, o33, o50,
                                                       "%.1f" % max(works) if works else "<33.3",
                                                       # a tenth of the ticks over budget: the PVR frame
                                                       # is skipped that often (dcrun "game drew")
                                                       "MISS" if o33 * 10 >= want else verdict(logic, logic, o33)))
            win = None


def main():
    a = sys.argv[1:]
    if len(a) >= 2 and a[0] in ("ps1", "dc"):
        conv(a[1], a[0], prof="--prof" in a)
        return
    if len(a) >= 2 and a[0] == "table":
        for p in a[1:]:
            head = open(p, errors="replace").read(1 << 20)
            if "harness: fps" in head or "harness: work" in head:
                table_gba(p)
            elif "vsyncs-per-frame" in head or re.search(r"fps \S+ [\d.]+ \(\d+ frames", head):
                table_ps1(p)
            else:
                table_dc(p)
        return
    print(__doc__)
    sys.exit(2)


if __name__ == "__main__":
    main()
