#!/usr/bin/env python3
# doomo-generator
"""langpack.py - the Spanish UI string table (owner: foundation; contract in
core/include/doomo/lang.h).

Reads core/lang/es.tsv (UTF-8, English<TAB>Spanish, # comments; keys use \\n,
\\\\ and \\xHH escapes) and writes core/gen/lang_ui_es.c: a sorted table of
FNV-1a 32-bit hashes of the English text -> Spanish strings, with the Spanish
letters mapped onto the font bytes 0xA0..0xAF (font.h STR_ES_*).

    python3 tools/langpack.py [--out-root DIR] [--check]
"""
import os
import re
import sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
SRC = os.path.join(ROOT, "core", "lang", "es.tsv")
FONT = {"á": 0xA0, "é": 0xA1, "í": 0xA2, "ó": 0xA3, "ú": 0xA4, "ñ": 0xA5, "ü": 0xA6,
        "Á": 0xA7, "É": 0xA8, "Í": 0xA9, "Ó": 0xAA, "Ú": 0xAB, "Ñ": 0xAC, "Ü": 0xAD,
        "¿": 0xAE, "¡": 0xAF}


def unesc(s):
    out = bytearray()
    i = 0
    while i < len(s):
        c = s[i]
        if c == "\\" and i + 1 < len(s):
            n = s[i + 1]
            if n == "n":
                out.append(10); i += 2; continue
            if n == "\\":
                out.append(92); i += 2; continue
            if n == "x" and i + 3 < len(s) + 1:
                out.append(int(s[i + 2:i + 4], 16)); i += 4; continue
        if c in FONT:
            out.append(FONT[c])
        elif ord(c) < 0x80:
            out.append(ord(c))
        else:
            raise ValueError("character %r is not in the font" % c)
        i += 1
    return bytes(out)


def fnv(b):
    h = 2166136261
    for x in b:
        h = ((h ^ x) * 16777619) & 0xFFFFFFFF
    return h


def load():
    ent = {}
    for n, line in enumerate(open(SRC, encoding="utf-8").read().split("\n"), 1):
        if not line.strip() or line.startswith("#"):
            continue
        f = line.split("\t")
        if len(f) < 2 or not f[1].strip():
            continue
        try:
            k, v = unesc(f[0]), unesc(f[1])
        except ValueError as e:
            raise SystemExit("es.tsv:%d: %s" % (n, e))
        if len(v) > 120:
            raise SystemExit("es.tsv:%d: translation over 120 bytes" % n)
        ent[fnv(k)] = v
    return ent


def build(ent):
    keys = sorted(ent)
    blob = b""
    offs = []
    for k in keys:
        offs.append(len(blob))
        blob += ent[k] + b"\0"
    n = len(keys)
    head = 8 + 4 * n + 2 * n
    head += (-head) & 3
    if head + len(blob) > 0xFFFF + head or head > 0xFFFF:
        raise SystemExit("langpack: table too big")
    data = (0x31474E4C).to_bytes(4, "little") + (n | (head << 16)).to_bytes(4, "little")
    data += b"".join(k.to_bytes(4, "little") for k in keys)
    data += b"".join(o.to_bytes(2, "little") for o in offs)
    data += b"\0" * ((-len(data)) & 3)
    assert len(data) == head
    data += blob
    data += b"\0" * ((-len(data)) & 3)
    return data


LONG = 48   # Spanish strings longer than this go to the second table (lang_help_es.c; not linked on the PS1)


def write(gen, name, sym, ent):
    data = build(ent)
    words = [int.from_bytes(data[i:i + 4], "little") for i in range(0, len(data), 4)]
    with open(os.path.join(gen, name), "w") as f:
        f.write("/* GENERATED by tools/langpack.py from core/lang/es.tsv - do not edit. */\n")
        f.write("/* %d strings, %d bytes (format: doomo/lang.h) */\n" % (words[1] & 0xFFFF, len(data)))
        f.write('#include "doomo/types.h"\n\nconst uint32_t %s[%d] = {\n' % (sym, len(words)))
        for i in range(0, len(words), 6):
            f.write("    " + ", ".join("0x%08Xu" % w for w in words[i:i + 6]) + ",\n")
        f.write("};\n")


def main(argv):
    out = ROOT
    if "--out-root" in argv:
        out = os.path.abspath(argv[argv.index("--out-root") + 1])
    ent = load()
    gen = os.path.join(out, "core", "gen")
    os.makedirs(gen, exist_ok=True)
    short = {k: v for k, v in ent.items() if len(v) <= LONG}
    long_ = {k: v for k, v in ent.items() if len(v) > LONG}
    write(gen, "lang_ui_es.c", "doomo_lang_ui_es", short)
    write(gen, "lang_help_es.c", "doomo_lang_help_es", long_)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
