#!/usr/bin/env python3
# doomo-generator
"""langpack.py - the language registry and the UI string tables (L1; owner:
foundation; the contract is core/include/doomo/lang.h).

Inputs (UTF-8):
  core/lang/languages.tsv     the registry: code, save byte, name, glyph mode,
                              glyph page, plural rule, ready (its header says
                              what each column means)
  core/lang/<code>/ui_*.tsv   English<TAB>translation[<TAB># where], '#'
                              comments; keys and values use \\n, \\\\ and \\xHH
                              escapes; an empty translation = not done yet
                              (the string stays English)

Outputs (core/gen/):
  lang_ids.h                  the LANG_* enum (= the saved option byte)
  lang_registry.c             doomo_lang_info[], doomo_lang_names[] and the
                              table of every language (weak references)
  lang_tab_<id>.c             doomo_lang_<id>: ONE LNG2 table with every UI
                              string of the language (ROM platforms: GBA,
                              native, Dreamcast)
  lang_res_<id>.c             doomo_lang_<id>_res: the PS1's resident table,
                              the strings of ui_main.tsv of at most 48 bytes
                              (the PS1 links no lang_tab_*.c; L6 replaces
                              this with tables read from the disc)

The LNG2 format is in lang.h. It fails on: two different English keys with
the same hash, one English key with two different translations (give one a
context, LCTX in lang.h), a character the font cannot draw, a translation
over 250 bytes, and a registry that breaks its rules (save bytes dense and
in order, at most LANG_SLOTS languages, glyph mode cjk2 not implemented).

    python3 tools/langpack.py [--out-root DIR]   write the files
    python3 tools/langpack.py --check            exit 1 if any file would
                                                 change, or is left over
"""
import os
import sys
import unicodedata

ROOT = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
LANG_DIR = os.path.join(ROOT, "core", "lang")
REGISTRY = os.path.join(LANG_DIR, "languages.tsv")

LANG_SLOTS = 10               # lang.h: the most languages the registry may hold
RESERVED = {8: "ja", 9: "zh"}  # save bytes kept for the CJK languages (later)
MAX_VALUE = 250               # longest translation, bytes
RES_MAX = 48                  # the PS1's resident table: ui_main.tsv strings up to this long
RES_FILE = "ui_main.tsv"
MAGIC = 0x32474E4C            # "LNG2"
HEAD_WORDS = 5                # magic, n, bucket bits | flags, strings offset, size
OFF16 = 0x100                 # header flag: the string offsets are u16

GLYPHS = {"latin": "LANG_GLYPHS_LATIN"}             # cjk2: reserved, not implemented
PLURALS = {"one": "LANG_PLURAL_ONE", "zero_one": "LANG_PLURAL_ZERO_ONE",
           "pl": "LANG_PLURAL_PL", "none": "LANG_PLURAL_NONE"}

# Glyph page 0 (the only page so far): the letters at 0xA0..0xAF (font.h
# STR_ES_*). The glyph pages of L4 replace this with core/lang/charset.tsv.
FONT = {"á": 0xA0, "é": 0xA1, "í": 0xA2, "ó": 0xA3, "ú": 0xA4, "ñ": 0xA5, "ü": 0xA6,
        "Á": 0xA7, "É": 0xA8, "Í": 0xA9, "Ó": 0xAA, "Ú": 0xAB, "Ñ": 0xAC, "Ü": 0xAD,
        "¿": 0xAE, "¡": 0xAF}

GEN_NOTE = "GENERATED by tools/langpack.py"


class Lang:
    def __init__(self, code, save, name, glyphs, page, plural, ready):
        self.code, self.save, self.name = code, save, name
        self.glyphs, self.page, self.plural, self.ready = glyphs, page, plural, ready
        self.id = code.lower().replace("-", "_")
        self.enum = "LANG_" + self.id.upper()


def die(msg):
    raise SystemExit("langpack: " + msg)


def unesc(s, where=None, lenient=False):
    """TSV text -> font bytes. lenient: a letter the font lacks loses its
    accent (names of languages that are not ready yet)."""
    out = bytearray()
    i = 0
    while i < len(s):
        c = s[i]
        if c == "\\" and i + 1 < len(s):
            n = s[i + 1]
            if n == "n":
                out.append(10); i += 2; continue
            if n == "\\":
                out.append(92); i += 2; continue
            if n == "x" and i + 3 < len(s) + 1:
                b = int(s[i + 2:i + 4], 16)
                if b == 0:
                    raise ValueError("\\x00 inside a string")
                out.append(b); i += 4; continue
        if c in FONT:
            out.append(FONT[c])
        elif ord(c) < 0x80:
            out.append(ord(c))
        elif lenient and ord(unicodedata.normalize("NFD", c)[0]) < 0x80:
            out.append(ord(unicodedata.normalize("NFD", c)[0]))
        else:
            raise ValueError("character %r is not in the font" % c)
        i += 1
    return bytes(out)


def fnv(b):
    h = 2166136261
    for x in b:
        h = ((h ^ x) * 16777619) & 0xFFFFFFFF
    return h


def rel(path):
    return os.path.relpath(path, ROOT)


# ---- the registry -----------------------------------------------------------

def load_registry(path=None):
    path = path or REGISTRY
    langs = []
    for n, line in enumerate(open(path, encoding="utf-8").read().split("\n"), 1):
        if not line.strip() or line.startswith("#"):
            continue
        f = line.split("\t")
        where = "%s:%d" % (rel(path), n)
        if len(f) != 7:
            die("%s: want 7 columns (code save name glyphs page plural ready), got %d" % (where, len(f)))
        code, save, name, glyphs, page, plural, ready = f
        try:
            save, page, ready = int(save), int(page), int(ready)
        except ValueError:
            die("%s: save, page and ready are numbers" % where)
        if not code or not all(c.isalnum() or c == "-" for c in code):
            die("%s: bad code %r" % (where, code))
        if save != len(langs):
            die("%s: save byte %d out of order: the registry is append-only, the next "
                "language takes byte %d" % (where, save, len(langs)))
        if save in RESERVED and code != RESERVED[save]:
            die("%s: save byte %d is reserved for %s" % (where, save, RESERVED[save]))
        if save >= LANG_SLOTS:
            die("%s: more than LANG_SLOTS (%d) languages" % (where, LANG_SLOTS))
        if glyphs == "cjk2":
            die("%s: glyph mode cjk2 is reserved and not implemented yet (lang.h, \"LATER: CJK\")" % where)
        if glyphs not in GLYPHS:
            die("%s: glyph mode %r (want one of: %s)" % (where, glyphs, ", ".join(GLYPHS)))
        if plural not in PLURALS:
            die("%s: plural rule %r (want one of: %s)" % (where, plural, ", ".join(PLURALS)))
        if ready not in (0, 1) or not 0 <= page <= 255 or not name:
            die("%s: ready is 0 or 1, page 0..255, name not empty" % where)
        if any(l.code.lower() == code.lower() for l in langs):
            die("%s: code %s twice" % (where, code))
        lang = Lang(code, save, name, glyphs, page, plural, ready)
        try:
            lang.name_bytes = unesc(name, lenient=not ready)
        except ValueError as e:
            die("%s: the name of a ready language must be drawable: %s" % (where, e))
        langs.append(lang)
    if not langs or langs[0].code != "en":
        die("%s: English (en) is the source language and must be save byte 0" % rel(path))
    if os.path.isdir(os.path.join(LANG_DIR, "en")):
        die("core/lang/en/: English is the source text, it has no translation files")
    return langs


# ---- the string tables ------------------------------------------------------

def load_strings(lang):
    """{hash: (value bytes, where, key bytes)} of every ui_*.tsv, and the
    hashes of the resident set (ui_main.tsv, short)."""
    d = os.path.join(LANG_DIR, lang.code)
    ent, res = {}, set()
    if not os.path.isdir(d):
        return ent, res
    for fn in sorted(os.listdir(d)):
        if not (fn.startswith("ui_") and fn.endswith(".tsv")):
            continue
        path = os.path.join(d, fn)
        for n, line in enumerate(open(path, encoding="utf-8").read().split("\n"), 1):
            if not line.strip() or line.startswith("#"):
                continue
            f = line.split("\t")
            if len(f) < 2 or not f[1].strip():
                continue
            where = "%s:%d" % (rel(path), n)
            try:
                k, v = unesc(f[0]), unesc(f[1])
            except ValueError as e:
                die("%s: %s" % (where, e))
            if len(v) > MAX_VALUE:
                die("%s: translation over %d bytes" % (where, MAX_VALUE))
            if k[:1] == b"\x1f" and k.count(b"\x1f") < 2:
                die("%s: a context key is \\x1Fcontext\\x1Ftext (LCTX in lang.h)" % where)
            h = fnv(k)
            if h in ent:
                v0, w0, k0 = ent[h]
                if k0 != k:
                    die("%s: the English hashes like %s's (0x%08X): reword one of them" % (where, w0, h))
                if v0 != v:
                    die("%s: translated differently in %s: one English text has one translation "
                        "everywhere, give one of them a context (LCTX in lang.h)" % (where, w0))
            else:
                ent[h] = (v, where, k)
            if fn == RES_FILE and len(v) <= RES_MAX:
                res.add(h)
    return ent, res


def build(strings):
    """{hash: value bytes} -> the LNG2 table (lang.h), little-endian bytes."""
    keys = sorted(strings)
    n = len(keys)
    bits = 0
    while bits < 8 and (n >> bits) > 16:
        bits += 1
    nb = 1 << bits
    bucket = [0] * (nb + 1)
    for b in range(nb + 1):
        lo = 0
        while lo < n and (keys[lo] >> (32 - bits) if bits else 0) < b:
            lo += 1
        bucket[b] = lo if b < nb else n
    bwords = (nb + 2) // 2
    blob = b""
    rel = []
    for k in keys:
        rel.append(len(blob))
        blob += strings[k] + b"\0"
    # u16 string offsets when the whole table stays under 64 KB (the PS1's
    # resident tables: RAM), u32 otherwise (the full tables, in ROM)
    for wide in (False, True):
        owords = n if wide else (n + 1) // 2
        strings_at = 4 * (HEAD_WORDS + bwords + n + owords)
        if wide or strings_at + len(blob) <= 0xFFFF:
            break
    size = strings_at + len(blob)
    size += (-size) & 3
    flags = bits | (0 if wide else OFF16)
    data = b"".join(w.to_bytes(4, "little") for w in (MAGIC, n, flags, strings_at, size))
    bk = bucket + [0] * (2 * bwords - len(bucket))
    data += b"".join(x.to_bytes(2, "little") for x in bk)
    data += b"".join(k.to_bytes(4, "little") for k in keys)
    data += b"".join((strings_at + r).to_bytes(4 if wide else 2, "little") for r in rel)
    data += b"\0" * ((-len(data)) & 3)
    assert len(data) == strings_at
    data += blob
    data += b"\0" * ((-len(data)) & 3)
    assert len(data) == size
    return data


def c_table(sym, data, what):
    words = [int.from_bytes(data[i:i + 4], "little") for i in range(0, len(data), 4)]
    out = ["/* %s - do not edit. */\n" % GEN_NOTE,
           "/* %s: %d strings, %d bytes (format LNG2: doomo/lang.h) */\n" % (what, words[1], len(data)),
           '#include "doomo/types.h"\n\nconst uint32_t %s[%d] = {\n' % (sym, len(words))]
    for i in range(0, len(words), 6):
        out.append("    " + ", ".join("0x%08Xu" % w for w in words[i:i + 6]) + ",\n")
    out.append("};\n")
    return "".join(out)


def c_str(b):
    """bytes -> a C string literal (font bytes as \\x escapes, split after them)."""
    out, hexed = [], False
    for x in b:
        c = chr(x)
        if x < 0x20 or x >= 0x7F or c in '"\\':
            out.append("\\x%02X" % x)
            hexed = True
            continue
        if hexed and c in "0123456789abcdefABCDEF":
            out.append('" "')
        out.append(c)
        hexed = False
    return '"' + "".join(out) + '"'


def gen_ids(langs):
    w = max(len(l.enum) for l in langs)
    out = ["/* %s from core/lang/languages.tsv - do not edit.\n" % GEN_NOTE,
           " * The values are the byte saved in the island's options (OPT_LANGUAGE):\n",
           " * append-only, never reordered (languages.tsv). */\n",
           "#ifndef DOOMO_GEN_LANG_IDS_H\n#define DOOMO_GEN_LANG_IDS_H\n\n",
           "enum {\n"]
    for l in langs:
        out.append("    %s = %d,%s /* %s */\n" % (l.enum.ljust(w), l.save, "", l.code))
    out.append("    %s = %d\n};\n\n" % ("LANG_COUNT".ljust(w), len(langs)))
    out.append("/* the most languages the registry may ever hold: file directories with\n"
               " * one entry per language reserve this many (8 Latin now, ja and zh later) */\n"
               "#define LANG_SLOTS %d\n\n#endif\n" % LANG_SLOTS)
    return "".join(out)


def gen_registry(langs, tabs, ress):
    out = ["/* %s from core/lang/languages.tsv - do not edit. */\n" % GEN_NOTE,
           '#include "doomo/lang.h"\n\n',
           "/* the tables (lang_tab_<id>.c, lang_res_<id>.c) are weak: a platform may\n"
           " * leave them out (the PS1 links no lang_tab_*.c), and a language with no\n"
           " * translation yet has none */\n"]
    for l in langs:
        if l.id in tabs:
            out.append("extern const uint32_t doomo_lang_%s[] __attribute__((weak));\n" % l.id)
        if l.id in ress:
            out.append("extern const uint32_t doomo_lang_%s_res[] __attribute__((weak));\n" % l.id)
    out.append("\nconst DoomoLangInfo doomo_lang_info[LANG_COUNT] = {\n")
    for l in langs:
        out.append("    /* %s */ { %s, \"%s\", %s, %d, %s, %d },\n" % (
            l.enum, c_str(l.name_bytes), l.code, GLYPHS[l.glyphs], l.page, PLURALS[l.plural], l.ready))
    out.append("};\n\n/* the Options row's values (DoomoOptionInfo.values) */\n"
               "const char *const doomo_lang_names[LANG_COUNT] = {\n")
    for l in langs:
        out.append("    %s,\n" % c_str(l.name_bytes))
    out.append("};\n\n/* each language's UI table; NULL = English / not translated yet */\n"
               "const uint32_t *const doomo_lang_tables[LANG_COUNT] = {\n")
    for l in langs:
        out.append("    %s,\n" % (("doomo_lang_" + l.id) if l.id in tabs else "0"))
    out.append("};\n\n/* the PS1's resident tables (plat_lang_table() in ps1/src/lang_ps1.c) */\n"
               "const uint32_t *const doomo_lang_res_tables[LANG_COUNT] = {\n")
    for l in langs:
        out.append("    %s,\n" % (("doomo_lang_%s_res" % l.id) if l.id in ress else "0"))
    out.append("};\n")
    return "".join(out)


def generate():
    """{repo-relative path: text} of every file langpack writes."""
    langs = load_registry()
    files = {}
    tabs, ress = set(), set()
    for l in langs[1:]:
        ent, res = load_strings(l)
        if ent:
            tabs.add(l.id)
            files["core/gen/lang_tab_%s.c" % l.id] = c_table(
                "doomo_lang_" + l.id, build({h: e[0] for h, e in ent.items()}),
                "%s, every core/lang/%s/ui_*.tsv" % (l.code, l.code))
        if res:
            ress.add(l.id)
            files["core/gen/lang_res_%s.c" % l.id] = c_table(
                "doomo_lang_%s_res" % l.id, build({h: ent[h][0] for h in res}),
                "%s, the PS1's resident strings: core/lang/%s/%s, up to %d bytes" % (
                    l.code, l.code, RES_FILE, RES_MAX))
    files["core/gen/lang_ids.h"] = gen_ids(langs)
    files["core/gen/lang_registry.c"] = gen_registry(langs, tabs, ress)
    return files


def ours(fn):
    return (fn.startswith("lang_tab_") or fn.startswith("lang_res_")) and fn.endswith(".c")


def main(argv):
    files = generate()
    if "--check" in argv:
        bad = 0
        for p, text in sorted(files.items()):
            path = os.path.join(ROOT, p)
            if not os.path.isfile(path) or open(path, encoding="utf-8").read() != text:
                print("langpack: STALE %s" % p); bad = 1
        gen = os.path.join(ROOT, "core", "gen")
        for fn in sorted(os.listdir(gen)):
            if ours(fn) and "core/gen/" + fn not in files:
                print("langpack: LEFT OVER core/gen/%s (no language makes it)" % fn); bad = 1
        if not bad:
            print("langpack: %d files up to date" % len(files))
        return bad
    out = ROOT
    if "--out-root" in argv:
        out = os.path.abspath(argv[argv.index("--out-root") + 1])
    gen = os.path.join(out, "core", "gen")
    os.makedirs(gen, exist_ok=True)
    for fn in os.listdir(gen):
        if ours(fn) and "core/gen/" + fn not in files:
            os.remove(os.path.join(gen, fn))
    for p, text in files.items():
        with open(os.path.join(out, p), "w", encoding="utf-8") as f:
            f.write(text)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
