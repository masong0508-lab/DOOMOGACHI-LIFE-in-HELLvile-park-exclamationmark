#!/usr/bin/env python3
# doomo-generator
"""look_build.py - the gene field table (customisation v2, P0; SPEC 1.3).

Reads core/data/look/fields.txt (one `name bits` per line, in bit order) and writes

    core/gen/gene_table.c   (doomo_gene_field[]: bit position, max value, width)

so the table is no longer hand-written in gene.c. It checks that the names are exactly the
GF_* ids of core/include/doomo/gene.h in the same order, that the widths are 1..11 bits (a field
must fit gene_get's 3-byte window), and that the total is exactly 384 bits.

    python3 tools/look_build.py [--out-root DIR]

INTEGER ONLY, no dates: the output is byte-identical on every machine (make -C core check-gen).
"""
import os
import re
import sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
FIELDS = os.path.join(ROOT, "core", "data", "look", "fields.txt")
GENE_H = os.path.join(ROOT, "core", "include", "doomo", "gene.h")
GENE_BITS = 384


def enum_names():
    """GF_* ids of gene.h in order, voice/persona runs expanded, GF_COUNT excluded."""
    src = open(GENE_H).read()
    a = src.index("enum {\n    GF_BODY")
    b = src.index("GF_COUNT\n};", a)
    body = re.sub(r"/\*.*?\*/", "", src[a:b], flags=re.S).replace("enum {", "")
    names = []
    for t in body.split(","):
        t = t.strip()
        if not t:
            continue
        n = t.split("=")[0].strip()
        if not n.startswith("GF_"):
            raise SystemExit("look_build: unexpected enum entry %r in gene.h" % n)
        n = n[3:].lower()
        if n == "voice0":
            names += ["voice%d" % i for i in range(5)]
        elif n == "persona0":
            names += ["persona%d" % i for i in range(5)]
        else:
            names.append(n)
    return names


def read_fields():
    out = []
    for ln, line in enumerate(open(FIELDS), 1):
        line = line.split("#", 1)[0].strip()
        if not line:
            continue
        parts = line.split()
        if len(parts) != 2 or not parts[1].isdigit():
            raise SystemExit("look_build: fields.txt:%d: expected `name bits`" % ln)
        out.append((parts[0], int(parts[1])))
    return out


def main(argv):
    root = ROOT
    i = 1
    while i < len(argv):
        if argv[i] == "--out-root" and i + 1 < len(argv):
            root = os.path.abspath(argv[i + 1])
            i += 2
        else:
            raise SystemExit("usage: look_build.py [--out-root DIR]")
    fields = read_fields()
    names = enum_names()
    if [n for n, _ in fields] != names:
        for k, (a, b) in enumerate(zip([n for n, _ in fields], names)):
            if a != b:
                raise SystemExit("look_build: field %d is %r in fields.txt but gene.h has %r" % (k, a, b))
        raise SystemExit("look_build: fields.txt has %d fields, gene.h has %d" % (len(fields), len(names)))
    pos = 0
    rows = []
    for n, bits in fields:
        if not 1 <= bits <= 11:
            raise SystemExit("look_build: %s is %d bits (1..11 allowed)" % (n, bits))
        rows.append("    { %d, %d, %d },   /* %s */" % (pos, (1 << bits) - 1, bits, n))
        pos += bits
    if pos != GENE_BITS:
        raise SystemExit("look_build: fields add up to %d bits, the gene is %d" % (pos, GENE_BITS))
    text = ["/* gene_table.c - GENERATED by tools/look_build.py from core/data/look/fields.txt.",
            " * DO NOT EDIT: edit the text file and run `make -C core gen`.",
            " *",
            " * doomo_gene_field[GF_COUNT]: { bit position, max value, width }, %d bits in all. */" % pos,
            '#include "doomo/doomo.h"',
            '#include "doomo/gene.h"',
            "",
            "const DoomoGeneField doomo_gene_field[GF_COUNT] = {"] + rows + ["};", ""]
    outdir = os.path.join(root, "core", "gen")
    os.makedirs(outdir, exist_ok=True)
    with open(os.path.join(outdir, "gene_table.c"), "w") as f:
        f.write("\n".join(text))
    print("look_build: %d fields, %d bits -> core/gen/gene_table.c" % (len(fields), pos))


if __name__ == "__main__":
    main(sys.argv)
