#!/usr/bin/env python3
# doomo-generator
"""mmlc.py - the music compiler (owner: MU1T; docs/design/music/SPEC.md
sec.5, 16, 18).

    python3 tools/mmlc.py [--out-root DIR]

Reads the id locks (core/music/ids/*.lock) and writes
    core/gen/mus_ids.h    the MC_* / STG_* / VINYL_* / MOTIF_* / INST_* ids
    core/gen/mus_data.c   doomo_mus_bank[], the bank (mus_data.h formats)
under DIR (default: the repository root). Deterministic, stdlib only,
integer only (like sfxgen.py).
"""
import argparse
import os
import re
import sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..'))
IDS_DIR = os.path.join(ROOT, 'core', 'music', 'ids')

# id ranges per lock file (sec.16.1)
AREAS = {
    'world':    {'cue': (1, 63)},
    'combat':   {'cue': (64, 111)},
    'activity': {'cue': (112, 175)},
    'common':   {'cue': (176, 199), 'sting': (0, 127), 'vinyl': (0, 255),
                 'motif': (0, 255), 'inst': (0, 255)},
    'classic':  {'cue': (200, 231)},
    'sfx':      {'cue': (232, 255)},
}


class MmlcError(Exception):
    pass


def read_locks():
    """-> list of (name, id, kind, area), validated."""
    out = []
    seen = {}
    for area in sorted(AREAS):
        path = os.path.join(IDS_DIR, area + '.lock')
        if not os.path.exists(path):
            continue
        with open(path, encoding='ascii') as f:
            for ln, line in enumerate(f, 1):
                line = line.split('#', 1)[0].strip()
                if not line:
                    continue
                m = re.match(r'^([A-Z][A-Z0-9_]*)\s*=\s*(\d+)\s+(cue|sting|vinyl|motif|inst)$', line)
                if not m:
                    raise MmlcError('%s.lock:%d: bad line %r' % (area, ln, line))
                name, ident, kind = m.group(1), int(m.group(2)), m.group(3)
                rng = AREAS[area].get(kind)
                if rng is None or not (rng[0] <= ident <= rng[1]):
                    raise MmlcError('%s.lock:%d: %s %d outside the %s range' % (area, ln, kind, ident, area))
                if name in seen:
                    raise MmlcError('%s.lock:%d: %s defined twice' % (area, ln, name))
                for (n2, i2, k2, a2) in out:
                    if k2 == kind and i2 == ident:
                        raise MmlcError('%s.lock:%d: %s id %d already used by %s' % (area, ln, kind, ident, n2))
                seen[name] = 1
                out.append((name, ident, kind, area))
    return out


def emit_ids(locks):
    lines = ['/* mus_ids.h - GENERATED by tools/mmlc.py from core/music/ids/<area>.lock.',
             ' * Do not edit: append to the lock of your area and run `make -C core gen`. */',
             '#ifndef DOOMO_MUS_IDS_H', '#define DOOMO_MUS_IDS_H', '',
             '#define MC_NONE 0']
    last_kind = None
    for name, ident, kind, area in sorted(locks, key=lambda t: ({'cue': 0, 'sting': 1, 'vinyl': 2,
                                                                 'motif': 3, 'inst': 4}[t[2]], t[1], t[0])):
        if kind != last_kind:
            lines.append('/* %s ids */' % kind)
            last_kind = kind
        lines.append('#define %-28s %d' % (name, ident))
    classic = [t for t in locks if t[3] == 'classic']
    if classic:
        lines.append('#define MC_CLASSIC_FIRST %d' % min(t[1] for t in classic))
        lines.append('#define MC_CLASSIC_COUNT %d' % len(classic))
    lines += ['', '#endif', '']
    return '\n'.join(lines)


# ---- the bank -------------------------------------------------------------------
def u16(v):
    return [v & 0xFF, (v >> 8) & 0xFF]


def u32(v):
    return [v & 0xFF, (v >> 8) & 0xFF, (v >> 16) & 0xFF, (v >> 24) & 0xFF]


def fnv1a(data):
    h = 0x811C9DC5
    for b in data:
        h ^= b
        h = (h * 0x01000193) & 0xFFFFFFFF
    return h


def build_bank(cues=(), insts=()):
    """cues: list of (id, kind, flags, blob bytes) ; insts: list of 20-byte rows."""
    hdr_size = 52
    dir_entries = sorted(cues, key=lambda c: (c[1], c[0]))
    n_cues = sum(1 for c in cues if c[1] != 1)
    n_stings = sum(1 for c in cues if c[1] == 1)
    dir_off = hdr_size
    inst_off = dir_off + 8 * len(dir_entries)
    body = []
    off = inst_off + 20 * len(insts)
    for row in insts:
        assert len(row) == 20
    blobs = []
    dir_bytes = []
    for ident, kind, flags, blob in dir_entries:
        while off % 4:
            blobs.append(0)
            off += 1
        dir_bytes += u32(off) + u16(len(blob)) + [ident, (kind << 6) | (flags & 0x3F)]
        blobs += list(blob)
        off += len(blob)
    while off % 4:
        blobs.append(0)
        off += 1
    for row in insts:
        body += list(row)
    rest = dir_bytes + body + blobs
    total = hdr_size + len(rest)
    misc_off = total
    hdr = (u16(0x534D) + u16(1) + u16(n_cues) + u16(n_stings) + u16(len(insts)) + u16(0) * 7 +
           u32(dir_off) + u32(inst_off) + u32(total) + u32(total) + u32(misc_off) + u32(total))
    fnv = fnv1a(rest)
    hdr += u32(fnv)
    assert len(hdr) == hdr_size
    return bytes(hdr + rest)


def emit_bank_c(bank, comment_lines=()):
    out = ['/* mus_data.c - GENERATED by tools/mmlc.py: the music bank (formats in',
           ' * core/include/doomo/mus_data.h). Do not edit; run `make -C core gen`.']
    for c in comment_lines:
        out.append(' * ' + c)
    out += [' */', '#include "doomo/mus_data.h"', '',
            'const uint32_t doomo_mus_bank_size = %du;' % len(bank),
            '__attribute__((aligned(4))) const uint8_t doomo_mus_bank[%d] = {' % len(bank)]
    for i in range(0, len(bank), 16):
        out.append('    ' + ','.join('0x%02x' % b for b in bank[i:i + 16]) + ',')
    out += ['};', '']
    return '\n'.join(out)


def write(out_root, rel, text):
    path = os.path.join(out_root, rel)
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, 'w', encoding='ascii', newline='\n') as f:
        f.write(text)


def main(argv):
    ap = argparse.ArgumentParser(description=__doc__.split('\n')[0])
    ap.add_argument('--out-root', default=ROOT)
    args = ap.parse_args(argv)
    try:
        locks = read_locks()
        write(args.out_root, 'core/gen/mus_ids.h', emit_ids(locks))
        bank = build_bank()
        write(args.out_root, 'core/gen/mus_data.c', emit_bank_c(bank, ['(MU0: empty bank)']))
    except MmlcError as e:
        sys.stderr.write('mmlc: error: %s\n' % e)
        return 1
    return 0


if __name__ == '__main__':
    sys.exit(main(sys.argv[1:]))
