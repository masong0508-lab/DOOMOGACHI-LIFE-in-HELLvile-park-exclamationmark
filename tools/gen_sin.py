#!/usr/bin/env python3
# doomo-generator
"""gen_sin.py - writes core/src/fixmath_table.c (owner: foundation).

doomo_sin_q[i] = round(sin(i * 90deg / 1024) * 65536), i = 0..1024.

The sine is evaluated with exact rational arithmetic (Taylor series on
fractions.Fraction with a rational approximation of pi good to ~60 digits),
so the output is byte-identical on every machine regardless of the host
libm. Usage:

    python3 tools/gen_sin.py [--out-root DIR]

Without --out-root the file is written into the repository.
"""
import os
import sys
from fractions import Fraction

# pi to 60 decimal places (exact rational)
PI = Fraction(
    "3.141592653589793238462643383279502884197169399375105820974944")


def sin_exact(x):
    """Taylor series of sin(x) for 0 <= x <= pi/2; error << 1e-30."""
    term = x
    total = x
    n = 1
    x2 = x * x
    while True:
        term = -term * x2 / ((2 * n) * (2 * n + 1))
        total += term
        n += 1
        if abs(term) < Fraction(1, 10 ** 40):
            break
    return total


def round_half_up(fr):
    # values are non-negative here
    return int(fr + Fraction(1, 2))


def build():
    vals = []
    for i in range(1025):
        x = PI / 2 * Fraction(i, 1024)
        vals.append(round_half_up(sin_exact(x) * 65536))
    assert vals[0] == 0 and vals[1024] == 65536
    out = []
    out.append("/* fixmath_table.c - GENERATED by tools/gen_sin.py. Do not edit.\n"
               " * doomo_sin_q[i] = round(sin(i * 90deg / 1024) * 65536). */\n")
    out.append('#include "doomo/fixmath.h"\n\n')
    out.append("const int32_t doomo_sin_q[1025] = {\n")
    for row in range(0, 1025, 8):
        chunk = vals[row:row + 8]
        out.append("    " + ", ".join("%d" % v for v in chunk) + ",\n")
    out.append("};\n")
    return "".join(out)


def main(argv):
    root = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
    if "--out-root" in argv:
        root = os.path.abspath(argv[argv.index("--out-root") + 1])
    path = os.path.join(root, "core", "src", "fixmath_table.c")
    os.makedirs(os.path.dirname(path), exist_ok=True)
    data = build()
    with open(path, "w", newline="\n") as f:
        f.write(data)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
