#!/usr/bin/env python3
# doomo-generator
"""gen_wheel.py - writes core/gen/mg_wheel_tab.c (owner: minigames; S2-3): the Prize Wheel's ROM tables.

The wheel (core/src/mg_wheel.c) was 151 ms a frame on the GBA. Its geometry only depends on the radius (50 at
240x160, 72 at 320x240), so the parts that cost the most are made here once (PS1: they are in the minigame
overlay, the basename is mg_*):

  * mg_wheel_atan_oct: atan_oct(n, d) (core/src/fixmath.c) for every 0 <= n <= d <= MG_WHEEL_ATAN_MAX, one
    octant. The pie asked fx_atan2 for the angle of each of its ~1,500 colour spans a frame (44% of the GBA
    frame: atan_oct's 64-bit products); mg_wheel_atan2() folds (x, y) into the octant exactly as fx_atan2 does.
    Same integer steps as atan_oct (binary search on sin * den <= cos * num, then the closer of lo / lo + 1)
    over doomo_sin_q as tools/gen_sin.py makes it. test_minigames checks every (x, y) of the disc.
  * mg_wheel_pie_hw_*: the pie's row half-widths isqrt((R + 1)^2 - y^2), once instead of an isqrt a row.
  * mg_wheel_rim_*: the rim, ui_fill_circle(cx + 2, cy + 3, R + 6, shadow), (cx, cy, R + 6, candy),
    (cx, cy, R + 4, gold) under the pie (radius R + 1), as rects relative to the centre: each circle only where
    the next ones leave it visible (a ring), rows with the same piece merged; a rect with w = 0 ends the list. The circles' rows are
    ui_circle_dx's (core/src/ui_raster.c: isqrt((r^2 - y^2) * 4 + 2r) / 2); the GBA's frame hashes and the
    native 320x240 shots are unchanged.

Usage:

    python3 tools/gen_wheel.py [--out-root DIR]
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import gen_sin  # noqa: E402

from math import isqrt  # noqa: E402

MAX = 73          # the biggest pie radius + 1 (mg_wheel.c: 72 + 1); mg.h MG_WHEEL_ATAN_MAX
RADII = (("small", 50), ("big", 72))   # mg.h MG_WHEEL_R_SMALL / MG_WHEEL_R_BIG


def sin_table():
    src = gen_sin.build()
    body = src[src.index("{") + 1:src.index("}")]
    vals = [int(v) for v in body.replace("\n", " ").split(",") if v.strip()]
    assert len(vals) == 1025
    return vals


def atan_oct(sq, num, den):
    lo, hi = 0, 512
    if den == 0:
        return 0
    while lo < hi:
        mid = (lo + hi + 1) >> 1
        if sq[mid] * den <= sq[1024 - mid] * num:
            lo = mid
        else:
            hi = mid - 1
    if lo < 512:
        e0 = sq[1024 - lo] * num - sq[lo] * den
        e1 = sq[lo + 1] * den - sq[1023 - lo] * num
        if e1 < e0:
            lo += 1
    return lo


def circle_dx(r, y):
    """ui_circle_dx (core/src/ui_raster.c) for r > 15 (its table below)"""
    assert r > 15
    return isqrt((r * r - y * y) * 4 + r * 2) // 2


def rim_rects(R):
    """the visible rings of the three rim circles under the pie, as merged (x, y, w, h, layer) runs"""
    rc, rg, R1 = R + 6, R + 4, R + 1
    runs = [None] * 6           # open run per slot: [x, y0, w, h]
    out = []

    def put(slot, layer, x, y, w):
        r = runs[slot]
        if r and w > 0 and r[0] == x and r[2] == w and r[1] + r[3] == y:
            r[3] += 1
            return
        if r:
            out.append((r[0], r[1], r[2], r[3], layer))
        runs[slot] = [x, y, w, 1] if w > 0 else None

    def minus(slot, layer, y, a, b):
        if a is None:
            put(slot, layer, 0, y, 0)
            put(slot + 1, layer, 0, y, 0)
            return
        a0, a1 = a
        if b is None or b[1] < a0 or b[0] > a1:
            put(slot, layer, a0, y, a1 - a0 + 1)
            put(slot + 1, layer, 0, y, 0)
            return
        put(slot, layer, a0, y, b[0] - a0)
        put(slot + 1, layer, b[1] + 1, y, a1 - b[1])

    for y in range(-rc, rc + 4):
        ay, asy = abs(y), abs(y - 3)
        sh = (2 - circle_dx(rc, asy), 2 + circle_dx(rc, asy)) if asy <= rc else None
        ca = (-circle_dx(rc, ay), circle_dx(rc, ay)) if ay <= rc else None
        go = (-circle_dx(rg, ay), circle_dx(rg, ay)) if ay <= rg else None
        pi = (-isqrt(R1 * R1 - ay * ay), isqrt(R1 * R1 - ay * ay)) if ay <= R1 else None
        minus(0, 0, y, sh, ca)
        minus(2, 1, y, ca, go)
        minus(4, 2, y, go, pi)
    for slot in range(6):
        put(slot, slot // 2, 0, 1 << 20, 0)
    for x, y, w, h, layer in out:
        assert -128 <= x <= 127 and -128 <= y <= 127 and 0 < w <= 255 and 0 < h < 64
    return out


def build():
    sq = sin_table()
    vals = []
    for d in range(MAX + 1):
        for n in range(d + 1):
            vals.append(atan_oct(sq, n, d))
    out = ["/* mg_wheel_tab.c - GENERATED by tools/gen_wheel.py (make -C core gen). Do not edit.\n"
           " * S2-3: the Prize Wheel's ROM tables (core/src/mg_wheel.c; tools/gen_wheel.py says how they are made). */\n",
           '#include "../src/mg.h"\n\n',
           "#if MG_WHEEL_ATAN_MAX != %d || MG_WHEEL_R_SMALL != %d || MG_WHEEL_R_BIG != %d\n"
           "#error \"tools/gen_wheel.py is out of step with mg.h\"\n#endif\n\n" % (MAX, RADII[0][1], RADII[1][1]),
           "/* [d * (d + 1) / 2 + n] = atan_oct(n, d), 0 <= n <= d <= %d */\n" % MAX,
           "const uint16_t mg_wheel_atan_oct[%d] = {\n" % len(vals)]
    for row in range(0, len(vals), 16):
        out.append("    " + ", ".join("%d" % v for v in vals[row:row + 16]) + ",\n")
    out.append("};\n")
    for name, R in RADII:
        R1 = R + 1
        hw = [isqrt(R1 * R1 - y * y) for y in range(R1 + 1)]
        out.append("\n/* R = %d: the pie's (radius %d) half-width by |row| */\n" % (R, R1))
        out.append("const uint8_t mg_wheel_pie_hw_%s[%d] = {\n" % (name, len(hw)))
        for row in range(0, len(hw), 16):
            out.append("    " + ", ".join("%d" % v for v in hw[row:row + 16]) + ",\n")
        out.append("};\n")
        rects = rim_rects(R)
        out.append("\n/* R = %d: the rim's %d rects {x, y, w, h | layer << 6} from the centre (layer 0 shadow, 1 candy, 2 gold),"
                   " then { 0 } */\n" % (R, len(rects)))
        out.append("const MgRimRect mg_wheel_rim_%s[%d] = {\n" % (name, len(rects) + 1))
        for i in range(0, len(rects), 6):
            out.append("    " + " ".join("{ %d, %d, %d, %d }," % (x, y, w, h | layer << 6)
                                         for x, y, w, h, layer in rects[i:i + 6]) + "\n")
        out.append("    { 0, 0, 0, 0 }\n};\n")
    return "".join(out)


def main(argv):
    root = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
    if "--out-root" in argv:
        root = os.path.abspath(argv[argv.index("--out-root") + 1])
    path = os.path.join(root, "core", "gen", "mg_wheel_tab.c")
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", newline="\n") as f:
        f.write(build())
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
