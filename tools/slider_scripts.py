#!/usr/bin/env python3
"""slider_scripts.py - CR-SLIDERX: the creator_sliders walk-through at every Slider range (x2, x3, x4).

    python3 -I tools/slider_scripts.py          write the three variants of both scripts
    python3 -I tools/slider_scripts.py --check  exit 1 if one would change (a hand edit, or the base moved)

core/tests/scripts/creator_sliders.txt (the native runner, the PS1 harness, the Dreamcast ui-compare) and
gba/harness/scripts/creator_sliders.txt (the GBA harness) move every build slider across its range and
shoot it (tools/slider_shots_check.py reads the shots). The variants are the same script with one line in
front of the creator: `opt 69 N`, the option "Slider range" (OPT_SLIDER_RANGE, core/include/doomo/town.h:
the next OPT2 id; 0 = x1, 1 = x2, 2 = x3, 3 = x4). The runner, the GBA and PS1 harnesses and dcrun fail
the script when the option does not read back the value, so a moved id cannot pass quietly.
Edit the base scripts and run this tool; never edit a variant.
"""
import os
import re
import sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
OPT_SLIDER_RANGE = 69
BASES = [("core/tests/scripts", r"^scene CREATOR -1$"), ("gba/harness/scripts", r"^push CREATOR -1$")]


def variant(text, rx, mult):
    lines = text.split("\n")
    out, hit = [], 0
    for ln in lines:
        if re.match(rx, ln):
            out.append("opt %d %d" % (OPT_SLIDER_RANGE, mult - 1))
            hit += 1
        out.append(ln)
    if hit != 1:
        raise SystemExit("slider_scripts: expected one '%s' line, found %d" % (rx, hit))
    head = ("# creator_sliders_x%d.txt - GENERATED by tools/slider_scripts.py from creator_sliders.txt (do not edit):\n"
            "# the same walk-through with the cheat Slider range at x%d (opt %d %d), so every slider moves the\n"
            "# preview further. Same shot names, same checker (tools/slider_shots_check.py).\n"
            % (mult, mult, OPT_SLIDER_RANGE, mult - 1))
    return head + "\n".join(out)


def main():
    check = "--check" in sys.argv
    bad = 0
    for d, rx in BASES:
        base = open(os.path.join(ROOT, d, "creator_sliders.txt"), encoding="utf-8").read()
        for mult in (2, 3, 4):
            path = os.path.join(ROOT, d, "creator_sliders_x%d.txt" % mult)
            want = variant(base, rx, mult)
            have = open(path, encoding="utf-8").read() if os.path.exists(path) else None
            if have != want:
                if check:
                    print("slider_scripts: %s is out of date" % os.path.relpath(path, ROOT))
                    bad = 1
                else:
                    open(path, "w", encoding="utf-8").write(want)
    if check and not bad:
        print("slider_scripts: variants up to date")
    return bad


sys.exit(main())
